package ru.stohastika.sklyanka.feature.widgets.open

import androidx.compose.runtime.Composable
import ru.stohastika.sklyanka.domain.pro.ProBenefit

/**
 * Витрина «Склянки Про» как слот экрана настройки виджета (§5.12, Р-67, Р-83).
 *
 * Без доступа нажатие «Добавить виджет» открывает витрину **вместо завершения**, и после
 * покупки установка продолжается без второго жеста. Значит поверхность покупки обязана
 * рисоваться **поверх** экрана настройки, не уводя с него: экран остаётся живым, а по
 * закрытии шторки перечитывает доступ и, если он появился, даёт завершить установку.
 *
 * Поэтому порт отдаёт не намерение, а место в композиции: экран сам решает, когда шторка
 * видна, а `app` рисует ту же `ProSheet`, что и в остальных точках входа (одна поверхность
 * покупки — Р-67). Модуль виджетов при этом не зависит от `feature-pro` (ADR-0007).
 *
 * В бесплатной сборке порт связан с пустой реализацией `app`, поэтому слот ничего не рисует:
 * оплаты в продукте нет, и установка идёт сразу (Р-86, ADR-0016).
 */
interface ProShowcaseTarget {

    /**
     * Слот витрины в композиции вызывающего.
     *
     * @param visible просьба показать витрину; шторка гасится сама (системная «Назад»,
     *   тап по затемнению) и сообщает об этом через [onDismiss].
     * @param benefit пункт-повод: у экрана настройки виджета он один — «Виджеты» (Р-67 п. 2).
     * @param onDismiss шторка закрылась: экран перечитывает доступ и продолжает установку.
     */
    @Composable
    fun Showcase(visible: Boolean, benefit: ProBenefit, onDismiss: () -> Unit)
}
