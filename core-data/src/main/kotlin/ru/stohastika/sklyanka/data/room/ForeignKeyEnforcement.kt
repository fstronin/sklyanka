package ru.stohastika.sklyanka.data.room

import androidx.room.RoomDatabase

/**
 * Явное включение внешних ключей на соединении записи (ИНВ-12, SKL-107).
 *
 * SQLite по умолчанию не исполняет внешние ключи: исполнение поднимает прагма
 * `foreign_keys`, пер-соединением. Измерено на эмуляторе API 35: свежее сырое
 * соединение (помощник без Room) держит её выключенной и висячие ссылки пишет;
 * Room включает её на соединении записи сам — на это умолчание и опирался норматив.
 * Продукт перестаёт опираться: включение записано явным вызовом, зависимость от
 * внутренности библиотеки снята, а сам факт, что включает именно вызов, закреплен
 * парой проверок на сыром соединении.
 *
 * Колбэк `RoomDatabase.Callback` для этого непригоден: платформенный помощник
 * исполняет `onCreate`/`onOpen` внутри транзакции создания базы, где
 * `PRAGMA foreign_keys` — no-op; закреплено проверкой
 * `aPragmaInsideTheCreateTransactionIsNotEffective`. Точка включения — сразу после
 * сборки базы, `withForeignKeysEnabled`, которой пользуются и боевой граф, и каждый
 * тестовый builder: проверка обязана видеть то же открытие, что видит продукт.
 *
 * Пишущие операции Room исполняет на этом соединении; читательские соединения записей
 * не делают, и исполнение на них не нужно. Помощник держит соединение открытым, пока
 * жив `RoomDatabase` — синглтон графа.
 */
fun <T : RoomDatabase> T.withForeignKeysEnabled(): T = apply {
    // Соединение только что открыто вызовом выше и без транзакции: платформенный флаг
    // меняется на лету, что и подтверждает сырая пара проверок.
    openHelper.writableDatabase.setForeignKeyConstraintsEnabled(true)
}
