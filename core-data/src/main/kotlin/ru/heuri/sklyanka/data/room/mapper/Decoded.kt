package ru.heuri.sklyanka.data.room.mapper

/**
 * Результат чтения строки базы.
 *
 * Отдельный тип нужен из-за МГ-6: значение перечисления, записанное более новой сборкой
 * или пришедшей из файла переноса, может быть незнакомо — и это не повод падать.
 * Строка, которую не удалось прочесть, называет поле, а не бросает исключение;
 * решение принимает вызывающий слой, а в журнал уходит событие ENUM_UNKNOWN.
 */
sealed interface Decoded<out T> {

    data class Value<T>(val model: T) : Decoded<T>

    /** @property field имя колонки с непонятым значением — без самого значения и без названия лекарства. */
    data class UnknownEnum(val field: String) : Decoded<Nothing>
}
