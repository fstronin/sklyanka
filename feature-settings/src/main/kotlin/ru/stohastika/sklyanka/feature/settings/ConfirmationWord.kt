package ru.stohastika.sklyanka.feature.settings

/**
 * Совпадает ли введённое слово с образцом (ОВ-7, ОВ-67).
 *
 * Краевые пробелы не считаются вводом, регистр не различается: слово набирают
 * с клавиатуры телефона, и требование точного совпадения наказывало бы за лишний
 * пробел или заглавную букву, а не защищало от случайного нажатия. Внутренние
 * пробелы значимы — «Заменить всё» не равно «Заменить».
 *
 * Образец приходит из ресурсов (НФТ-42): русского текста в этом файле нет. Функция
 * общая для экранов необратимых действий: «Заменить всё» (SKL-39) и удаление профиля
 * (SKL-36) используют одно правило, а не два похожих.
 */
internal fun matchesConfirmationWord(input: String, word: String): Boolean =
    input.trim().equals(word.trim(), ignoreCase = true)
