package ru.stohastika.sklyanka.feature.settings

import ru.stohastika.sklyanka.domain.transfer.AppStamp
import javax.inject.Inject

/**
 * То, что экран настроек **спрашивает** у внешнего мира, а не помнит сам (НФТ-52).
 *
 * Два ответа идут вместе и приходят одним узлом: состояние системы (разрешения и настройки
 * напоминаний) читается заново при каждом показе экрана, а версия берётся из собранного
 * пакета. Ничего из этого экран не хранит «по вере»: подпись, показанная по устаревшему
 * значению, здесь дороже отсутствующей.
 *
 * Отдельным типом, а не двумя параметрами конструктора: у ViewModel набирается достаточно
 * зависимостей, и «сколько у экрана внешних ответов» перестаёт быть вопросом о его подписи.
 * Hilt собирает узел сам (`SettingsSystemStateReader` даёт `app`, версию — `app`).
 */
class SettingsEnvironment @Inject constructor(
    /** Разрешения, настройки напоминаний — то, что меняется мимо приложения (НФТ-52). */
    val system: SettingsSystemStateReader,
    /** Версия собранного пакета: тот же снимок, что уходит в файл переноса. */
    val stamp: AppStamp,
)
