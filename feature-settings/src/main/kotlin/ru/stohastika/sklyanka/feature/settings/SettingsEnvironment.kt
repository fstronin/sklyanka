package ru.stohastika.sklyanka.feature.settings

import ru.stohastika.sklyanka.domain.pro.ObserveProStatusUseCase
import ru.stohastika.sklyanka.domain.transfer.AppStamp
import javax.inject.Inject

/**
 * То, что экран настроек **спрашивает** у внешнего мира, а не помнит сам (НФТ-52, SKL-122).
 *
 * Три ответа идут вместе и приходят одним узлом: состояние системы (разрешения и настройки
 * напоминаний) читается заново при каждом показе экрана, версия берётся из собранного
 * пакета, а состояние подписки — из кэша последнего ответа магазина. Ничего из этого
 * экран не хранит «по вере»: подпись, показанная по устаревшему значению, здесь дороже
 * отсутствующей.
 *
 * Отдельным типом, а не тремя параметрами конструктора: у ViewModel набирается достаточно
 * зависимостей, и «сколько у экрана внешних ответов» перестаёт быть вопросом о его подписи.
 * Hilt собирает узел сам (`SettingsSystemStateReader` даёт `app`, версию и подписку — `app`).
 */
class SettingsEnvironment @Inject constructor(
    /** Разрешения, настройки напоминаний — то, что меняется мимо приложения (НФТ-52). */
    val system: SettingsSystemStateReader,
    /** Версия собранного пакета: тот же снимок, что уходит в файл переноса. */
    val stamp: AppStamp,
    /** Кэш последнего ответа магазина: гейты состава читают его, а не сеть (Р-68 п. 7). */
    val proStatus: ObserveProStatusUseCase,
)
