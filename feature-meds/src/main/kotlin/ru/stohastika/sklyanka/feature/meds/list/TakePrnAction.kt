package ru.stohastika.sklyanka.feature.meds.list

/**
 * Приём «по потребности», запускаемый кнопкой «Принять» в карточке списка (ПР-4).
 *
 * Порт, а не собственная реализация. Создание такого приёма — предметная операция
 * задачи SKL-07 («отметка приёма»): проверка суточного лимита и вставка записи обязаны
 * идти одной транзакцией, иначе два быстрых нажатия подряд дают четвёртый приём при
 * ограничении три. Списку лекарств об этом знать нечего — он знает только, что действие
 * есть и когда оно недоступно.
 *
 * Реализация подставляется снаружи: тот же сценарий вызывает кнопка «Принять» на экране
 * «Сегодня», и двух разных реализаций одного действия быть не должно.
 */
fun interface TakePrnAction {

    suspend operator fun invoke(medicationId: String)
}
