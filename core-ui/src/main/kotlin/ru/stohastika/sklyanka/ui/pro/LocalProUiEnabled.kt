package ru.stohastika.sklyanka.ui.pro

import androidx.compose.runtime.staticCompositionLocalOf

/**
 * Виден ли в интерфейсе платный контур: метки «Про» и строки, ведущие в покупку.
 *
 * По умолчанию `false`. Значение `true` подставляет только платный вариант сборки —
 * в нём метки и входы покупки остаются живыми (Р-86, ADR-0016). Поставляется бесплатная
 * сборка, и в ней ни метки «Про», ни строки «Склянка Про» на экранах нет.
 *
 * Флаг **не** решает о доступе к функциям: в бесплатной сборке доступ всегда есть
 * (кэш подписки возвращает активный доступ), поэтому гейты состава проходят без
 * изменений, а сам флаг прячет только признаки платности (§5.9, §5.17).
 */
val LocalProUiEnabled = staticCompositionLocalOf { false }
