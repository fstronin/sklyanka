package ru.stohastika.sklyanka.ui.token

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Отступы. Девять шагов из `docs/norm/06-design.md` §3.2.
 *
 * Шаги 3, 5, 6, 7 и 13 dp в макетах встречаются, но приходятся на композицию иконок
 * и мелкой графики; в шкалу они не выносятся и округляются к ближайшему шагу.
 */
object SklyankaSpacing {

    /**
     * Отсутствие отступа — явный ноль рядом со шкалой, а не её шаг.
     *
     * Нужен там, где нулевое поле или зазор — решение, а не забытый отступ: однострочное
     * поле ввода не несёт вертикального поля, светлые формы кнопок — минимального воздуха
     * до рамки, тёмная — бокового поля подписи. Литерал `0.dp` по месту запрещён (НФТ-47).
     * В [all] не входит: шкала остаётся девятью шагами спецификации.
     */
    val None: Dp = 0.dp

    /** Разрыв между названием и вторичной строкой внутри карточки. */
    val Hair: Dp = 2.dp

    /** Внутренний зазор сегмент-переключателя, зазор в индикаторе шагов. */
    val Micro: Dp = 4.dp

    /** Между чипами, между меткой и полем, между строками времени. */
    val Small: Dp = 8.dp

    /** Между карточками в группе, между заголовком времени и списком. */
    val Default: Dp = 10.dp

    /** Внутри карточки между иконкой и текстом; между кнопками в ряду. */
    val Medium: Dp = 12.dp

    /** Внутренний отступ карточки приёма, зазор между карточками разделов. */
    val Large: Dp = 14.dp

    /** Внутренний отступ карточки раздела, между иконкой и текстом в шапке лекарства. */
    val Block: Dp = 16.dp

    /** Между группами времени на экране «Сегодня»; боковое поле экрана. */
    val Section: Dp = 20.dp

    /** Боковое поле онбординга и напоминания, нижнее поле панели навигации. */
    val Screen: Dp = 24.dp

    /** Боковое поле пустого состояния: текст там намеренно сужен (§4.8). */
    val EmptyStateSide: Dp = 44.dp

    /** Все шаги — опора теста шкалы. */
    val all: List<Dp>
        get() = listOf(Hair, Micro, Small, Default, Medium, Large, Block, Section, Screen)
}
