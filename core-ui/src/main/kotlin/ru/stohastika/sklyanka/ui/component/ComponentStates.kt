package ru.stohastika.sklyanka.ui.component

import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.runtime.Immutable
import androidx.compose.ui.unit.Dp
import ru.stohastika.sklyanka.ui.token.SklyankaShapes
import ru.stohastika.sklyanka.ui.token.SklyankaSizes

/**
 * Состояния компонентов каталога (`docs/spec/08-design-system.md` §4).
 *
 * Все перечисления собраны в одном файле намеренно: это словарь состояний системы,
 * по которому строится и каталог, и превью, и проверка «компонент существует во
 * всех своих состояниях» (критерий 10). Разложенные по файлам компонентов, они
 * перестают читаться списком, и пропуск состояния становится незаметным.
 *
 * Перечисление, а не набор булевых флагов: три флага дают восемь сочетаний, из
 * которых осмысленны четыре, и позволяют собрать «принято и пропущено
 * одновременно» (TDD §6.1).
 */

/**
 * Состояния карточки приёма (§4.1).
 *
 * Шестое состояние таблицы — «чужой профиль» — состоянием карточки не является:
 * граница и акцент там пересчитываются темой, а подпись «отметили вы» приходит
 * параметром [IntakeCard]. Иначе пришлось бы завести «принято в чужом профиле» и
 * «ожидается в чужом профиле» как разные состояния.
 */
enum class IntakeCardState { Pending, DueNow, Taken, Missed, AsNeeded }

/**
 * Подписи карточки приёма.
 *
 * Готовые строки, а не доменная модель: `core-ui` не знает ни про `Intake`, ни про
 * `IntakeStatus`, иначе появление нового статуса (ОВ-12) стало бы правкой
 * дизайн-системы, а не экрана (TDD §6.1). Одним значением, а не тремя параметрами:
 * три строки подряд в подписи компонента путают местами на первом же вызове.
 */
@Immutable
data class IntakeCardLabels(val medication: String, val dose: String, val time: String = "")

/** Действия карточки приёма одним значением: иначе подпись компонента разрастается. */
@Immutable
data class IntakeCardActions(val onMark: (() -> Unit)? = null, val onSkip: (() -> Unit)? = null)

/**
 * Ссылка в строке подписи полосы прогресса: видимое слово и невидимо расширенная
 * цель нажатия (ОВ-84).
 *
 * Готовая строка и готовое действие, как у [IntakeCardActions]: `core-ui` не знает
 * ни про историю, ни про маршруты — куда ведёт ссылка, решает экран.
 */
@Immutable
data class ProgressAction(val label: String, val onClick: () -> Unit)

/**
 * Подписи шапки экрана.
 *
 * [overline] — дата над заголовком корневого экрана. Имени профиля здесь нет намеренно:
 * оно приходит из оформления профиля (`ProfileChrome`, ПРФ-12), а не параметром. Параметр
 * означал бы одиннадцать мест, где индикацию чужого профиля можно забыть, причём забыть
 * незаметно — экран выглядит нормально, просто защита пропала (ПРФ-10).
 *
 * По макетам надстрочная строка и надпись «Профиль · Имя» взаимно исключают друг друга:
 * в контексте чужого профиля место занято именем профиля (ПРФ-11).
 */
@Immutable
data class ScreenHeaderLabels(val title: String, val overline: String? = null)

/**
 * Состояния кнопки (§4.3).
 *
 * [Pressed] задаётся снаружи только каталогом и превью — в приложении оно приходит
 * от настоящего нажатия. Состояние, которого нет в каталоге, не существует, и
 * показать его иначе нечем.
 */
enum class ButtonState {
    Normal,
    Pressed,
    Disabled,
    Busy,
    ;

    /** Кнопка отзывается на нажатие только в обычном состоянии. */
    val isInteractive: Boolean get() = this == Normal

    /** «Недоступна» и «в работе» выглядят одинаково: действие сейчас невозможно. */
    val isActive: Boolean get() = this == Normal || this == Pressed
}

/**
 * Виды основной кнопки (§4.3).
 *
 * [Primary] — обычное главное действие; [Danger] — необратимое: «Заменить всё»,
 * «Удалить профиль» (ОВ-38, ОВ-67). Вид перечислением, а не булевым флагом: у кнопки
 * уже есть [ButtonState], и второй флаг дал бы «опасная, но недоступная» как сочетание
 * двух значений, которое перечисление не собирает по построению.
 *
 * Фон [Danger] не подменяется цветом профиля: опасность обязана читаться одинаково
 * в любом профиле, иначе она станет цветом профиля (ОВ-67).
 *
 * Имена значений выбраны по словарю дизайн-системы («основная», «опасная»): словарь
 * состояний читается проверкой эталонов SKL-24, и `Primary` — уже существующая пара
 * снимков `button-primary-*`.
 */
enum class PrimaryButtonKind { Primary, Danger }

/**
 * Виды тихой кнопки (§4.3, ОВ-124).
 *
 * [Accent] — обычное действие в шапке и внутри строк; [Muted] — «Отмена» рядом
 * с главным действием; [Danger] — удаление: текст цветом опасности, который в чужом
 * профиле не подменяется цветом профиля (ОВ-67). Вид перечислением, а не двумя флагами,
 * по той же причине, что у [PrimaryButtonKind]: «приглушённая и опасная» — сочетание,
 * которого в дизайн-системе нет.
 */
enum class QuietButtonKind { Accent, Muted, Danger }

/**
 * Форма кнопки: карточная (внутри карточек) и экранная (§4.3, ОВ-90).
 *
 * Габариты берут существующие токены `SklyankaSizes`/`SklyankaShapes` — новых
 * размеров и радиусов не вводится (НФТ-47). Одну форму делят оба вида кнопок в ряду:
 * иначе «Принято» и «Пропустить» разной высоты читаются как кривая вёрстка.
 */
enum class ButtonForm(val height: Dp, val shape: RoundedCornerShape) {
    Card(SklyankaSizes.SecondaryButtonHeight, SklyankaShapes.Button),
    Screen(SklyankaSizes.PrimaryButtonHeight, SklyankaShapes.Large),
}

/**
 * Состояния чипа (§4.2).
 *
 * [Info] не нажимается вовсе: это метка, а не выбор. Разделение состоянием, а не
 * булевым `clickable`, не даёт собрать «информационный, но нажимаемый» чип —
 * элемент, который выглядит меткой и срабатывает на касание.
 */
enum class ChipState { Info, Unselected, Selected, Disabled }

/**
 * Состояния поля ввода (§4.4).
 *
 * [Error] добавлено задачей SKL-09 и является расширением дизайн-системы, а не
 * вольностью экрана. Макетов ошибки не существует ни одного, а правил валидации формы
 * лекарства девять, и каждое обязано указать человеку на поле. Поэтому состояние
 * заведено здесь — по образцу соседних, одним значением перечисления, — а не собрано
 * на экране рамкой по месту: собранное на экране, оно разойдётся со вторым экраном,
 * которому ошибка понадобится, и никогда не попадёт в каталог.
 *
 * Оформление минимальное и производное от уже принятых решений: граница ролью
 * `danger` толщиной `BorderAccent` (так же, как фокус отличается от покоя) и пояснение
 * под полем стилем `CaptionSmall`. Роль `danger` выбрана потому, что опасность обязана
 * читаться одинаково и в чужом профиле, где акцент подменяется цветом профиля.
 * Окончательный вид — за дизайном (ОВ-16).
 */
enum class TextFieldState { Empty, Filled, Focused, Disabled, Error }

/** Состояния переключателя (§4.5). */
enum class SwitchState { On, Off, Disabled }

/** Виды баннера (§4.6). */
enum class BannerKind {
    /** Остаток упаковки, непройденное разрешение. */
    Warning,

    /** «Это не ваши приёмы» — на подкрашенной шапке чужого профиля. */
    Profile,

    /** Пояснение в настройках и переносе данных. */
    Neutral,
}

/** Назначения полосы прогресса (§4.7). */
enum class ProgressPurpose {
    Day,
    Course,
    Stock,

    /** Критический остаток: тот же остаток, но цветом предупреждения. */
    StockCritical,
}

/** Виды шапки экрана (§4.9). */
enum class ScreenHeaderKind {
    /** Корневая: дата, заголовок экрана, действия справа. */
    Root,

    /** Вложенная: стрелка «Назад» слева, тихое действие справа. */
    Nested,

    /** Модальная: «Отмена» слева, название по центру, «Готово» справа. */
    Modal,
}
