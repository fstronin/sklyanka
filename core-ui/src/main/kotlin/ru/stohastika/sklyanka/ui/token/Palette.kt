package ru.stohastika.sklyanka.ui.token

import androidx.compose.ui.graphics.Color

/**
 * Сырые значения цвета — нижний уровень дизайн-системы.
 *
 * Сюда попадает ровно то, что `docs/v2/12-design.md` §1.1 и §1.2 помечает
 * словом «токен». Всё, что помечено «производный» или «вне сборки», здесь
 * отсутствует намеренно: производный цвет вычисляется из токена ([tint]), а цвет
 * макетной обвязки в приложении не нужен вовсе.
 *
 * Палитра `internal`: снаружи модуля виден только верхний уровень — роли
 * [SklyankaColors], которые тема подменяет под профиль и под тёмную среду. Экран,
 * добравшийся до сырого значения, снова получил бы неподменяемый цвет — то есть
 * ровно ту ошибку, от которой защищает НФТ-47.
 */
internal object Palette {

    // --- §1.1, токены спеки ---

    /** Фон всех светлых экранов. */
    val Background = Color(0xFFFBF7F1)

    /** Карточки, поля ввода, нижняя панель. */
    val Surface = Color(0xFFFFFFFF)

    /** Основной текст и заголовки. */
    val Text = Color(0xFF241F1B)

    /** Вторичные строки карточек и подписи разделов. */
    val TextMuted = Color(0xFF5F564D)

    /** Разделители между блоками и граница поля ввода. */
    val Line = Color(0xFFE6DED2)

    /** Основная кнопка, прогресс, выбранный чип, метка «Сейчас». */
    val Accent = Color(0xFFB4512F)

    /** Тот же акцент в тёмной среде: светлый на тёмном фоне даёт всего 3,59 (§6.1). */
    val AccentOnDark = Color(0xFFC9633D)

    /** Подложка выбранного чипа и фон баннера остатка. */
    val AccentSoft = Color(0xFFF6E7DF)

    /** Время отметки, галочка, аватар владельца. */
    val Taken = Color(0xFF1F5F6B)

    /** Плашка иконки принятого лекарства. */
    val TakenSoft = Color(0xFFE2EEF0)

    /** Фон карточки архивного курса. */
    val ArchiveBackground = Color(0xFFF6F1E8)

    /**
     * Фон тёмной среды.
     *
     * Единственное место со спорным значением (ОВ-9): `design/SPEC-original.md` §9
     * задаёт `#191512`, макет `Reminder.dc.html` использует `#241F1B`. До ответа
     * дизайна держим значение спеки — когда вопрос закроется, правится одна строка,
     * а не восемь мест в коде.
     */
    val DarkBackground = Color(0xFF191512)

    /** Цвет чужого профиля из §9; он же первый цвет закрытой палитры профилей. */
    val ProfileForeign = Color(0xFF8F3E23)

    // --- §1.2, токены, добавленные по итогам аудита макетов ---

    /** Третий уровень текста и «тихие» иконки. Не сводится к [TextMuted]: 3,56 против 6,73. */
    val TextTertiary = Color(0xFF8C8177)

    /** Недоступный текст. Контраст 2,69 — применим только там, где смысл несёт сосед (§6.1). */
    val TextDisabled = Color(0xFFA79C90)

    /** Линия на белой поверхности: [Line] рассчитана на фон, на поверхности она темнит. */
    val LineOnSurface = Color(0xFFEFE7DB)

    /** Граница второстепенной кнопки: заметнее [Line], иначе кнопка не читается как кнопка. */
    val LineInteractive = Color(0xFFD9CDBD)

    /** Неинформативная графика: шеврон, декоративная стрелка. Осознанно не проходит AA. */
    val IconFaint = Color(0xFFB0A597)

    /** Нейтральная плашка иконки и фон чипа времени. */
    val NeutralSoft = Color(0xFFF3EDE3)

    /** Дорожка полосы прогресса: темнее фона и светлее линии. */
    val ProgressTrack = Color(0xFFEDE3D6)

    /** Дорожка выключенного переключателя: из [Line] она не читается. */
    val SwitchOff = Color(0xFFDCD1C2)

    /** Рамка карточки, требующей действия: [Accent] для рамки слишком крикливый. */
    val AccentBorder = Color(0xFFE7CEC2)

    /** Текст на мягком акценте: [Accent] на [AccentSoft] даёт 1,3 и нечитаем. */
    val OnAccentSoft = Color(0xFF6B3620)

    /** Статус «пропущено». Семантика не утверждена (ОВ-12), роль заведена. */
    val Missed = Color(0xFFC9BFB1)

    /** Статус «принято частично». Семантика не утверждена (ОВ-12), роль заведена. */
    val TakenPartial = Color(0xFF6E9FA8)

    // --- Закрытая палитра цветов профиля (§1.2, ПРФ-15) ---

    /** Цвет профиля из §9. */
    val ProfileTerracotta = ProfileForeign
    val ProfileTeal = Color(0xFF1F5F6B)
    val ProfileOlive = Color(0xFF7A5B2E)
    val ProfilePlum = Color(0xFF6B4A6B)

    // --- Тёмная среда (§5): переопределяются ровно восемь ролей ---

    /** Приподнятая поверхность в тёмной среде: [Surface] там неприменим. */
    val SurfaceDark = Color(0xFF342D26)

    /** Линия в тёмной среде. */
    val LineDark = Color(0xFF4A4139)

    /**
     * Текст второстепенной кнопки на тёмном (§1.2).
     *
     * Это не основной текст тёмной среды: им по §5 становится [Background] —
     * «фон и текст меняются местами». Применяет этот токен полноэкранное
     * напоминание, SKL-13.
     */
    val TextOnDark = Color(0xFFE5DCD1)

    /** Приглушённый текст на тёмном. */
    val TextMutedOnDark = Color(0xFFC9BFB1)

    /** Третий уровень текста на тёмном. */
    val TextTertiaryOnDark = Color(0xFFA79C90)

    /** Мягкий акцент в тёмной среде: обводка иконки лекарства на напоминании. */
    val AccentSoftOnDark = Color(0xFFE8B9A5)

    /** Прозрачность — отсутствие цвета, а не цвет: полоса профиля у владельца. */
    val Transparent = Color.Transparent
}
