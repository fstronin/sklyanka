package ru.stohastika.sklyanka.ui.token

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Габариты компонентов из `docs/v2/12-design.md` §3.3 и §4.
 *
 * Зачем отдельный объект рядом с [SklyankaSpacing]. Отступ и габарит — разные вещи:
 * отступ берётся из девятишаговой шкалы, а высота кнопки, толщина рамки и размер
 * бегунка переключателя заданы каталогом компонентов поимённо и в шкалу не ложатся.
 * Заводить их «по месту» нельзя — литерал размера вне пакета токенов валит сборку
 * (НФТ-47), и это правильно: тогда высота основной кнопки разойдётся по пяти экранам.
 */
object SklyankaSizes {

    /**
     * Минимальная цель нажатия (§3.3, НФТ-29).
     *
     * Ровно 44 dp, а не 48 dp из Material: система задаёт 44, и расхождение в четыре
     * точки на плотной вёрстке макета заметно.
     */
    val MinTouchTarget: Dp = 44.dp

    /** Полоса профиля вверху экрана (§4.10). */
    val ProfileStripeHeight: Dp = 6.dp

    /** Плашка иконки лекарства в карточке приёма и её содержимое (§4.1). */
    val IconPlate: Dp = 40.dp
    val IconPlateGlyph: Dp = 20.dp

    /** Круглая кнопка отметки в карточке приёма (§4.1). */
    val MarkButton: Dp = 44.dp
    val MarkButtonGlyph: Dp = 18.dp

    /** Высота основной кнопки (§4.3: 52–54 dp). */
    val PrimaryButtonHeight: Dp = 52.dp

    /** Высота второстепенной кнопки и кнопки внутри карточки (§4.3: 44–52 dp). */
    val SecondaryButtonHeight: Dp = 44.dp

    /** Высота основной кнопки тёмной формы — полный рост макета напоминания (§5.1, ОВ-146). */
    val DarkPrimaryButtonHeight: Dp = 58.dp

    /** Высота второстепенной кнопки тёмной формы (§5.1, ОВ-146). */
    val DarkSecondaryButtonHeight: Dp = 54.dp

    /**
     * Ведущая галочка основной кнопки тёмного напоминания и толщина её штриха (§5.1, ОВ-146).
     *
     * Габарит именной, а не ступень: макет задаёт ровно 20 px со штрихом 2,4, и общая
     * доля штриха 0,13 дала бы другой рисунок (НФТ-47).
     */
    val DarkButtonGlyph: Dp = 20.dp
    val DarkButtonGlyphStroke: Dp = 2.4.dp

    /** Боковое поле подписи кнопки: светлые формы — 28, тёмная — без поля (§5.1, ОВ-146). */
    val ButtonPadding: Dp = 28.dp
    val QuietButtonPadding: Dp = 8.dp

    /** Высота чипа-кнопки — не меньше цели нажатия (§4.2). */
    val ChipHeight: Dp = 44.dp
    val ChipPadding: Dp = 14.dp

    /** Поле ввода (§4.4): обычное и компактное числовое. */
    val FieldHeight: Dp = 50.dp
    val CompactFieldHeight: Dp = 42.dp
    val FieldPadding: Dp = 14.dp

    /**
     * Наименьшая высота многострочного поля (§4.4, макет `Diagnostics.dc.html`).
     *
     * Многострочный режим растёт по содержимому, но ниже 112 dp не опускается: иначе
     * поле для комментария читается как однострочное и человек не понимает, что можно
     * писать развёрнуто.
     */
    val MultilineFieldMinHeight: Dp = 112.dp

    /**
     * Внутреннее вертикальное поле многострочного поля (ОВ-142).
     *
     * Именной габарит, а не шаг шкалы: макет задаёт `.field-box{padding:13px 14px}`,
     * и 13 dp в девятишаговую шкалу не ложится (НФТ-47).
     */
    val MultilineFieldPaddingVertical: Dp = 13.dp

    /**
     * Поля плашки-объяснения на полотне шторки (ОВ-142).
     *
     * Именные габариты: макет задаёт `.sheet-body .plate{padding:13px 15px}`, а 13 и 15 dp
     * в девятишаговую шкалу не ложатся (НФТ-47).
     */
    val ExplanationPlatePaddingVertical: Dp = 13.dp
    val ExplanationPlatePaddingHorizontal: Dp = 15.dp

    /**
     * Плитка-маркер строки «Разрешений» 40×40 (AC-10, макет `Diagnostics.dc.html`).
     *
     * Именной габарит: плитка — единственное место, где нейтральный глиф стоит
     * самостоятельной плашкой, и подбирать её «примерно» на экране нельзя (НФТ-47).
     */
    val MarkerTile: Dp = 40.dp

    /**
     * Колонка действия строки «Разрешений» и её футера (AC-11, §4.11).
     *
     * Фиксированная ширина — под подпись «Исправить» при 100 % с запасом: подписи
     * выравниваются по левому краю колонки, шевроны — по правому, поэтому начала подписей
     * не «плывут» от строки к строке. Значение — 100 px из макета.
     */
    val PermissionActionColumn: Dp = 100.dp

    /**
     * Верхнее поле подписи группы «Разрешений» (AC-8, макет `Diagnostics.dc.html`).
     *
     * Именной габарит: макет задаёт `.pgroup{padding:13px 0 3px}`, и 13 dp в девятишаговую
     * шкалу не ложится (НФТ-47). Нижнее поле группы — [PermissionGroupPaddingBottom],
     * собственное поле подписи — [SklyankaSpacing.Hair].
     */
    val PermissionGroupLabelPaddingTop: Dp = 13.dp

    /**
     * Нижнее поле группы «Разрешений» — 3 dp из `.pgroup{padding:13px 0 3px}`.
     *
     * Стоит на группе, а не на подписи: в макете оно ниже последней строки группы и
     * отделяет её от следующей группы или от строки «Остальные разрешения выданы».
     */
    val PermissionGroupPaddingBottom: Dp = 3.dp

    /** Переключатель (§4.5): габарит 52×32, бегунок 26. */
    val SwitchWidth: Dp = 52.dp
    val SwitchHeight: Dp = 32.dp
    val SwitchThumb: Dp = 26.dp
    val SwitchPadding: Dp = 3.dp

    /**
     * Наименьшая ширина текстовой колонки в ряду «иконка — текст — действие».
     *
     * Ниже неё ряд перестраивается и действие уезжает под текст (§6.3). Порог задан
     * шириной, а не масштабом шрифта: порог по `fontScale` врёт при длинном названии
     * лекарства — оно переносит строку и на обычном масштабе.
     */
    val MinTextColumn: Dp = 96.dp

    /** Полоса прогресса (§4.7): высота 7–8 dp. */
    val ProgressHeight: Dp = 8.dp

    /** Знак в пустом состоянии, плоская редукция (§4.8). */
    val EmptyStateMark: Dp = 92.dp

    // --- Фирменный блок: заставка и логотип с названием (SKL-21) ---

    /** Знак на заставке (`design/screens/Splash.dc.html`). */
    val SplashMark: Dp = 170.dp

    /** Знак в логотипе с названием (`design/screens/SklyankaLockup.dc.html`). */
    val LockupMark: Dp = 128.dp

    /** Зазор между знаком и текстовым блоком: 34 в обоих макетах фирменного блока. */
    val BrandGap: Dp = 34.dp

    /** Отступ «Stohastika» от нижнего края заставки. */
    val SplashVendorBottom: Dp = 46.dp

    // --- Экраны лекарств: список и форма (SKL-09, макеты Meds.dc.html и AddMed.dc.html) ---

    /**
     * Круглая кнопка добавления лекарства и её знак (`Meds.dc.html`).
     *
     * Габарит именной, а не из шкалы отступов: плавающая кнопка — единственный элемент
     * продукта такого размера, и подбирать его «примерно 60» на экране нельзя (НФТ-47).
     */
    val AddButton: Dp = 60.dp
    val AddButtonGlyph: Dp = 26.dp

    /** Шеврон перехода в карточке списка (`Meds.dc.html`). */
    val Chevron: Dp = 16.dp

    /** Плитка формы выпуска в сетке 3×2 и её значок (`AddMed.dc.html`, ОВ-94). */
    val FormTile: Dp = 80.dp
    val FormTileGlyph: Dp = 30.dp

    /** Кнопка вида таблетки и силуэт на ней (`AddMed.dc.html`). */
    val ShapeButton: Dp = 60.dp
    val ShapeGlyph: Dp = 30.dp

    /** Плитка и силуэт блока-превью выбора (§4.16, ОВ-94). */
    val PreviewTile: Dp = 72.dp
    val PreviewGlyph: Dp = 38.dp

    /** Высота вкладки сегментного переключателя «Активные · 5 / Архив · 12». */
    val SegmentHeight: Dp = 38.dp

    /** Поле количества дозы (120) и поле остатка в упаковке (54) — ширины из макета формы. */
    val DoseField: Dp = 120.dp
    val StockField: Dp = 54.dp

    /** Наименьшая ширина числа между кнопками «Уменьшить» и «Увеличить»: чтобы «10» не дёргало ряд. */
    val CounterValue: Dp = 22.dp

    // --- Карточка лекарства и недельная полоса приёмов (SKL-10, макет MedCard.dc.html) ---

    /** Плитка значка в титуле карточки лекарства и её значок (§4.15: 62 и 34). */
    val MedCardPlate: Dp = 62.dp
    val MedCardPlateGlyph: Dp = 34.dp

    /** Плитка значка в строке списка лекарств и её силуэт (§4.15: 42×42, силуэт 22). */
    val MedsListPlate: Dp = 42.dp
    val MedsListPlateGlyph: Dp = 22.dp

    /** Кружок дня в блоке «Последние 7 дней» и точка легенды под ним. */
    val AdherenceDay: Dp = 26.dp
    val AdherenceLegendDot: Dp = 10.dp

    /**
     * Обводка полого кружка сегодняшнего дня.
     *
     * Своя толщина, а не [BorderAccent]: полый кружок 26 dp с рамкой 1,5 dp читается как
     * закрашенный светлым, и «сегодня» перестаёт отличаться от «пропущено» (ЭКР-6).
     */
    val AdherenceRing: Dp = 2.dp

    // --- Календарь месяца на экране истории (SKL-18, макет History.dc.html) ---

    /**
     * Клетка дня календаря месяца и полоса лекарства в блоке «По лекарствам».
     *
     * Габариты из макета: квадрат 30 и полоса 7. Клетка не нажимается — раскрытие дня
     * в список приёмов в макете не нарисовано и вынесено из объёма задачи, — поэтому
     * требование цели нажатия 44 dp (НФТ-29, ОВ-17) к ней не относится: расширять
     * область нажатия у элемента, который не нажимается, нечем и незачем.
     */
    val CalendarDay: Dp = 30.dp
    val AdherenceBar: Dp = 7.dp

    /**
     * Стрелка переключения месяца: рисунок 32 dp, шеврон внутри 17 dp.
     *
     * Цель нажатия доводится до 44 dp модификатором `minTouchTarget`, а не размером
     * рисунка: макет рисует стрелки 32×32, и «переверстать покрупнее» значит сломать
     * плотность, ради которой они такие.
     */
    val MonthArrow: Dp = 32.dp
    val MonthArrowGlyph: Dp = 17.dp

    /** Баннер (§4.6): внутреннее поле 11–16 dp. */
    val BannerPaddingVertical: Dp = 11.dp
    val BannerPaddingHorizontal: Dp = 14.dp
    val BannerIcon: Dp = 17.dp

    /**
     * Контурная галочка состояния успеха шторки (§4.18, ОВ-125).
     *
     * Именной габарит: это единственное место продукта, где глиф-отметка стоит
     * самостоятельной иллюстрацией, и подбирать его на экране нельзя (НФТ-47).
     * Толщина штриха — тоже именная: ОВ-125 задаёт ровно 6 dp на 72 dp, а не общую
     * долю 0,13, от которой штрих вышел бы вдвое толще.
     */
    val BottomSheetSuccessMark: Dp = 72.dp
    val BottomSheetSuccessMarkStroke: Dp = 6.dp

    /**
     * Кнопка-аватар профиля в шапке (`Main.dc.html`, `MainProfile.dc.html`).
     *
     * Пилюля 44 dp с кружком инициала 30 dp и шевроном 14 dp. Габариты именные: аватар —
     * единственный элемент продукта такой формы, и подбирать их на экране нельзя (НФТ-47).
     */
    val ProfileAvatarButton: Dp = 44.dp
    val ProfileAvatar: Dp = 30.dp
    val ProfileAvatarChevron: Dp = 14.dp

    /** Шеврон цели единицы в поле ввода (§5.3): подпись «мг» рядом с ним, а не вместо него. */
    val FieldUnitChevron: Dp = 14.dp
    val ProfileAvatarPadding: Dp = 6.dp

    /** Шапка экрана (§4.9): верхний отступ 26–30 dp. */
    val HeaderTopPadding: Dp = 30.dp
    val HeaderTopPaddingProfile: Dp = 24.dp
    val HeaderBottomPadding: Dp = 14.dp

    /**
     * Потолок суммы «верхний инсет + полоса чужого профиля + поле шапки» — 56 dp от верхней
     * грани (§4, Р-54).
     *
     * Поле шапки отсчитывается не от грани экрана, а от системной панели, и на устройстве
     * с вырезом складывалось с её высотой: заголовок уходил на 79,6 dp. Потолок возвращает
     * правило макета (26–30 dp от грани) на любой инсет: на обычной строке состояния
     * (24 dp) сумма остаётся 54 dp и вид не меняется, на вырезе (49,5 dp) поле урезается
     * до 6,5 dp — а в чужом профиле до 0,5 dp: 6 dp из того же верхнего поля занимает
     * полоса профиля. Правило считает [ru.stohastika.sklyanka.ui.component.headerTopPadding] —
     * одна функция на все шапки, чтобы на одиннадцати экранах не завелось одиннадцать чисел.
     */
    val HeaderTopCap: Dp = 56.dp

    /**
     * Закреплённый компактный ряд шапки (§7).
     *
     * Именной габарит, а не ступень шкалы (НФТ-47): 56 dp — нижняя граница, из которых
     * 44 отданы целям нажатия. При крупном системном шрифте ряд растёт по кнопкам,
     * но не сжимается.
     */
    val PinnedHeaderBar: Dp = 56.dp

    /**
     * Глиф возврата — шеврон направления «влево» в цели [MinTouchTarget] 44 dp (§7, Р-30).
     *
     * Габарит поимённый: рисунок 22 dp выведен из макетов (`design/screens/MedCard.dc.html`),
     * и подбирать его на экране нельзя.
     */
    val BackChevron: Dp = 22.dp

    /**
     * Нижний инсет прокрутки под наложенным действием (§4.1).
     *
     * Высота наложения плюс два шага [SklyankaSpacing.Section]: для круглой кнопки
     * добавления 60 dp это 100 dp. Меньшее поле — дефект: последняя карточка
     * недостижима под кнопкой (V-10).
     */
    val FloatingActionInset: Dp = 100.dp

    /** Штрих и разрыв пунктирной границы блока «по потребности» (§4.1). */
    val DashOn: Dp = 6.dp
    val DashOff: Dp = 5.dp

    /** Обычная граница и граница элемента, требующего действия (§4.1, §4.2). */
    val BorderThin: Dp = 1.dp
    val BorderAccent: Dp = 1.5.dp

    /** Разделитель между блоками. */
    val DividerThickness: Dp = 1.dp

    /**
     * Потолок масштаба системного шрифта для [SklyankaType.Display] (§6.3).
     *
     * Применяется только к 64 sp на полноэкранном напоминании, где время физически
     * не помещается на 390 dp. Остальная типографика масштабируется свободно:
     * ограничение масштаба — это отъём у человека того, что система ему дала.
     */
    const val DISPLAY_MAX_FONT_SCALE: Float = 1.3f

    /**
     * Масштаб, выше которого подпись вкладки нижней панели скрывается (§6.3, НФТ-30).
     *
     * Иконка с `contentDescription` остаётся: скрывается дубль, а не смысл.
     */
    const val LABEL_HIDE_FONT_SCALE: Float = 1.3f

    /**
     * Масштаб, выше которого шапка шторки уводит заголовок в отдельную строку (§4.18, §6.3).
     *
     * В одной строке с «Отмена» доля заголовка на 200 % становится уже его самого длинного
     * слова, и «Отчёт разработчику» рвётся по буквам (AC-42). Выше этого масштаба действие
     * остаётся в своей строке, а заголовок занимает всю ширину следующей.
     */
    const val SHEET_HEADER_STACK_FONT_SCALE: Float = 1.3f
}
