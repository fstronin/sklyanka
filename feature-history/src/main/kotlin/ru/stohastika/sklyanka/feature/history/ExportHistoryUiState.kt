package ru.stohastika.sklyanka.feature.history

import androidx.compose.runtime.Immutable
import ru.stohastika.sklyanka.domain.history.HistoryCsvDocument
import ru.stohastika.sklyanka.domain.history.ReportPreset
import java.time.LocalDate

/**
 * Состояние шторки экспорта истории — единственный источник правды её разметки (SKL-119, §5.16).
 *
 * Шторки нет — [sheet] пуст, и это единственный признак видимости: состояния «загрузка»
 * у поверхности нет (данные локальные, документ собирается сразу), а отказ выражается
 * сообщением исхода внутри самой шторки.
 */
@Immutable
data class ExportHistoryUiState(
    /** Открытая шторка; `null` — строка настроек ещё не нажата или шторка закрыта. */
    val sheet: ExportUi? = null,
    /**
     * Исход последнего действия; `null` — действия ещё не было.
     *
     * Сообщается **в шторке**, а не баннером на экране: успех заменяет её содержимое,
     * отмена и ошибка остаются её первым элементом (то же решение, что у отчёта, ОВ-125).
     */
    val outcome: ExportOutcome? = null,
)

/**
 * Открытая выгрузка: готовый файл, состав словами и выбранный период.
 *
 * Документ приходит собранным: экран его передаёт и сохраняет, но не собирает.
 * [composition] — структура «подпись — значение»: значения приходят отдельными полями,
 * а подписи берёт разметка из ресурсов.
 */
@Immutable
data class ExportUi(
    val document: HistoryCsvDocument,
    val composition: ExportComposition,
    /** Выбранный пресет периода: подсвечивает чип и решает, показывать ли «С»/«По». */
    val preset: ReportPreset,
    /** Границы «Другого периода»: те же, что у отчёта, и хранятся так же — в открытой шторке. */
    val customFrom: LocalDate,
    val customTo: LocalDate,
    val today: LocalDate,
)

/**
 * Состав файла словами: профиль, период, число записей и формат.
 *
 * [records] — число строк таблицы; `null` — за период нет ни одной записи, и на месте числа
 * стоит та же фраза, что в документе отчёта (Р-33): «0» читалось бы как измерение.
 */
@Immutable
data class ExportComposition(
    val profile: String,
    /** Диапазон словами: «1 — 30 сентября 2026». */
    val period: String,
    /** Начало периода одной датой: значение строки «С» в «Другом периоде». */
    val from: String,
    /** Окончание периода одной датой: значение строки «По». */
    val to: String,
    val records: String?,
    /** «CSV». */
    val format: String,
)

/**
 * Исход выгрузки истории.
 *
 * Отмена системного диалога — не ошибка и не молчание: для человека она выглядит точно так же,
 * как отказ записи, и различить их обязано приложение. Успех — отдельное состояние содержимого
 * шторки; отмена и ошибка — сообщение над составом. Исходы ставятся по факту: «передан» означает
 * «отдан системному обмену» и доставку не обещает (П-7).
 *
 * «Места не хватило» — отдельный исход, а не разновидность отказа: это единственная причина,
 * которую человек может исправить сам, и слова у неё свои (§5.16).
 */
enum class ExportOutcome {
    CANCELLED,

    /** Отказ передачи: текст называет действие — «Экспорт не удалось передать». */
    FAILED_SHARE,

    /** Отказ сохранения: «Файл не сохранён» — отмена выбора места сюда же (SKL-46). */
    FAILED_SAVE,

    /** Места не хватило до записи: «Места недостаточно. Файл не сохранён». */
    NO_SPACE,

    SHARED,
    SAVED,
    ;

    val isSuccess: Boolean get() = this == SHARED || this == SAVED
}
