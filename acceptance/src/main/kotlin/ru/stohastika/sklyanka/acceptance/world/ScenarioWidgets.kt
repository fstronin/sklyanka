package ru.stohastika.sklyanka.acceptance.world

/**
 * Состояние виджетов домашнего экрана в сценарии (SKL-118).
 *
 * Мир приёмки — чистый Kotlin/JVM и не знает ни `WidgetType` модуля виджетов, ни его
 * ресурсов: тип назван своим перечислением, а строки интерфейса проверяет экранный прогон
 * модуля, где ресурсы есть. Здесь живёт то, о чём говорят сценарии: какой виджет человек
 * ставит, открыта ли настройка и появилась ли плита.
 *
 * Платформенный ход (диалог домашнего экрана прошивки) приёмке недоступен, поэтому
 * установка изображается состоянием: проверяются правила гейта — отмена настройки
 * не добавляет виджет, завершение добавляет (Р-32, ПР-23).
 */
class ScenarioWidgets {

    /** Тип виджета словами сценария: у каждого своё содержимое (Р-34). */
    enum class Type { TODAY, WEEK, MEDICATION }

    var type: Type = Type.TODAY

    /** Сколько плит появилось на домашнем экране за сценарий. */
    var installed: Int = 0

    /** Сколько плит уже стояло к началу текущего захода: «добавлен» — это «стало на одну больше». */
    var installedAtStart: Int = 0

    /** Экран настройки открыт платформой при добавлении виджета. */
    var configOpen: Boolean = false

    /** Выбранное в настройке лекарство — имя сценария; `null` — выбор не сделан. */
    var selectedMedication: String? = null
}
