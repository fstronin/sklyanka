package ru.stohastika.sklyanka.platform

import android.util.Log
import kotlinx.coroutines.CoroutineExceptionHandler
import javax.inject.Inject
import javax.inject.Singleton

/**
 * Отказ «забытой» фоновой работы (П-1, Р-44).
 *
 * Работа старта приложения и работа приёмников запускается в область, у которой нет
 * вызывающего: вернуть отказ некому. Kotlin в такой области отдаёт исключение обработчику
 * по умолчанию, то есть системному обработчику потока, — а тот в Android **завершает
 * процесс**. Цена ошибки видна на пути отказа: база новее сборки, не хватило места на
 * копию перед миграцией, отозвано разрешение — всё это продукт обязан пережить (Р-44,
 * ADR-0012 пп. 3, 7), а переживает падением. Падение при этом случается не в сценарии
 * отказа, а у соседа: работа старта идемпотентна и живёт дольше, чем повод её запустить.
 *
 * Поэтому обе активные области приложения носят этот обработчик, и отказ в них:
 *
 * - **не роняет процесс.** Работа старта повторится на следующем запуске (на EMUI старт —
 *   единственное событие, которое случается наверняка), а пересборка окна — на якорном
 *   будильнике или задаче `WorkManager` (НАП-8);
 * - **не молчит.** Остаётся строкой локального журнала: только этап работы и класс отказа.
 *   Ни идентификаторов, ни названий лекарств, ни имён профилей — как и требует НФТ-19 для
 *   журналов; наружу строка не уходит (сети и отчётов о сбоях нет, П-7).
 *
 * Журнал операций для этого не годится: причина отказа чаще всего и есть «база недоступна»,
 * и запись в неё была бы вторым падением вместо первой записи. Журнал запуска не требует
 * ни базы, ни графа и потому доступен там, где всё остальное уже не работает.
 */
@Singleton
class BackgroundWorkFailures @Inject constructor() {

    /** Обработчик области работы старта приложения ([ru.stohastika.sklyanka.SklyankaApp]). */
    fun forStartup(): CoroutineExceptionHandler = handler(Stage.STARTUP)

    /** Обработчик области работы приёмников напоминаний (`ReminderScope`). */
    fun forReminders(): CoroutineExceptionHandler = handler(Stage.REMINDERS)

    private fun handler(stage: Stage): CoroutineExceptionHandler = CoroutineExceptionHandler { _, failure ->
        Log.e(TAG, "background work failed: stage=$stage, error=${failure.javaClass.simpleName}")
    }

    /**
     * Этап работы — перечисление, а не строка.
     *
     * Так в журнал физически не может попасть ничего, кроме двух известных значений:
     * называть этап словами вызывающего значило бы однажды записать туда название
     * лекарства (НФТ-19).
     */
    internal enum class Stage { STARTUP, REMINDERS }

    private companion object {
        const val TAG = "SklyankaBackground"
    }
}
