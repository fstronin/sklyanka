package ru.stohastika.sklyanka.navigation

import androidx.compose.runtime.staticCompositionLocalOf

/**
 * Открыта ли модальная поверхность поверх корня (SKL-119).
 *
 * Модальная шторка Compose не забирает возврат «по праву»: обработчики вызываются
 * в порядке регистрации, а слои навигации пересобираются на каждом переходе — то есть
 * свежий экранный `BackHandler` оказывается позже шторки и уводит человека на «Сегодня»,
 * оставив шторку висеть поверх чужого экрана. Поймал поход на эмуляторе.
 *
 * Поэтому экранные обработчики возврата спрашивают этот признак и выключаются, пока
 * поверхность открыта: новый экранный `BackHandler` обязан уступать открытой шторке,
 * иначе вернётся тот же дефект.
 */
val LocalModalSurfaceOpen = staticCompositionLocalOf { false }
