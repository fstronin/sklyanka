package ru.stohastika.sklyanka.navigation

import ru.stohastika.sklyanka.domain.undo.UndoableActionStore
import ru.stohastika.sklyanka.domain.undo.UndoableMark

/**
 * Возврат на «Сегодня» под живым окном отмены отметки (SKL-43, дополнение ОВ-81).
 *
 * Окно отмены отметки показывается только на «Сегодня» (SKL-30): человек, отметивший
 * приём с полноэкранной карточки и не попавший туда, теряет единственный способ
 * исправить промах — через 5 секунд отметка необратима. Поэтому появление человека
 * в приложении при живом окне приводит на «Сегодня» с любого экрана корня.
 *
 * Окно удаления лекарства (SKL-99, ОВ-124) живёт на том экране, откуда человек удалил,
 * и переключения не требует: возврат за ним не уводит, а живое окно остаётся видимым.
 *
 * Объект, а не часть `MainActivity`, по той же причине, что `SplashRoute`: правило
 * принимается по времени и проверяется на JVM без устройства. Истёкшее окно не
 * переключает ничего — отменять уже нечего.
 */
object UndoReturn {

    /**
     * Человек оказался в приложении: вернулся с полноэкранной карточки, разблокировал
     * телефон или снова открыл приложение.
     *
     * @return был ли это возврат под живым окном отметки — по ответу вызывающий закрывает
     *   экран, стоящий поверх корня (разрешения), чтобы «Сегодня» стало видимым.
     */
    fun onAppeared(undoActions: UndoableActionStore, navigation: RootNavigation): Boolean {
        if (undoActions.live() !is UndoableMark) return false
        navigation.openToday()
        return true
    }
}
