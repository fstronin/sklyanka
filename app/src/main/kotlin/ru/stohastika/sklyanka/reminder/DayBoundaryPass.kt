package ru.stohastika.sklyanka.reminder

/**
 * Полуночный проход и перерисовка плит как одно действие (SKL-118, ПР-1, П-7).
 *
 * Пара собрана отдельным типом, а не двумя строками внутри воркера: «перерисовки нет
 * вовсе» — молчаливая регрессия, и её видит только тот, кто называет пару вслух.
 * Проход и перерисовка приходят функциями: обе живут в графе, а эта ступень отвечает
 * ровно за то, что вторая идёт вслед за первой.
 */
internal class DayBoundaryPass(private val sweep: suspend () -> Unit, private val refresh: suspend () -> Unit) {

    suspend fun run() {
        sweep()
        refresh()
    }
}
