package ru.stohastika.sklyanka.startup

/**
 * Данные, которые заводит отладочная сборка на первом запуске.
 *
 * Существует по одной причине: **экрана добавления профиля нет** — он не описан ни
 * в макетах, ни в спецификации, и помечен открытым вопросом `ОВ-3` (ПРФ-9). Без второго
 * профиля половина приёмки SKL-15 недостижима руками: переключиться некуда, индикацию
 * чужого профиля не увидеть, отметку в чужом профиле не поставить.
 *
 * Набор, а не один объект: в релизной сборке он **пуст**, и это не «выключено флагом»,
 * а физически отсутствующий код (отладочная связка живёт в `src/debug`). Флаг можно
 * поставить не туда, и тогда продукт заведёт человеку профиль, которого тот не просил.
 */
fun interface StartupSeed {

    /** Вызывается один раз при старте, после того как профиль владельца уже существует. */
    suspend fun seed()
}
