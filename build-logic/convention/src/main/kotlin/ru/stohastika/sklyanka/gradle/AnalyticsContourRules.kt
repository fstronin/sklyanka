package ru.stohastika.sklyanka.gradle

/**
 * Правила состава артефакта (SKL-82 → SKL-100 → SKL-122, ПЛ-3/ПЛ-4, ПМ-31).
 *
 * Одно место, где записано, чему разрешено ехать в сборке: запрещённые группы, белый список
 * координат вендора и сетевые разрешения. Задачи проверки манифеста и состава зависимостей
 * читают эти правила, поэтому разрешение и зависимости не могут разойтись.
 *
 * **Платный контур появился** (SKL-122, `ADR-0010` п. 1 и п. 5): `INTERNET` перестал быть
 * запрещённым безусловно и стал разрешением контура, а белый список координат заполнен
 * замыканием клиента магазина. Запреты GMS, Firebase, рекламы и чужой аналитики сохраняются
 * (ПЛ-4), как и безусловный запрет разрешений состояния сети (НФТ-15).
 */
object AnalyticsContourRules {

    /**
     * Модуль платного сетевого контура.
     *
     * Сеть в сборке разрешена ровно вместе с ним: проверка манифеста не пропускает `INTERNET`
     * без контура, а проверка зависимостей требует его координату (ИИ-24, `ADR-0010` п. 5).
     */
    const val PAID_CONTOUR_MODULE = "billing-appgallery"

    /** Путь модуля контура в графе проектов. */
    const val PAID_CONTOUR_PROJECT = ":billing-appgallery"

    /**
     * Обязательная координата контура — клиент магазина.
     *
     * Обязательная, а не просто разрешённая: контур без клиента — это витрина, которая
     * никогда не покажет цену, то есть обещание покупки без покупки (П-7).
     */
    val REQUIRED_COORDINATES = listOf("com.huawei.hms:iap")

    /**
     * Белый список координат — данные, а не логика, и заполнен **осознанно** (`ADR-0010` п. 5).
     *
     * Здесь ровно замыкание `com.huawei.hms:iap` (посчитано по POM вендора и подтверждено
     * разрешением classpath): сам клиент, его база и то, что база тянет за собой — настройки
     * среды, телеметрия клиента, сетевая библиотека вендора, его же криптография и hmf-задачи,
     * на типе которых возвращаются ответы. Любая координата `com.huawei.*` вне этого списка
     * по-прежнему валит сборку.
     *
     * **Названные следствия** (решение заказчика 15.10.2026, записано в пересмотре `ADR-0010`):
     * `com.huawei.hms:stats` и `com.huawei.hms:hatool` — телеметрия вендорского клиента, а
     * `network-*` — его сетевая библиотека. Это не наша аналитика (клиентской аналитики
     * у продукта нет, Р-4) и не наш сетевой слой: исключить их значило бы менять поведение
     * клиента магазина без возможности проверить покупку автоматическим прогоном. Запрет
     * сторонних (не вендорских) аналитических и рекламных SDK остаётся в силе отдельным
     * списком групп, а своя отправка событий продукту не добавляется.
     */
    val ALLOWED_COORDINATES = listOf(
        // Клиент магазина и его база.
        "com.huawei.hms:iap",
        "com.huawei.hms:base",
        "com.huawei.hms:ui",
        "com.huawei.hms:device",
        "com.huawei.hms:log",
        "com.huawei.hms:baselegacyapi",
        "com.huawei.hms:availableupdate",
        // Телеметрия клиента: приходит с базой, продуктом не зовётся.
        "com.huawei.hms:stats",
        "com.huawei.hms:hatool",
        // Сетевая библиотека вендора и его криптография: ими ходит клиент магазина.
        "com.huawei.hms:network-grs",
        "com.huawei.hms:network-common",
        "com.huawei.hms:network-framework-compat",
        "com.huawei.android.hms:security-ssl",
        "com.huawei.android.hms:security-encrypt",
        "com.huawei.android.hms:security-base",
        // Настройки проекта AppGallery Connect и задачи, которыми возвращаются ответы.
        "com.huawei.agconnect:agconnect-core",
        "com.huawei.hmf:tasks",
    )

    /**
     * Сетевые разрешения платного контура.
     *
     * `INTERNET` допустим в слитом манифесте, только если он пришёл из контура и ни из какого
     * другого модуля (`verifyManifest<Вариант>`); без контура в артефакте разрешение валит
     * сборку, как и прежде (ПЛ-3, НФТ-15, `ADR-0010` п. 1).
     */
    val PAID_CONTOUR_PERMISSIONS = listOf("android.permission.INTERNET")

    /** Запрещённые группы: GMS, Firebase, реклама, чужая аналитика и крашлитика (ПЛ-4, НФТ-16/39). */
    val FORBIDDEN_GROUPS = listOf(
        "com.google.android.gms",
        "com.google.firebase",
        "com.google.android.play",
        "com.crashlytics",
        "io.fabric",
        "com.google.mlkit",
    )

    /**
     * Разрешения, запрещённые всегда (НФТ-15, `ADR-0010` п. 5).
     *
     * Состояние сети продукту не нужно: ядро работает без сети, а покупка — дело магазина.
     * Замыкание вендорского клиента объявляет `ACCESS_NETWORK_STATE` в своих манифестах;
     * манифест `app` снимает его через `tools:node="remove"`, и проверка слитого манифеста
     * держит это правило, а не обещание. `com.google.gms.permission.AD_ID` — по той же
     * причине: рекламные идентификаторы не собираются ни при каких условиях (ПМ-17 п. 4).
     */
    val FORBIDDEN_PERMISSIONS = listOf(
        "android.permission.ACCESS_NETWORK_STATE",
        "android.permission.ACCESS_WIFI_STATE",
        "com.google.gms.permission.AD_ID",
    )

    /** Разрешена ли координата: точная или по началу (модули одной публикации). */
    fun allows(coordinate: String): Boolean = ALLOWED_COORDINATES.any { coordinate.startsWith(it) }
}
