package ru.stohastika.sklyanka.gradle

/**
 * Правила состава артефакта (SKL-82 → SKL-100 → SKL-165, ПЛ-3/ПЛ-4, ПМ-26/31).
 *
 * Одно место, где записано, чему не разрешено ехать в сборке: запрещённые группы
 * и координаты, запрещённые разрешения, сетевые разрешения. Задачи проверки манифеста
 * и состава зависимостей читают эти правила, поэтому разрешение и зависимости не могут
 * разойтись.
 *
 * **Сети в продукте нет.** Поставляемая сборка работает офлайн: аккаунта, облака,
 * синхронизации и аналитики не существует (ПЛ-3, `ADR-0017`). Поэтому `INTERNET`
 * и `ACCESS_NETWORK_STATE` запрещены безусловно — не «только вместе с контуром»,
 * а всегда: разрешению неоткуда взяться законно. Запреты GMS, Firebase, рекламы
 * и чужих SDK сохраняются (ПЛ-4).
 */
object ArtifactCompositionCatalog {

    /**
     * Сетевые разрешения, которых в собранном артефакте быть не может (ПЛ-3, НФТ-15).
     *
     * Проверяются оба: `INTERNET` открывает сеть, `ACCESS_NETWORK_STATE` — чтение её
     * состояния. Второе приходит с библиотеками (`androidx.work` объявляет его своим
     * манифестом), и манифест `app` снимает его через `tools:node="remove"`.
     */
    val NETWORK_PERMISSIONS = listOf(
        "android.permission.INTERNET",
        "android.permission.ACCESS_NETWORK_STATE",
    )

    /**
     * Запрещённые группы: GMS, Firebase, реклама и крашлитика (ПЛ-4, НФТ-16/39).
     *
     * Проверяется каждая: иначе координата вендора и её транзитивное замыкание проехали бы
     * мимо проверки состава молча, и обещание «GMS/Firebase/рекламы нет» держалось бы
     * только на честном слове.
     */
    val FORBIDDEN_GROUPS = listOf(
        "com.google.android.gms",
        "com.google.firebase",
        "com.google.android.play",
        "com.crashlytics",
        "io.fabric",
        "com.google.mlkit",
    )

    /**
     * Разрешения, запрещённые всегда (НФТ-15, `ADR-0017` п. 3).
     *
     * `ACCESS_WIFI_STATE` продукту не нужен: состояние сети никто не читает. Запрещён
     * безусловно и `com.google.android.gms.permission.AD_ID`: рекламные идентификаторы
     * не собираются ни при каких условиях (ПМ-26).
     */
    val FORBIDDEN_PERMISSIONS = listOf(
        "android.permission.ACCESS_WIFI_STATE",
        "com.google.android.gms.permission.AD_ID",
    )
}
