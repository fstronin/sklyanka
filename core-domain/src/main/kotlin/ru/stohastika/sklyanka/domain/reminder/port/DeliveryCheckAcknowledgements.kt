package ru.stohastika.sklyanka.domain.reminder.port

import java.time.Instant

/**
 * Подтверждения объявленного результата самопроверки (SKL-86, ОВ-108).
 *
 * Результат проверки не кончается сам: без постоянного «объявлено» баннер о вчерашней
 * неудаче возвращался бы при каждом входе — та же ложь, что вечная галочка. Момент
 * проверки, а не флаг: следующая проверка с другим моментом объявляется заново.
 */
interface DeliveryCheckAcknowledgements {

    /** Момент проверки, результат которой человеку уже объявлен; `null` — не объявляли. */
    suspend fun announced(): Instant?

    /** Запомнить, что результат проверки с этим моментом объявлен. */
    suspend fun remember(dueAt: Instant)
}
