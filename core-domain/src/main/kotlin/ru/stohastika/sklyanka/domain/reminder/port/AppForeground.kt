package ru.stohastika.sklyanka.domain.reminder.port

/**
 * Открыто ли приложение сейчас (SKL-86, ОВ-108).
 *
 * Отвечает на один вопрос сценария самопроверки: если приложение на переднем плане
 * в момент тестового срабатывания, проверка не состоялась — фоновый путь при открытом
 * приложении не проверяется, и «не дошло» здесь было бы ложью (НФТ-8).
 *
 * Открытым считается приложение, видимое человеку. Заблокированный телефон открытым
 * не считается: блокировать его и не просят, а разбуженный приёмник активити не имеет
 * вовсе — процесс без возобновлённых активностей и есть «закрытое приложение».
 */
fun interface AppForeground {
    fun isForeground(): Boolean
}
