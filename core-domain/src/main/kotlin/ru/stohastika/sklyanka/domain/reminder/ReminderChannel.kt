package ru.stohastika.sklyanka.domain.reminder

/**
 * Канал доставки напоминания (НАП-24).
 *
 * Каналов ровно два, они статичны и создаются один раз: параметры канала неизменяемы после
 * создания, а удаление и создание канала с тем же идентификатором восстанавливает прежний
 * (ПЛ-10). Отсюда же следует, что индивидуальный звук на лекарство невозможен без
 * версионированных каналов и отложен во вторую версию (НАП-27).
 *
 * Канала тихих часов здесь нет и заготовки под него не будет: решение по НАП-28 не принято,
 * а полуработающая функция, глушащая напоминание, противоречит НАП-1.
 *
 * Идентификатор обычного канала версионирован после публикации: звук задаётся при создании
 * канала и после этого не меняется (ПЛ-10), поэтому собственный сигнал (Р-99) потребовал
 * нового идентификатора. Канал прежнего выпуска [RETIRED_REGULAR_ID] удаляется при старте.
 */
enum class ReminderChannel(val id: String) {
    /** Первое напоминание о приёме — всегда этот канал (НАП-25). */
    REGULAR("reminders_regular_v2"),

    /** Повтор о неотмеченном приёме: заметнее и с обходом «Не беспокоить» (НАП-25, НАП-17). */
    PERSISTENT("reminders_persistent"),
    ;

    companion object {

        /**
         * Идентификатор обычного канала до смены сигнала (Р-99).
         *
         * Нужен ровно для уборки: у тех, кто ставил сборку до 2026.10.3, канал звучит
         * системным сигналом уведомления, и напоминание на него больше не уходит. Заново
         * с этим идентификатором канал не создаётся никогда — пересоздание вернуло бы
         * прежний звук (ПЛ-10).
         */
        const val RETIRED_REGULAR_ID: String = "reminders_regular"
    }
}
