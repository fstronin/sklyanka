package ru.stohastika.sklyanka.domain.history

/**
 * Состав отчёта врачу — выбор человека, а не тариф (Р-85 п. 1, SKL-119).
 *
 * Отчёт врачу один, и вход в него один: в шторке выбирается **состав** того же документа.
 * «Базовый» — документ сегодняшнего вида (один период, приверженность, разбивка
 * по лекарствам) и остаётся бесплатным навсегда (Р-36): ни его состав, ни вёрстка, ни имя
 * файла от появления второго состава не меняются. «Расширенный» — тот же документ плюс три
 * раздела (сравнение периодов, динамика приверженности по месяцам, паттерн пропусков),
 * и он доступен только с активным доступом «Про»; разбивка по лекарствам в «Про» не уходит
 * (Р-36, Р-85 п. 1).
 *
 * **Домен считает то, о чём попросили.** Права состава домен не проверяет и проверять
 * не может: доступ — состояние подписки, и решает по нему поверхность (Р-22, Р-67).
 * Здесь только «какой документ собрать».
 *
 * **Имя типа.** В `feature-history` уже живёт `ReportComposition` — состав отчёта
 * словами для карточки шторки (профиль, период, принято, формат). Второй тип с тем же
 * именем в домене завёл бы тень одного слова на двух значениях, поэтому состав-выбор
 * называется [ReportScope] (отклонение от буквы `TDD.md §3` с сохранением смысла контракта).
 */
enum class ReportScope {

    /** Документ сегодняшнего вида: один период, приверженность, разбивка по лекарствам. */
    BASE,

    /** Тот же документ плюс три раздела «Про»; без активного доступа не собирается. */
    EXTENDED,
}
