package ru.stohastika.sklyanka.domain.pro

import java.time.LocalDate

/**
 * Состояние подписки «Склянки Про» — то, что знает продукт о доступе человека.
 *
 * Источник правды — магазин, и только он (`ADR-0015`): своего сервера энтитлментов нет,
 * учётной записи нет, сшивки покупок между магазинами нет. Состояние кэшируется
 * на устройстве, чтобы недоступный магазин не отнимал доступ (П-6, Р-68 п. 7).
 *
 * Истечение — это `None`, а не отдельное состояние: витрина после истечения показывает
 * то же, что до покупки, без упрёков (Р-67 п. 3), и «когда-то была, но кончилась»
 * продукту не нужно ни для экрана, ни для доступа.
 */
sealed interface ProSubscription {

    /** Подписки нет: не оформлена или истекла. */
    data object None : ProSubscription

    /**
     * Подписка активна до [until] включительно.
     *
     * [productId] — товар, из которого пришла покупка; `null`, когда магазин его не назвал
     * (так бывает у восстановления). Он нужен одному месту — цене продления в состоянии
     * «активна» (Р-73 п. 1): без него цену брать не из чего, и она не показывается вовсе.
     */
    data class Active(val productId: ProProductId?, val until: LocalDate) : ProSubscription

    companion object {

        /**
         * Состояние по дате магазина и сегодняшнему дню.
         *
         * «Активна до 13 ноября» значит ровно это: день [until] ещё входит в доступ,
         * а следующий — уже нет. Сравнение идёт в датах интерфейса, а не в моментах:
         * дату называет магазин, и часовых поясов у неё нет (НФТ-48).
         */
        fun activeIfNotExpired(productId: ProProductId?, until: LocalDate, today: LocalDate): ProSubscription =
            if (until.isBefore(today)) None else Active(productId, until)
    }
}
