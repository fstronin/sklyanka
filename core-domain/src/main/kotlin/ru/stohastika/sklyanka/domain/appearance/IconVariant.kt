package ru.stohastika.sklyanka.domain.appearance

/**
 * Вариант иконки приложения (§2.4, Р-31, SKL-120).
 *
 * Два варианта одного знака: холодный — базовый (Р-56, Р-57), тёплый — «Про».
 * Разные у них краски, плитка и ресурсы; геометрия знака и слои одни и те же, поэтому
 * домену довольно имени варианта: какой ресурс включить, решает `app` (два
 * `activity-alias`), а не правило.
 *
 * Имя в лончере от варианта не зависит: у обоих алиасов `android:label` — `app_name`,
 * потому что название в списке приложений принадлежит продукту, а не оформлению
 * (В-120-2). Ярлык «Добавить лекарство» и значок уведомления от варианта не зависят
 * вовсе: первый — действие, второй — монохромная маска.
 */
enum class IconVariant(val key: String) {

    /** «Ледяная» — базовая, холодная палитра знака (Р-57). */
    ICE("ice"),

    /** «Тёплая» — оливковая палитра знака, вариант «Про» (§2.4). */
    WARM("warm"),
    ;

    /** Базовая иконка: доступна в любой подписке и без неё. */
    val isBase: Boolean get() = this == DEFAULT

    companion object {

        /** Базовая иконка (Р-56, Р-57). */
        val DEFAULT: IconVariant = ICE

        /** Вариант по записи в постоянных настройках; незнакомая строка — базовая. */
        fun ofKey(key: String?): IconVariant = entries.firstOrNull { it.key == key } ?: DEFAULT
    }
}
