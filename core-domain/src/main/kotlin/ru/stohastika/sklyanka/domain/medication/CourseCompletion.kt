package ru.stohastika.sklyanka.domain.medication

import ru.stohastika.sklyanka.domain.model.Medication
import ru.stohastika.sklyanka.domain.model.ScheduleMode
import java.time.LocalDate

/**
 * Предложение убрать законченный курс в архив (ОВ-42).
 *
 * Кто проставляет `archive_reason = course_finished` — приложение по дате окончания или
 * человек — спецификация не решает (`docs/norm/04-behavior.md` §3). Из трёх разобранных
 * вариантов реализован третий: **приложение предлагает, человек подтверждает**.
 *
 * Почему не два других. Автоматическая архивация уносит курс из списка без ведома
 * человека — ровно в тот момент, когда он, возможно, собирался его продлить. Только
 * вручную — список активных зарастает именно теми курсами, которые кончились, и человек
 * продолжает получать напоминания о лекарстве, которое больше не пьёт; это прямой вред.
 *
 * Предложение — вычисляемое состояние, а не запись в базе: хранить «мы уже предлагали»
 * значило бы отвечать на вопрос «что делать, если человек игнорирует предложение неделю»
 * схемой данных, а он не решён. Пока курс закончился и не убран, предложение видно;
 * как только убран — исчезает само.
 */
object CourseCompletion {

    /**
     * Курс закончился, но всё ещё активен: карточка предлагает убрать его в архив
     * с причиной «курс завершён».
     *
     * Бессрочный курс сюда не попадает: окончить его нечем (ПР-6). Лекарство
     * «по потребности» — тоже: отрезка курса у него нет (ПР-8).
     *
     * Сравниваются календарные даты, а не моменты: последний день курса входит в него
     * целиком (ИНВ-15), поэтому курс, заканчивающийся сегодня, ещё не закончен.
     */
    fun isFinished(medication: Medication, today: LocalDate): Boolean {
        val end = medication.endDate
        return !medication.isArchived &&
            medication.scheduleMode == ScheduleMode.SCHEDULED &&
            end != null &&
            end < today
    }
}
