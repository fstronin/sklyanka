package ru.stohastika.sklyanka.domain.appearance

/**
 * Что произошло при выборе оформления (§5.17, Р-31, Р-67, Р-22).
 *
 * Исходов два, и оба — про доступ, а не про экран: выбор применён или открывается витрина.
 * Метка «Про» на строке при этом не меняется — строка не переводится в недоступность
 * ни в одном из исходов (П-7).
 */
enum class AppearanceOutcome {

    /** Выбор применён и сохранён. */
    APPLIED,

    /**
     * Открывается витрина с пунктом-поводом «Акцент и иконки» первым (Р-67 пп. 2–3).
     *
     * Применение выбранного при этом не меняется: выбор ждёт доступа, и повторное нажатие
     * после его оформления открывает диалог — та же модель, что у состава отчёта (§5.15).
     */
    SHOWCASE,
}

/**
 * Граница «Про» на акцентную тему и вариант иконки (Р-31, Р-22, §5.17).
 *
 * Правило живёт в домене, а не в ViewModel: его проверяет приёмка без Android, и оно же
 * гейт для любой поверхности, которая однажды появится рядом. Замка здесь нет: закрыто
 * **применение** платного выбора, а не показ списка — человек имеет право увидеть, что
 * именно покупает (П-7, Р-79).
 *
 * Что именно покупается. Акцентные темы и два варианта иконки — возможности «Про» (Р-31),
 * но базовая «Олива» (Р-20) и базовая «Ледяная» (Р-56) — темы **базы**: они доступны
 * в любой подписке и без неё, и метки у них нет (Р-71: метка продавала бы бесплатное).
 *
 * Что происходит после отмены подписки (Р-22, В-120-3). Выбранная тема и выбранный
 * вариант иконки **остаются применёнными**: заведённое не запирается, и запирать его
 * значило бы отнять оплаченное. Снимается ровно выбор нового — платного.
 */
object AppearanceGate {

    /**
     * Выбор варианта в диалоге.
     *
     * @param isBase базовая тема («Олива») или базовая иконка («Ледяная»): они проходят
     *   в любой подписке и без неё.
     * @param included есть ли доступ «Про» прямо сейчас.
     *
     * Доступ перечитывается в момент выбора, а не берётся из состояния диалога: подписка
     * могла кончиться, пока диалог был открыт, и применить платный выбор по устаревшему
     * ответу значило бы применить то, за что уже не заплачено.
     *
     * **Правила «нажатия строки» здесь нет и быть не может** (§5.17, SKL-120): строка
     * открывает диалог и без доступа — человек видит четыре образца темы и обе миниатюры
     * иконки до покупки (Р-67 п. 5), а «Про» стоит у платных строк, а не у поверхности.
     * Гейт остался один — на выборе; второй, на входе в диалог, отнимал бы у человека
     * право увидеть, что именно он покупает.
     */
    fun choose(isBase: Boolean, included: Boolean): AppearanceOutcome =
        if (included || isBase) AppearanceOutcome.APPLIED else AppearanceOutcome.SHOWCASE
}
