package ru.stohastika.sklyanka.domain.pro

import java.time.LocalDate

/**
 * Магазин за портом: домен и экраны не знают ни AppGallery, ни AppGallery Connect
 * (`ADR-0007`, `ADR-0010` п. 2).
 *
 * Порт стоит между витриной и вендором ровно затем, чтобы покупку можно было проверить
 * приёмкой без магазина, а песочница осталась ручной проверкой (`docs/tasks/SKL-122/task.md`).
 * Реализация живёт в модуле платного контура — вне `core-domain` и `core-data`.
 *
 * Ни один метод не возвращает «успех» вместо ответа магазина (П-7): исходы называются
 * тем, чем они были. Отказ магазина, отсутствие связи и своя отмена окна покупки —
 * разные исходы, потому что слова для человека у них разные (Р-68 п. 6).
 */
interface ProStore {

    /** Что продаётся и за сколько. Цена — только отсюда (Р-68 п. 3). */
    suspend fun offers(): ProOffers

    /** Владеет ли человек подпиской. Спрашивается при каждом запуске с сетью (`ADR-0015` п. 1). */
    suspend fun owned(): ProOwned

    /** Покупка выбранного периода; в магазин уходит идентификатор товара (Р-68 п. 1). */
    suspend fun purchase(productId: ProProductId): ProPurchase

    /** Восстановление покупки: только внутри своего магазина (Р-39). */
    suspend fun restore(): ProRestore

    /**
     * Экран управления подписками магазина (`startIapActivity`); отменяет подписку магазин.
     *
     * @return удалось ли передать человека магазину. На устройстве без служб магазина или
     *   когда активность уже ушла в фон, экран не открывается — и тогда об этом нельзя
     *   ни молчать как о состоявшемся действии, ни писать в журнал (П-7, Р-73 п. 1).
     */
    suspend fun openSubscriptionManagement(): Boolean
}

/** Ответ магазина на вопрос о товарах. */
sealed interface ProOffers {

    data class Available(val products: List<ProProduct>) : ProOffers

    /**
     * Магазин не ответил.
     *
     * Последняя известная цена как текущая не показывается никогда (Р-68 п. 4): витрина
     * в этом случае называет выгоды без цен и говорит причину словами.
     */
    data object Unavailable : ProOffers
}

/** Ответ магазина на вопрос о владении подпиской. */
sealed interface ProOwned {

    data class Owned(val productId: ProProductId?, val until: LocalDate) : ProOwned

    /** Покупки нет — это ответ магазина, а не отсутствие ответа. */
    data object None : ProOwned

    /**
     * Магазин о подписке знает, а действующей записи среди его ответов нет.
     *
     * Случай отделён от [None] ради честности слов: «покупок не нашлось» про истёкшую
     * или возвращённую подписку — утверждение о магазине, которого он не делал (П-7).
     */
    data object NotActive : ProOwned

    /** Проверить не удалось: доступ сохраняется по кэшу, срока давности у него нет (П-6). */
    data object Unavailable : ProOwned
}

/** Исход обращения к магазину за покупкой. */
sealed interface ProPurchase {

    data class Purchased(val productId: ProProductId, val until: LocalDate) : ProPurchase

    /** Отказ магазина или отсутствие связи: причина называется словами (Р-68 п. 6, П-7). */
    data class Refused(val failure: ProStoreFailure) : ProPurchase

    /**
     * Человек закрыл окно магазина, не заплатив.
     *
     * Это не событие приложения, и комментировать его нельзя (Р-68 п. 6): сообщение
     * о собственном решении человека — шум. Отдельный исход, а не отказ, именно за этим.
     */
    data object CancelledByPerson : ProPurchase
}

/** Исход восстановления покупки. */
sealed interface ProRestore {

    data class Restored(val productId: ProProductId?, val until: LocalDate) : ProRestore

    /** Магазин ответил, что покупок нет. */
    data object NothingFound : ProRestore

    /** Записи в магазине есть, действующей среди них нет: истекла, возвращена или отменена. */
    data object NotActive : ProRestore

    /** Восстановить не удалось: причина называется словами. */
    data class Failed(val failure: ProStoreFailure) : ProRestore
}

/**
 * Почему обращение к магазину не удалось.
 *
 * Различия здесь нужны словам, а не разбору: «нет связи» и «магазин отклонил покупку» —
 * разные предложения для человека (Р-68 п. 6), и одно сообщение на оба случая было бы
 * ложью в одном из них.
 */
enum class ProStoreFailure(val code: String) {

    /** Сети нет или магазин не ответил. */
    NETWORK("network"),

    /**
     * Магазин недоступен на этом устройстве: нет клиента магазина или он не поддерживается.
     *
     * Отдельно от [NETWORK] потому, что слова разные: «нет связи» советует подождать,
     * а недоступный магазин ждать не заставит — на устройстве без служб магазина покупка
     * не состоится никогда, и обещать обратное было бы ложью (П-7).
     */
    STORE_UNAVAILABLE("store_unavailable"),

    /** Магазин отказал в покупке: платёж не прошёл. */
    PAYMENT_DECLINED("payment_declined"),

    /** Товар недоступен в этом регионе или снят с продажи. */
    PRODUCT_UNAVAILABLE("product_unavailable"),

    /** Магазин ответил ошибкой. */
    STORE_ERROR("store_error"),

    /**
     * Магазин подтвердил покупку, а живой записи о ней не отдал — ни в ответе, ни в переспросе.
     *
     * Отказом это не является и словами отказа называться не может: деньги могли быть списаны
     * (П-7). Отдельное значение нужно ровно за этим — за фразой, которая не врёт ни в ту,
     * ни в другую сторону.
     */
    CONFIRMED_UNREADABLE("confirmed_unreadable"),
}
