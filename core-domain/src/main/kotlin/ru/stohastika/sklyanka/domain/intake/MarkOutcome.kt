package ru.stohastika.sklyanka.domain.intake

import ru.stohastika.sklyanka.domain.model.Intake

/**
 * Что случилось с приёмом при попытке его отметить.
 *
 * Отказ не бросается исключением намеренно: проигравшая отметка — штатный ход событий
 * (ЧАС-22), а не ошибка. Человеку она не показывается вовсе, поэтому вызывающему нужен
 * не текст ошибки, а состояние приёма — то, которое человек и увидит на экране.
 */
sealed interface MarkOutcome {

    /** Приём после операции — то, что показывается человеку в любом исходе. */
    val intake: Intake?

    /**
     * Отметка состоялась — записана впервые или заместила более раннюю.
     *
     * Общий предикат точек публикации окна отмены (SKL-30): `Ignored` и `NotFound` —
     * не новое действие человека, и окно не открывают.
     */
    val isCompleted: Boolean
        get() = this is Applied || this is Superseded

    /** Приём был ожидающимся, отметка записана. */
    data class Applied(override val intake: Intake) : MarkOutcome

    /**
     * Приём уже был отмечен, но пришедшая отметка сделана раньше записанной — поля
     * отметки заменены (ПР-3).
     *
     * Второй записи не появляется: [intake] и [replaced] — один и тот же приём
     * до и после замены (ПР-2, НФТ-10).
     */
    data class Superseded(override val intake: Intake, val replaced: Intake) : MarkOutcome

    /**
     * Отметка отброшена: приём уже отмечен, и пришедшая отметка не раньше записанной.
     *
     * Это и есть идемпотентность по `intake_id` (ПР-2, ИНВ-19, НАП-32) и единственный
     * ответ на попытку исправить отметку, пока ОВ-6 не решён.
     */
    data class Ignored(override val intake: Intake, val reason: IgnoreReason) : MarkOutcome

    /** Приёма с таким идентификатором нет: запись удалена перепланированием или переносом данных. */
    data object NotFound : MarkOutcome {
        override val intake: Intake? get() = null
    }
}

/** Почему отметка отброшена. Уходит в журнал служебным кодом (`TDD.md §9`). */
enum class IgnoreReason(val code: String) {
    /** Тот же источник отметил приём второй раз: повторное нажатие на карточке. */
    ALREADY_MARKED("already_marked"),

    /** Отметка другого источника опоздала по времени действия (ЧАС-22). */
    RACE_LOSER("race_loser"),
}

/** Что сделать с остатком упаковки вслед за отметкой (ПР-5). */
enum class StockEffect {
    /** Остаток не трогается: осознанный пропуск и автоматический пропуск (решение SKL-12). */
    NONE,

    /** Списать дозу одного приёма. */
    DECREMENT,

    /**
     * Вернуть списанную дозу: замещающая отметка увела результат из «принято».
     *
     * Без возврата списание переставало бы быть однократным (ЧАС-23): остаток отражал бы
     * проигравшую отметку, а история — победившую.
     */
    RESTORE,
}

/**
 * Решение чистого правила перехода — что именно записать, до всякого хранилища.
 *
 * Отделено от [MarkOutcome] потому, что записывает не домен: проверка статуса и запись
 * обязаны быть одной транзакцией (ЧАС-24), и решение принимается **внутри** неё.
 */
sealed interface MarkDecision {

    /** Записать новые поля отметки. [superseded] отличает замещение от первой отметки. */
    data class Write(val intake: Intake, val stock: StockEffect, val superseded: Boolean) : MarkDecision

    /** Не трогать запись. */
    data class Keep(val intake: Intake, val reason: IgnoreReason) : MarkDecision
}

/**
 * Решение чистого правила отмены — что именно записать, до всякого хранилища (SKL-30).
 *
 * Отделено от [MarkDecision] потому, что отмена — не отметка: она не несёт ни результата,
 * ни момента действия, ни источника и не участвует в правиле первенства (ПР-3).
 */
sealed interface UndoDecision {

    /** Записать приём обратно ожидающимся и (у TAKEN) вернуть дозу. */
    data class Revert(val intake: Intake, val stock: StockEffect) : UndoDecision

    /** Не трогать запись: отменять нечего. */
    data class Keep(val intake: Intake) : UndoDecision
}
