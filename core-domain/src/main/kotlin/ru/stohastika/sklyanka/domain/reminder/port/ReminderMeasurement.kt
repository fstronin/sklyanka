package ru.stohastika.sklyanka.domain.reminder.port

/**
 * Режим измерения пилота (SKL-85, ADR-0011/ПМ-20).
 *
 * Это не продуктовая настройка, а измерительный инструмент: в обычной и релизной сборке
 * переключателя варианта нет вовсе, и сохранённое значение на планирование не влияет.
 * Доступность режима решает сборка, а не состояние данных.
 */
interface ReminderMeasurement {

    /** Доступен ли в этой сборке режим измерения: `false` — обычная сборка. */
    fun available(): Boolean
}
