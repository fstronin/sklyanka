package ru.stohastika.sklyanka.domain.reminder.port

import ru.stohastika.sklyanka.domain.reminder.AlarmKind

/**
 * Настройки напоминания из `design/screens/Settings.dc.html`.
 *
 * Экран настроек — SKL-20; здесь только значения. Ключей тихих часов в этом типе нет
 * и заготовки под них не будет: решение по НАП-28 не принято, а настройка, глушащая
 * напоминание, прямо противоречит НАП-1.
 */
data class ReminderSettingsValues(
    /** «Настойчивое напоминание · Повторить, если не отметили». По умолчанию выключено. */
    val persistentEnabled: Boolean = false,
    /**
     * «Отложить на» — интервал в минутах, по умолчанию 15.
     *
     * Один интервал на два смысла: подпись кнопки откладывания и период проверки условия
     * повтора (НАП-25). Два разных интервала в одном экране настроек человек не разведёт.
     */
    val snoozeMinutes: Int = DEFAULT_SNOOZE_MINUTES,
    /**
     * Вариант измерения пилота (SKL-85, ПМ-20).
     *
     * Значение по умолчанию — надёжный механизм. В обычной сборке поле инертно:
     * переключателя нет, а `EffectiveAlarmStrategy` не читает сохранённое значение.
     */
    val alarmStrategy: AlarmKind = AlarmKind.ALARM_CLOCK,
) {
    companion object {
        const val DEFAULT_SNOOZE_MINUTES: Int = 15
    }
}

/**
 * Настройка напоминания как предмет записи в журнал (НАП-14).
 *
 * Код уходит в журнал служебной строкой вместе с новым значением: по записи в диагностике
 * должно быть видно не только «настройки менялись», но и **что** стало другим — иначе
 * запись не отвечает на единственный вопрос, ради которого журнал существует.
 */
enum class ReminderSettingKey(val code: String) {
    /** «Настойчивое напоминание · Повторить, если не отметили» (НАП-25). */
    PERSISTENT_ENABLED("persistent_reminder_enabled"),

    /** «Отложить на» — интервал откладывания и период проверки повтора (НАП-30). */
    SNOOZE_MINUTES("snooze_minutes"),

    /**
     * Вариант измерения пилота — доступен только в измерительной сборке (SKL-85).
     *
     * След `alarm_strategy=<код>` пишется при смене варианта: окна измерения не имеют
     * права пересекаться, и смена варианта — такое же событие перепланирования, как
     * правка расписания (НАП-11, НАП-14).
     */
    ALARM_STRATEGY("alarm_strategy"),
    ;

    /** Служебная строка записи журнала: `persistent_reminder_enabled=true`. */
    fun trace(value: Any): String = "$code=$value"
}

/**
 * Чтение и запись настроек напоминания. Реализация — `core-data` (DataStore).
 *
 * **След в журнале оставляет реализация этого порта** (НАП-14, `ReminderEvent.SETTINGS_CHANGED`).
 * Место выбрано не из удобства: настройка меняется с экрана настроек, а в дальнейшем будет
 * меняться из онбординга и при загрузке файла переноса. Запись со стороны вызывающего
 * означала бы след при одном пути изменения и молчание при остальных, то есть журнал,
 * которому нельзя верить. Проход мимо порта невозможен: хранилище настроек ниже него.
 */
interface ReminderSettings {

    suspend fun read(): ReminderSettingsValues

    suspend fun setPersistentEnabled(enabled: Boolean)

    suspend fun setSnoozeMinutes(minutes: Int)

    /**
     * Смена варианта измерения пилота (SKL-85).
     *
     * В обычной сборке вызов недостижим: переключатель существует только при
     * `ReminderMeasurement.available()`.
     */
    suspend fun setAlarmStrategy(kind: AlarmKind)
}
