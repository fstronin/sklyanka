package ru.stohastika.sklyanka.domain.transfer

/**
 * Нормализация названия и имени профиля для сопоставления (ПЕР-19, ПЕР-20).
 *
 * Четыре действия и ровно они: обрезка краёв, схлопывание внутренних пробелов, нижний
 * регистр, «ё» → «е». Список не произвольный — это способы написать одно и то же
 * название, встречающиеся в реальном вводе: «Магний B6 » и «магний  b6» — одно лекарство,
 * а «Магний B6 форте» — другое.
 *
 * Дальше нормализация не идёт намеренно. Снятие латиницы, похожей на кириллицу
 * («B6» против «В6»), склеило бы два разных препарата, а это медицинские данные:
 * лишний вопрос человеку дешевле молча слитой истории.
 */
object TransferNames {

    private val WHITESPACE = Regex("\\s+")

    fun normalize(raw: String): String = raw
        .trim()
        .replace(WHITESPACE, " ")
        .lowercase()
        .replace('ё', 'е')
}
