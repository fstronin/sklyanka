package ru.stohastika.sklyanka.domain.intake

import java.time.LocalDateTime

/**
 * Окно приёма: до какого момента ожидающийся приём ещё можно отметить (ПР-1, НАП-35).
 *
 * Это **параметр предметной области**, а не константа в коде: граница не согласована
 * с заказчиком (ОВ-4), и смена решения обязана быть заменой реализации, а не правкой
 * переходов. Ни один переход не имеет права знать, чему равна граница, — он только
 * спрашивает её здесь.
 *
 * Граница считается от суток самого приёма, а не от момента проверки: приём в 23:55
 * истекает в конце своих суток, приём в 00:05 — в конце следующих (НФТ-37).
 */
fun interface IntakeWindow {

    /**
     * Момент, начиная с которого приём, назначенный на [scheduledAt], считается
     * пропущенным без отметки.
     *
     * Ровно на границе приём ещё ожидается: сравнение идёт «не раньше границы»,
     * то есть в 23:59 приём жив, а в 00:00 — уже нет.
     */
    fun deadlineFor(scheduledAt: LocalDateTime): LocalDateTime

    /**
     * Верхняя (исключительная) граница выборки кандидатов на перевод в «пропущено
     * без отметки»: приёмы, назначенные позже неё, заведомо не просрочены.
     *
     * Существует ради запроса к хранилищу: выбрать всё ожидающееся и проверять каждую
     * запись в домене — значит с ростом истории читать всю таблицу. Значение по
     * умолчанию — сам момент проверки: окно не может истечь раньше назначенного времени.
     * Реализация вправе сузить границу до своей, более дешёвой для индекса.
     */
    fun candidateBound(now: LocalDateTime): LocalDateTime = now
}

/**
 * Принятое до ответа по ОВ-4 значение: отметка принимается до конца суток приёма.
 *
 * Цена решения известна и записана в `docs/tasks/SKL-07/task.md`: «принято» в 23:50
 * для приёма на 08:00 попадает в статистику как принятое вовремя. Обратный вариант —
 * фиксированный интервал — показывал бы пропуск там, где человек лекарство принял.
 */
class EndOfDayIntakeWindow : IntakeWindow {

    override fun deadlineFor(scheduledAt: LocalDateTime): LocalDateTime =
        scheduledAt.toLocalDate().plusDays(1).atStartOfDay()

    /**
     * Просрочены только приёмы прошлых суток: сегодняшние живут до полуночи,
     * какое бы время у них ни стояло.
     */
    override fun candidateBound(now: LocalDateTime): LocalDateTime = now.toLocalDate().atStartOfDay()
}
