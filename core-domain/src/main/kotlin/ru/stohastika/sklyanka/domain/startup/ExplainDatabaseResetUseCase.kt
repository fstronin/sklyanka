package ru.stohastika.sklyanka.domain.startup

import ru.stohastika.sklyanka.domain.time.TimeSource

/**
 * Объяснение сброса данных после повреждения базы (МГ-8, Р-87 п. 2, RT-2).
 *
 * Платформа стирает повреждённый файл базы и открывает новый — приложение
 * продолжает работать, но данные человека пропали. Молчаливое пустое приложение
 * после потери — худшая форма отказа (П-7): человек не понимает, куда делись
 * лекарства и история. Поэтому пересоздание базы при живой отметке «база жила»
 * становится событием, и «Сегодня» один раз показывает объяснение.
 *
 * Одноразовость держится двумя отметками вне файла базы: момент события и момент
 * его закрытия. Закрытое объяснение не возвращается, а новое пересоздание пишет
 * новый момент события — и объяснение показывается снова. Чистая установка
 * молчит: отметки жизни нет, терять было нечего. Очистка данных приложения
 * стирает обе отметки вместе с настройками — ложного объяснения нет.
 */
class ExplainDatabaseResetUseCase(private val life: DatabaseLifeStore, private val time: TimeSource) {

    /**
     * Старт после успешного открытия базы: записать событие пересоздания, если
     * оно случилось на жившей базе, отметить жизнь и вернуть «показывать ли
     * объяснение». Зовётся один раз на процесс из состояния экрана «Сегодня».
     */
    suspend fun explanationOnStartup(): Boolean {
        if (life.consumeDatabaseRecreated() && life.hadLife()) {
            life.recordResetEventAt(time.now().toEpochMilli())
        }
        // Отметка ставится один раз в жизни: повторный старт не обязан писать в настройки.
        if (!life.hadLife()) {
            life.markLife()
        }
        val event = life.resetEventAt() ?: return false
        return event != life.resetEventAcknowledgedAt()
    }

    /** «Закрыть» на баннере: это событие объяснено и больше не показывается. */
    suspend fun dismissExplanation() {
        life.resetEventAt()?.let { life.acknowledgeResetEventAt(it) }
    }
}
