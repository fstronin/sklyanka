package ru.stohastika.sklyanka.domain.transfer

/**
 * Причина отказа от файла (ПЕР-28, ПЕР-29).
 *
 * Причина — код, а не текст: текст для человека собирает экран из ресурсов (НФТ-42),
 * а код уходит в журнал. Кодов несколько, хотя сообщений человеку два: разбор жалобы
 * «файл не грузится» без причины отказа невозможен, а сети и телеметрии нет.
 *
 * Разделение [FUTURE_FORMAT] и всех остальных — суть ОВ-65: файл, написанный будущей
 * версией схемы, обязан отличаться от испорченного файла, иначе повышение версии формата
 * будет выглядеть как порча данных.
 */
enum class TransferRejectReason(val code: String) {
    /** Не читается как JSON (ПЕР-28). */
    NOT_JSON("not_json"),

    /** Нет поля-опознавателя (ПЕР-6, ПЕР-28). */
    MISSING_MARKER("missing_marker"),

    /** Опознаватель чужой: валидный JSON другого приложения (ПЕР-28). */
    FOREIGN_MARKER("foreign_marker"),

    /** Версия формата отсутствует, не число или меньше единицы (ПЕР-7). */
    INVALID_VERSION("invalid_version"),

    /** Версия формата выше поддерживаемой (ПЕР-29, МГ-5). */
    FUTURE_FORMAT("future_format"),

    /** Нет обязательного раздела (ПЕР-5, ПЕР-28). */
    MISSING_SECTION("missing_section"),

    /** Значение поля не разбирается: дата, число, время (ПЕР-28). */
    INVALID_VALUE("invalid_value"),

    /** Идентификатор повторяется внутри раздела: связи файла перестают быть однозначными. */
    DUPLICATE_ID("duplicate_id"),

    /** Ссылка указывает в пустоту: приём без лекарства, лекарство без профиля (ПЕР-28, ИНВ-12). */
    BROKEN_LINK("broken_link"),

    /** Своего профиля в файле нет или их больше одного (ИНВ-1). */
    SELF_PROFILE("self_profile"),

    /** Запись не проходит правила предметной области (ИНВ-4 … ИНВ-17). */
    INVALID_RECORD("invalid_record"),
}

/**
 * Отказ с техническим пояснением одной строкой (ПЕР-28).
 *
 * [detail] — имя раздела или поля, на котором разбор споткнулся, и только оно.
 * Содержимого файла здесь нет ни в каком виде: содержимое — медицинские данные,
 * а отказ попадает и на экран, и в журнал (НФТ-19).
 */
data class TransferReject(val reason: TransferRejectReason, val detail: String = "") {

    /** Строка для журнала: код причины и место отказа, без значений. */
    val logDetail: String get() = if (detail.isEmpty()) reason.code else "${reason.code}:$detail"
}
