package ru.stohastika.sklyanka.domain.reminder.port

import java.time.Instant

/**
 * Память о поставленных будильниках.
 *
 * Порт существует по единственной причине: Android не позволяет перечислить будильники
 * приложения. Пересборка окна обязана знать, что уже стоит и на когда, — иначе она либо
 * снимает и ставит всё заново при каждом запуске процесса, либо оставляет осиротевшие
 * срабатывания от приёмов, которых больше нет (НАП-9).
 *
 * Правда о существовании будильника остаётся за платформой: реализация [AlarmGateway]
 * сверяет каждую запись с системой. Этот порт — только сохранённое «что мы ставили»,
 * и его потеря не страшна: следующая пересборка восстановит набор.
 */
interface AlarmRegistry {

    suspend fun all(): Map<String, Instant>

    suspend fun put(intakeId: String, at: Instant)

    suspend fun remove(intakeId: String)
}
