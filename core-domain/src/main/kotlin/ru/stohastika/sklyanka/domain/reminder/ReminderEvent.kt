package ru.stohastika.sklyanka.domain.reminder

import java.time.Instant

/**
 * Вид записи журнала срабатываний (НАП-4, НФТ-50, `TDD.md §11.1`).
 *
 * Журнал напоминаний ведётся отдельно от журнала операций над данными (`OpEvent`): вопросы
 * у них разные. Там — «кто и когда отметил приём», здесь — «почему напоминание не пришло».
 */
enum class ReminderEvent(val code: String) {
    /** Будильник сработал: плановое и фактическое время, отклонение. */
    FIRED("fired"),

    /** Уведомление предъявлено человеку — это и есть «напоминание сработало» (НАП-2). */
    SHOWN("shown"),

    /** Показ подавлен: приём уже отмечен, окно истекло или нет разрешения. */
    SUPPRESSED("suppressed"),

    /** Повтор настойчивого напоминания (НАП-25). */
    REPEATED("repeated"),

    /** Человек отложил напоминание (НАП-30). */
    SNOOZED("snoozed"),

    /**
     * Судьба отложенного срабатывания (SKL-35, ОВ-75).
     *
     * Поле `reason` различает исход: `restored` — пересборка поставила будильник
     * на момент из записи (в том числе после перезагрузки), `dropped` — запись снята,
     * потому что приём больше не ожидается (отмечен, истёк, архив, без дублирования).
     * Запись пишется только когда состояние действительно изменилось: пересборка
     * на неизменных данных не превращает журнал в журнал якорей.
     */
    DEFERRED("deferred"),

    /** Пересборка окна с причиной и числом снятых и поставленных будильников (НАП-14). */
    RESCHEDULED("rescheduled"),

    /**
     * Изменена настройка напоминания (НАП-14).
     *
     * След оставляет реализация порта настроек, а не экран: настройка меняется из настроек,
     * из онбординга и при загрузке файла переноса, и запись со стороны каждого вызывающего
     * дала бы событие, которого нет при изменении другим путём.
     */
    SETTINGS_CHANGED("settings_changed"),

    /** Автоперевод в «пропущено без отметки»; уведомлений не порождает (НАП-34). */
    MISSED_SWEEP("missed_sweep"),

    /**
     * Ротация журнала: сколько записей удалено и по какому порогу (ПМ-30).
     *
     * Запись оставляет факт уборки, чтобы сокращение журнала не выглядело потерей
     * данных; содержимого в ней нет — только числа ([ReminderLogRotation]).
     */
    ROTATED("rotated"),

    /** Обнаружен перерыв в напоминаниях — принудительная остановка приложения (НАП-38). */
    OUTAGE("outage"),

    /**
     * Среда измерения изменилась (SKL-85, НФТ-51).
     *
     * Запись `reason` несёт нагрузку `ключ=значение`: тип действующего будильника,
     * вендор, бренд, версия Android, сборка прошивки, энергосбережение. Записи среды
     * задают границы окон A/B-прогона пилота.
     */
    ENVIRONMENT("environment"),

    /**
     * Самопроверка доставки (ПМ-21, ОВ-108): не приём, а испытание пути напоминания.
     *
     * Отдельный вид, а не `FIRED`/`SHOWN` с пометкой: отличимая запись обязана не попадать
     * ни в «Последнее напоминание», ни в недельные сводки, ни в обнаружение перерыва —
     * и не попадает по построению, без правок каждого читателя. Идентификаторы приёма,
     * лекарства и профиля в записях проверки не заполняются: медицинских данных в них нет
     * (НФТ-19, НФТ-50).
     */
    DELIVERY_CHECK("delivery_check"),
}

/**
 * Коды исхода записи [ReminderEvent.DELIVERY_CHECK] (SKL-86, ОВ-108).
 *
 * Служебные строки в поле `reason`, тем же приёмом, что [DeferredReason]: подвид записи
 * читается журналом и диагностикой, но не образует второго перечисления в схеме.
 */
object DeliveryCheckReason {

    /** Проверка назначена человеком: `scheduledAt` — момент тестового срабатывания. */
    const val SCHEDULED = "scheduled"

    /** Тестовый будильник сработал. */
    const val FIRED = "fired"

    /** Тестовое уведомление предъявлено человеку. */
    const val SHOWN = "shown"

    /** Срабатывания не было или показа не было — тестовое напоминание не дошло. */
    const val NOT_DELIVERED = "not_delivered"

    /** Приложение было открыто в момент срабатывания: фоновый путь не проверялся. */
    const val NOT_COMPLETED = "not_completed"

    /** Человек отменил проверку до срабатывания. */
    const val CANCELLED = "cancelled"
}

/**
 * Коды исхода записи [ReminderEvent.DEFERRED] (SKL-35, `TDD.md §5.3`).
 *
 * Служебные строки в поле `reason`, а не отдельный вид события: различие исходов —
 * «состояние восстановлено» против «запись снята» — читается диагностикой и разбирается
 * по журналу, но не образует второго перечисления в схеме.
 */
object DeferredReason {

    /** Пересборка поставила будильник на момент из записи — в том числе после перезагрузки. */
    const val RESTORED = "restored"

    /** Запись снята: приём больше не ожидается. */
    const val DROPPED = "dropped"
}

/**
 * Одна запись журнала срабатываний.
 *
 * Полей много и они почти все необязательные: запись о пересборке окна и запись о показе
 * отвечают на разные вопросы, а два типа записей в одном журнале пришлось бы сводить
 * в диагностике вручную. Названий лекарств, дозировок и имён профилей здесь нет
 * ни в одном поле (НФТ-19).
 */
@Suppress("LongParameterList")
data class ReminderLogEntry(
    /**
     * Момент записи в UTC.
     *
     * Идентификатора записи в доменном типе нет: он нужен только хранилищу как первичный
     * ключ и присваивается там. Диагностика читает записи временем и видом, а не ключом.
     */
    val occurredAt: Instant,
    val event: ReminderEvent,
    val intakeId: String? = null,
    val medicationId: String? = null,
    val profileId: String? = null,
    /** Плановое время приёма как момент: журнал сравнивает его с фактическим (НАП-2). */
    val scheduledAt: Instant? = null,
    val firedAt: Instant? = null,
    /** `firedAt − scheduledAt`; отрицательное значение — дефект планирования (НАП-2). */
    val deviationSeconds: Long? = null,
    val channel: ReminderChannel? = null,
    val delivered: Boolean? = null,
    /** Причина пересборки или код подавления. Служебная строка, не текст для человека. */
    val reason: String? = null,
    val alarmsCancelled: Int? = null,
    val alarmsScheduled: Int? = null,
    val attempt: Int? = null,
    /** Интервал откладывания в минутах — только у записи [ReminderEvent.SNOOZED]. */
    val minutes: Int? = null,
    val watchResult: String? = null,
)
