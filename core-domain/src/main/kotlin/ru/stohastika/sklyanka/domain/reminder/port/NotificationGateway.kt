package ru.stohastika.sklyanka.domain.reminder.port

import ru.stohastika.sklyanka.domain.reminder.ReminderCard
import ru.stohastika.sklyanka.domain.reminder.ReminderChannel
import ru.stohastika.sklyanka.domain.reminder.ReminderSlot
import java.time.LocalDateTime

/**
 * Показ и снятие напоминания (НАП-29, НАП-36).
 *
 * Порт в домене, реализация в `app`: уведомления и каналы — платформенное.
 */
interface NotificationGateway {

    /**
     * Показать карточку приёма полноэкранным уведомлением.
     *
     * Один слот — одно уведомление: два приёма на 14:00 показываются одной карточкой
     * со списком, а не двумя карточками подряд (НАП-36). Повторный показ того же слота
     * обновляет уже показанное уведомление.
     */
    suspend fun show(card: ReminderCard, channel: ReminderChannel)

    /** Снять карточку слота: отметка любым способом, истечение окна, откладывание. */
    suspend fun cancel(slot: ReminderSlot)

    /**
     * Показана ли сейчас карточка этого слота.
     *
     * Нужно, чтобы отметка приёма не порождала уведомления. Отметка с экрана «Сегодня»
     * проходит тем же путём, что отметка с карточки напоминания (единственная точка
     * отметки), и без этого вопроса отметка одного из двух приёмов на 14:00 показала бы
     * карточку о втором — уведомление, которого человек не просил и не ждал.
     */
    suspend fun isShown(slot: ReminderSlot): Boolean

    /**
     * Снять показанные карточки, приёмы которых больше не ожидаются.
     *
     * Нужно там, где приём перестал быть ожидающимся не действием человека, а сам:
     * истекло окно и проход перевёл его в пропущенные (НАП-34). Новых уведомлений
     * операция не порождает — иначе телефон, включённый после суток простоя, выдал бы
     * очередь карточек о том, что всё пропущено (И-10).
     */
    suspend fun retainOnly(pendingIntakeIds: Set<String>)

    /** Разрешены ли уведомления (НАП-15). Читается из системы при каждом обращении (НФТ-52). */
    fun areNotificationsEnabled(): Boolean

    /**
     * Показать карточку самопроверки обычным каналом (SKL-86, ОВ-108).
     *
     * Карточка не притворяется приёмом: у неё нет состава слота и идентификаторов приёма,
     * поэтому [retainOnly] её не находит и не снимает — снятие у неё отдельный вызов.
     * Адрес у карточки один, показ заменяет предыдущий тестовый показ.
     */
    suspend fun showDeliveryCheck(at: LocalDateTime)

    /**
     * Показана ли сейчас карточка проверки.
     *
     * Вызов показа ещё не предъявление: система могла молча его уронить, и проверка
     * обязана отличать «не дошло» от «не показывали» (НАП-2, SKL-86).
     */
    suspend fun isDeliveryCheckShown(): Boolean

    /** Снять карточку проверки: «Понятно», отмена проверки или её завершение. */
    suspend fun cancelDeliveryCheck()
}
