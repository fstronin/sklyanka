package ru.stohastika.sklyanka.domain.log

/**
 * События журнала критичных операций над данными (TDD §10.3).
 *
 * Это след операций над **данными**; журнал срабатываний напоминаний (НФТ-50, НФТ-51)
 * заводит SKL-13 и живёт отдельно — вопросы у них разные.
 */
enum class OpEvent {
    /** Отметка приёма с её источником — главный вопрос разбора «кто и когда отметил». */
    INTAKE_MARKED,

    /** Повторная отметка отброшена: без следа гонка часов и телефона выглядит как пропавшая отметка (ПР-3). */
    INTAKE_MARK_IGNORED,

    /**
     * Отметка замещена более ранним действием (ПР-3, ЧАС-22).
     *
     * Отдельное событие, а не INTAKE_MARKED: запись при замещении меняется второй раз,
     * и без следа разбор жалобы «отметка была в 08:05, а стала 08:03» невозможен.
     */
    INTAKE_MARK_SUPERSEDED,

    /**
     * Отметка отменена человеком в коротком окне (ОВ-6/ОВ-81, SKL-30).
     *
     * Отдельное событие, а не стирание INTAKE_MARKED: без следа жалоба «остаток вырос
     * и приём снова ожидается» неразбираема, а пара с INTAKE_MARKED восстанавливает
     * историю однозначно. Пишется по каждому приёму отменённого действия.
     */
    INTAKE_MARK_UNDONE,

    /**
     * Запись «по потребности» снята человеком в коротком окне (Р-46, SKL-127).
     *
     * Отдельное событие рядом с INTAKE_MARK_UNDONE: исходы разные — плановая отметка
     * возвращается в «ожидается», а запись «по потребности» снимается, — и разбор
     * «куда делся приём» по общему событию путался бы между двумя причинами.
     */
    INTAKE_REVOKED,

    /**
     * Ожидающийся приём переведён в «пропущено без отметки» по истечении окна (ПР-1).
     *
     * Пишется пачкой с причиной запуска: резкий рост доли автоматических пропусков
     * означает, что напоминания не доходят, а не что человек стал забывчив.
     */
    INTAKE_AUTO_MISSED,

    /**
     * Групповая отметка одновременных приёмов одним нажатием (ОВ-32, SKL-08).
     *
     * Отдельное событие рядом с INTAKE_MARKED, а не вместо него: каждый приём группы
     * по-прежнему оставляет свой след, а это — след самой операции. Без него разбор
     * жалобы «я отметил один приём, а списалось три лекарства» упирается в три
     * одинаковых отметки в одну и ту же секунду и не отличает их от совпадения.
     */
    INTAKE_GROUP_MARKED,

    /** Создан приём по потребности (ПР-4): записи «ожидается» у него не бывает. */
    INTAKE_PRN_CREATED,

    /** Отказ по суточному лимиту приёмов по потребности (ИНВ-17): в контексте лимит и счёт за сутки. */
    INTAKE_PRN_LIMIT_REACHED,

    /** Списание остатка: жалоба «остаток не сходится» разбирается только по истории списаний. */
    STOCK_DECREMENTED,

    /**
     * Возврат списанной дозы: замещающая отметка увела результат из «принято».
     *
     * Без этой записи остаток выглядел бы выросшим сам по себе (ЧАС-23 требует, чтобы
     * списание было ровно одно, а не чтобы их было два в разные стороны молча).
     */
    STOCK_RESTORED,

    /**
     * Человек пополнил остаток вручную (ОВ-13).
     *
     * Значения до и после — единственный способ отличить «счётчик разошёлся с упаковкой»
     * от «человек ошибся при вводе»: истории пополнений приложение не хранит.
     */
    STOCK_REFILLED,

    /** Предупреждение о покупке появилось: в контексте порог и число оставшихся дней (ПР-13). */
    STOCK_WARNING_RAISED,

    /**
     * Предупреждение о покупке снято.
     *
     * Без парной записи жалоба «плашка висела и пропала сама» неразбираема: состояние
     * предупреждения нигде не хранится, оно каждый раз вычисляется заново.
     */
    STOCK_WARNING_CLEARED,

    /** Курс отправлен в архив. */
    MEDICATION_ARCHIVED,

    /**
     * Лекарство мягко удалено (ПМ-24, ПР-14).
     *
     * Единственный след удаления в журнале операций: момент, идентификаторы и признак
     * того, что запись скрыта; число снятых приёмов пишет планировщик своим событием
     * (`INTAKES_REVOKED`). Названия лекарств в записи нет (НФТ-19).
     */
    MEDICATION_DELETED,

    /**
     * Удаление отменено в коротком окне (ПМ-24 п. 5).
     *
     * Парная запись к `MEDICATION_DELETED`: без неё жалоба «лекарство вернулось само»
     * неразбираема. Возврат приёмов и будильников пишет планировщик своими событиями.
     */
    MEDICATION_DELETED_UNDONE,

    /** Курс заведён: единственная точка входа данных во всё приложение (SKL-09). */
    MEDICATION_CREATED,

    /**
     * Курс исправлен.
     *
     * В контексте — имена изменившихся полей, а не их значения: «изменились times
     * и dose_amount» диагностически достаточно и не содержит медицинских данных (НФТ-19).
     */
    MEDICATION_UPDATED,

    /**
     * Форма отказала в сохранении.
     *
     * Жалоба «приложение не даёт сохранить лекарство» разбирается только по этому следу:
     * в контексте — коды нарушенных правил, без введённых человеком значений.
     */
    MEDICATION_SAVE_REJECTED,

    /** Порождены приёмы по расписанию: доказательство того, что они были созданы и сколько. */
    INTAKES_GENERATED,

    /**
     * Сняты ожидающиеся приёмы, переставшие соответствовать расписанию (SKL-06).
     *
     * Отдельное событие, а не поле у INTAKES_GENERATED: вопрос «куда делся вечерний приём»
     * разбирается именно по нему, и устойчиво ненулевое число снятых при нетронутом
     * расписании — признак дефекта генерации, а не нормальной работы.
     */
    INTAKES_REVOKED,

    /** Переключение активного профиля — след для разбора отметки «не в том профиле» (ПРФ-10). */
    PROFILE_SWITCHED,

    /**
     * Профиль заведён (ПРФ-9).
     *
     * В контексте — идентификатор и начальное значение дублирования напоминаний,
     * без имени профиля: имя — такие же персональные данные, как название лекарства
     * (НФТ-19).
     */
    PROFILE_CREATED,

    /**
     * Переключено дублирование напоминаний профиля (ПРФ-5, НАП-12).
     *
     * Отдельное событие: вопрос «почему у меня перестал звонить телефон в 09:00»
     * разбирается только по нему, а связанное перепланирование пишет свои числа
     * в журнал напоминаний (НАП-14).
     */
    PROFILE_MIRROR_CHANGED,

    /**
     * Активный профиль восстановлен принудительно (ПРФ-31).
     *
     * Сохранённое значение указывало на профиль, которого больше нет: так бывает после
     * загрузки файла переноса в режиме «заменить всё». Без этой записи смена профиля
     * «сама собой» неразбираема, а для человека она выглядит как потерянные данные.
     */
    PROFILE_ACTIVE_RESTORED,

    /**
     * Профиль удалён вместе с лекарствами, архивом, историей и отложенными
     * срабатываниями (ОВ-7, SKL-36).
     *
     * Единственный след разрушительной операции: в контексте только идентификатор
     * профиля — ни имени, ни названий лекарств (НФТ-19). Запись переживает удаление:
     * у журнала нет внешних ключей, и разбирать «куда делся профиль» больше не по чему.
     */
    PROFILE_DELETED,

    /** Применён перенос данных: самая разрушительная операция, след обязан пережить её саму. */
    TRANSFER_APPLIED,

    /**
     * Выгрузка завершена (SKL-19, `TDD.md §10.1`).
     *
     * В контексте — числа записей и размер файла в байтах, без пути, выбранного человеком:
     * приложение не ведёт учёта того, куда ушёл файл (ПЕР-36, НФТ-19).
     */
    TRANSFER_EXPORTED,

    /**
     * Выгрузка не состоялась: нет места, запись сорвалась (ПЕР-31, ПЕР-32).
     *
     * Отдельное событие, а не поле у TRANSFER_EXPORTED: жалоба «я сохранял файл,
     * а его нет» разбирается именно по нему, и молчаливого отказа здесь быть не должно.
     */
    TRANSFER_EXPORT_FAILED,

    /**
     * Файл выбран и разобран: режим, версия формата файла, числа из сводки (ПЕР-15 п. 2).
     *
     * Без этой записи невозможно отличить «человек передумал» от «приложение не дошло
     * до применения».
     */
    TRANSFER_FILE_ACCEPTED,

    /** Файл отклонён целиком: код причины и место отказа, без содержимого файла (ПЕР-28, ПЕР-29). */
    TRANSFER_FILE_REJECTED,

    /** Создана страховочная копия перед заменой всего (ПЕР-16 п. 3): момент, размер, числа. */
    TRANSFER_SAFETY_COPY,

    /**
     * Транзакция применения откатилась (ПЕР-27, ПЕР-31).
     *
     * Парная запись к TRANSFER_APPLIED. Их отсутствие обеих при следующем запуске и есть
     * доказательство того, что процесс убили посреди загрузки.
     */
    TRANSFER_ROLLED_BACK,

    /** Совпадения при слиянии разобраны: сколько найдено и сколько каких решений принято (ПЕР-22). */
    TRANSFER_MATCHES_RESOLVED,

    /** Применена миграция схемы: доказательство НФТ-9 на устройстве человека, а не только в тесте. */
    MIGRATION_APPLIED,

    /**
     * Проверка целостности базы выполнена (`ADR-0012` п. 4, SKL-94).
     *
     * В контексте — источник проверки (`migration` после перехода или `daily` по суточному
     * окну) и её исход: сообщение `quick_check` и число нарушенных ссылок. Находка
     * **сообщается, а не чинится**: автоматический ремонт запрещён (МГ-6), и без записи
     * находка была бы молчаливой.
     *
     * Медицинских данных в записи нет: `quick_check` говорит о таблицах и страницах файла,
     * не о людях (НФТ-19).
     */
    INTEGRITY_CHECKED,

    /** Отказ записи: НФТ-11 требует, чтобы отказ не был тихим. */
    DB_WRITE_FAILED,

    /** Незнакомое значение перечисления при чтении (МГ-6). */
    ENUM_UNKNOWN,

    /**
     * Приверженность за период посчитана: открытие истории и каждое переключение месяца
     * (SKL-18, `docs/archive/tasks/SKL-18/TDD.md §11`).
     *
     * В контексте — профиль, границы периода, число обработанных записей и длительность
     * расчёта. Длительность здесь не любопытство: НФТ-25 задаёт 300 мс на базе, заполненной
     * годом приёма, и подтвердить бюджет на устройстве человека больше нечем.
     *
     * Результата расчёта в записи нет: «86 %» рядом с `profile_id` — это медицинские
     * данные, просто агрегированные (НФТ-19).
     */
    HISTORY_PERIOD_CALCULATED,

    /**
     * Доля «принято вовремя» не посчитана: в периоде нет ни одного наступившего планового
     * приёма (Р-33).
     *
     * Запись существует, чтобы отсутствие плитки было отличимо от дефекта. Прежняя
     * формулировка «порог не согласован» ушла вместе с решением Р-21: порог согласован,
     * и причина одна — мерить нечего (например, профиль ведёт только приёмы
     * «по потребности»).
     */
    HISTORY_ON_TIME_NOT_MEASURED,

    /**
     * Отчёт врачу сформирован (SKL-18).
     *
     * В контексте — период, число записей и число лекарств в отчёте. Содержимого отчёта
     * в журнале нет: это медицинские данные целиком (НФТ-19).
     */
    DOCTOR_REPORT_BUILT,

    /**
     * Исход передачи отчёта: передан, сохранён, отменён человеком, отказ записи.
     *
     * Отмена системного диалога выглядит для человека так же, как ошибка, и без записи
     * жалоба «нажал, и ничего не произошло» неразбираема.
     */
    DOCTOR_REPORT_TRANSFERRED,

    /**
     * Подписка «Про» проверена при запуске (SKL-122, `ADR-0015` п. 1).
     *
     * В `detail` — исход ответа магазина: `owned`, `none` или `unavailable`. Отдельное
     * событие, а не отсутствие записи: жалоба «подписка была, а приложение её не видит»
     * разбирается только по тому, отвечал ли магазин вообще, — а «не отвечал» и «ответил,
     * что нет» выглядят на экране одинаково. Медицинских данных в записи нет (НФТ-19).
     */
    PRO_SUBSCRIPTION_CHECKED,

    /** Покупка подтверждена магазином; `detail` — идентификатор товара (SKL-122, Р-68 п. 1). */
    PRO_PURCHASED,

    /**
     * Магазин отказал в покупке; `detail` — код причины (SKL-122, Р-68 п. 6).
     *
     * Отдельно от `PRO_PURCHASE_CANCELLED`: «не прошло» и «человек передумал» — разные
     * вопросы поддержки, и различить их постфактум без записи нечем.
     */
    PRO_PURCHASE_REFUSED,

    /** Человек закрыл окно магазина, не заплатив (SKL-122, Р-68 п. 6): приложение молчит, журнал помнит. */
    PRO_PURCHASE_CANCELLED,

    /** Восстановление покупки подтверждено; `detail` — идентификатор товара или `unknown` (SKL-122, Р-67 п. 4). */
    PRO_RESTORED,

    /** Восстановить покупку не удалось; `detail` — код причины или `nothing_found` (SKL-122, Р-39). */
    PRO_RESTORE_FAILED,

    /** Человек ушёл в экран управления подписками магазина (SKL-122, Р-73 п. 1). */
    PRO_MANAGEMENT_OPENED,
}
