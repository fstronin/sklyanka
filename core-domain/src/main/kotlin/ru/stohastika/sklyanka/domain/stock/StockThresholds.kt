package ru.stohastika.sklyanka.domain.stock

/**
 * Набор порогов напоминания о покупке (ПМ-13, SKL-74).
 *
 * Порог «Напомнить о покупке» был жёстко задан числом 5 дней. Пяти дней мало: человек
 * не успевает в аптеку. Набор параметризуемый, значение по умолчанию — 7 дней.
 *
 * Это доменное правило («за сколько дней предупреждать»), а не оформление: оно не зависит
 * ни от Android, ни от Compose, и форма с тестами читают состав из одного места.
 * Диапазоном значений модель не ограничивается: файл переноса данных может принести любое
 * число, и подменять чужие данные нельзя (как со `strengthUnit`).
 */
object StockThresholds {

    /** Рабочий состав порогов, дни (ПМ-13). Единственное место, где задан набор. */
    val Options: List<Int> = listOf(3, 5, 7, 10, 14)

    /** Значение по умолчанию: 7 дней (ПМ-13). */
    const val DEFAULT_DAYS: Int = 7
}
