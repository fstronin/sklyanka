package ru.stohastika.sklyanka.domain.history

import java.time.LocalDateTime

/**
 * Доля приёмов, отмеченных в своё окно, — плитка «принято вовремя».
 *
 * Тип, а не число, потому что числа может не быть: мерить нечего, когда в периоде нет
 * ни одного наступившего планового приёма (Р-33). Плитка, показывающая выдуманное число, —
 * это число, которое человек покажет врачу.
 */
sealed interface OnTimeShare {

    /**
     * Доля отмеченных вовремя среди наступивших плановых приёмов (Р-21, Р-27).
     *
     * Числитель и знаменатель, а не одно отношение: подпись плитки для чтения с экрана
     * называет знаменатель («принято вовремя, 12 из 14 приёмов»), и второй раз считать
     * их на экране нечем — расчёт один.
     */
    data class Value(val onTime: Int, val due: Int) : OnTimeShare {

        /** Доля от нуля до единицы: числитель к знаменателю. */
        val share: Double get() = onTime.toDouble() / due

        val percent: Int get() = Math.round(share * PERCENT).toInt()

        /**
         * Доля посчитана, но при округлении к целому проценту даёт ноль (Р-27).
         *
         * Экран показывает её словами (`history_percent_less_than_one`), а не нулём:
         * «0 %» при состоявшихся приёмах — ложь, из-за которой метрике перестают верить.
         * Приговор не округляется: доля 1/250 — утверждение, что приём был, и «0 %»
         * стёрло бы его.
         */
        val lessThanOnePercent: Boolean get() = onTime > 0 && percent == 0

        private companion object {
            const val PERCENT = 100
        }
    }

    /**
     * Мерить нечего: ни одного наступившего планового приёма в периоде (Р-33).
     *
     * Плитка в этом состоянии не рисуется вовсе — прочерка у неё не существует, потому
     * что прочерк читается как поломка. Профиль может быть только «по потребности» —
     * у таких приёмов нет назначенного времени, и «вовремя» для них не определено (Р-27).
     */
    data object Absent : OnTimeShare
}

/**
 * Порог «вовремя» — параметр предметной области, а не константа в расчёте.
 *
 * Требование `docs/norm/04-behavior.md` §7 к окну приёма действует и здесь: «окно
 * должно быть параметром домена, а не константой в коде, чтобы решение можно было
 * заменить без переделки». Расчёт приверженности спрашивает правило и не знает,
 * чему равна граница: [`AdherenceCalculator`] принимает [Agreed] и никогда не считает
 * часы сам.
 *
 * **НАП-2 здесь неприменим.** Он определяет «вовремя» для срабатывания напоминания
 * (отклонение от 0 до +120 секунд) — там опаздывает приложение, здесь человек. Совпадение
 * слова в двух смыслах — ловушка, поэтому у этих понятий и имена разные: `ReminderDelay`
 * живёт в подсистеме напоминаний, а порог отметки — здесь.
 */
sealed interface OnTimeRule {

    /**
     * Правило отметки: приём «вовремя», если момент отметки попал в окно приёма.
     *
     * Оба момента — местные: назначенное время хранится локальным (НФТ-34), а момент
     * отметки переводится в местное время ровно в одном месте расчёта
     * ([AdherenceCalculator]).
     */
    fun interface Agreed : OnTimeRule {
        fun isOnTime(scheduledAt: LocalDateTime, actedAt: LocalDateTime): Boolean
    }

    companion object {

        /**
         * Окно «вовремя», действующее в продукте (Р-21): **±2 часа** вокруг назначенного
         * времени, симметрично.
         *
         * Ранняя отметка в окне считается вовремя: человек мог принять лекарство раньше —
         * это исполнение назначения, а не его нарушение. Границы включаются.
         *
         * Значение объявлено здесь, а не в сборке приложения: окно — часть смысла метрики,
         * и одно определение нужно и продукту (`app/di/HistoryModule.kt`), и стендам
         * приёмки, которые обязаны повторять продукт, а не пересказывать его. Расчёт
         * по-прежнему ничего не знает про два часа: он принимает это правило параметром.
         */
        val TwoHours: Agreed = Agreed { scheduledAt, actedAt ->
            !actedAt.isBefore(scheduledAt.minusHours(WINDOW_HOURS)) &&
                !actedAt.isAfter(scheduledAt.plusHours(WINDOW_HOURS))
        }

        /** Полуширина окна в часах (Р-21). */
        private const val WINDOW_HOURS = 2L
    }
}
