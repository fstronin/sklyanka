package ru.stohastika.sklyanka.domain.reminder.port

import java.time.Instant

/**
 * Точные будильники системы (НАП-5).
 *
 * Порт в домене, реализация в `app`: `AlarmManager` — это `android.*`, которого в домене
 * нет физически (НФТ-46). Домен при этом остаётся хозяином правил: что поставить, когда
 * снять и чем адресовать, решает он.
 *
 * Адрес будильника — `intake_id` (НАП-9): повторная постановка **заменяет** предыдущий
 * будильник, а не добавляет второй. Без этого перелёт назад или двойное перепланирование
 * дали бы два напоминания об одном приёме.
 */
interface AlarmGateway {

    /** Поставить или заменить будильник приёма. Только точный (НАП-5). */
    suspend fun schedule(intakeId: String, at: Instant)

    suspend fun cancel(intakeId: String)

    /**
     * Что действительно стоит в системе: идентификатор приёма → момент срабатывания.
     *
     * Моменты нужны, а не одни идентификаторы (в отличие от `TDD.md §5.3`): без них
     * пересборка не отличает «будильник уже стоит на верное время» от «стоит на старое»,
     * и правка расписания оставляла бы напоминание на прежний час. Возвращается
     * состояние системы, а не то, что домен когда-то просил поставить: расхождение
     * «в базе план есть, будильника нет» — это и есть отказ, который нужно увидеть.
     */
    suspend fun scheduled(): Map<String, Instant>

    /** Якорный будильник перепланирования (НАП-8). Адрес у него один, повторная постановка заменяет. */
    suspend fun scheduleAnchor(at: Instant)

    /**
     * Будильник границы суток (НАП-34).
     *
     * Отдельный адрес рядом с якорным: якорь пересобирает окно ночью, а этот будильник
     * срабатывает ровно в полночь и переводит неотмеченные приёмы прошедших суток
     * в пропущенные, снимая их карточки. Ждать до якоря нельзя — три часа в шторке
     * висело бы уведомление о приёме, который уже пропущен.
     */
    suspend fun scheduleDayBoundary(at: Instant)

    /** Будильник повтора настойчивого напоминания (НАП-25): тот же приём, другой номер показа. */
    suspend fun scheduleRepeat(intakeId: String, at: Instant, attempt: Int)

    /**
     * Выдано ли право на точные будильники (НАП-16).
     *
     * Спрашивается на каждой пересборке: право отзывается в любой момент, а молчаливая
     * деградация до неточных будильников запрещена.
     */
    fun canScheduleExact(): Boolean
}
