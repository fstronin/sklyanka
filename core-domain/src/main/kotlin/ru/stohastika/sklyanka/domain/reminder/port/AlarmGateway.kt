package ru.stohastika.sklyanka.domain.reminder.port

import ru.stohastika.sklyanka.domain.reminder.AlarmKind
import ru.stohastika.sklyanka.domain.reminder.DirectBootAlarm
import java.time.Instant

/**
 * Точные будильники системы (НАП-5).
 *
 * Порт в домене, реализация в `app`: `AlarmManager` — это `android.*`, которого в домене
 * нет физически (НФТ-46). Домен при этом остаётся хозяином правил: что поставить, когда
 * снять и чем адресовать, решает он.
 *
 * Адрес будильника — `intake_id` (НАП-9): повторная постановка **заменяет** предыдущий
 * будильник, а не добавляет второй. Без этого перелёт назад или двойное перепланирование
 * дали бы два напоминания об одном приёме.
 */
interface AlarmGateway {

    /**
     * Поставить или заменить будильник приёма. Только точный (НАП-5).
     *
     * [attempt] — номер показа: `0` — первый, `>0` — настойчивый повтор (НАП-25).
     * Номер едет дополнением намерения, а не частью адреса: адрес у приёма один,
     * поэтому повторная постановка заменяет предыдущий будильник (НАП-9).
     *
     * Метод один на оба случая, а не два с надмножеством: восстановление ставит будильник
     * и для ручного откладывания (номер 0), и для повтора (номер 1…), и выбирать метод
     * по номеру на месте вызова — лишний способ ошибиться одинаково.
     */
    suspend fun schedule(intakeId: String, at: Instant, attempt: Int = 0)

    suspend fun cancel(intakeId: String)

    /**
     * Привести зеркало поставленных будильников к составу окна после полной пересборки.
     *
     * Полная пересборка — единственное место, где состав окна известен целиком; точечные
     * операции (откладывание, отметка, срабатывание) пишут зеркало через [schedule]/[cancel]
     * и без этого вызова не теряются. Вызов идемпотентен и дешёв: список может совпадать
     * с уже записанным. Отказ записи в зеркало — штатная деградация: реализация не имеет
     * права уронить пересборку.
     */
    suspend fun syncMirror(placed: List<DirectBootAlarm>)

    /**
     * Что действительно стоит в системе: идентификатор приёма → момент срабатывания.
     *
     * Моменты нужны, а не одни идентификаторы (в отличие от `TDD.md §5.3`): без них
     * пересборка не отличает «будильник уже стоит на верное время» от «стоит на старое»,
     * и правка расписания оставляла бы напоминание на прежний час. Возвращается
     * состояние системы, а не то, что домен когда-то просил поставить: расхождение
     * «в базе план есть, будильника нет» — это и есть отказ, который нужно увидеть.
     */
    suspend fun scheduled(): Map<String, Instant>

    /** Якорный будильник перепланирования (НАП-8). Адрес у него один, повторная постановка заменяет. */
    suspend fun scheduleAnchor(at: Instant)

    /**
     * Поставить тестовое срабатывание самопроверки (SKL-86, ПМ-21).
     *
     * Адрес у проверки один: повторная постановка заменяет, а не добавляет второй будильник
     * (принцип НАП-9). Будильник не входит в [scheduled]: проверка не приём, и число
     * будильников в окне диагностики она увеличивать не имеет права.
     */
    suspend fun scheduleDeliveryCheck(at: Instant)

    /** Снять тестовое срабатывание; отсутствие будильника — не ошибка. */
    suspend fun cancelDeliveryCheck()

    /**
     * Будильник границы суток (НАП-34).
     *
     * Отдельный адрес рядом с якорным: якорь пересобирает окно ночью, а этот будильник
     * срабатывает ровно в полночь и переводит неотмеченные приёмы прошедших суток
     * в пропущенные, снимая их карточки. Ждать до якоря нельзя — три часа в шторке
     * висело бы уведомление о приёме, который уже пропущен.
     */
    suspend fun scheduleDayBoundary(at: Instant)

    /**
     * Выдано ли право на точные будильники (НАП-16).
     *
     * Спрашивается на каждой пересборке: право отзывается в любой момент, а молчаливая
     * деградация до неточных будильников запрещена.
     */
    fun canScheduleExact(): Boolean

    /**
     * Механизм, которым ставятся будильники приёмов прямо сейчас (SKL-85, НАП-5).
     *
     * Им же размечается журнал среды: значение обязано приходить из того же объекта,
     * который ставит будильник, иначе разметка измерения разойдётся с реальностью.
     */
    suspend fun alarmKind(): AlarmKind
}
