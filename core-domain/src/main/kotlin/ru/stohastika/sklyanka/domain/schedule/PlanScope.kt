package ru.stohastika.sklyanka.domain.schedule

/**
 * Область запуска генерации.
 *
 * Узкая область существует не ради скорости: пересчёт всех лекарств всех профилей при
 * каждом нажатии «Сохранить» шумит в журнале настолько, что разобрать по нему инцидент
 * становится невозможно.
 */
sealed interface PlanScope {

    /**
     * Все лекарства всех профилей.
     *
     * Полный обход намеренно не ограничен активным профилем: ПР-10 запрещает смешивать
     * профили в выборках экранов, а генерация — фоновая операция, и приёмы профиля
     * подопечного обязаны рождаться, пока на экране открыт профиль владельца (ПРФ-8, НАП-12).
     */
    data object AllProfiles : PlanScope

    /** Лекарства одного профиля. */
    data class Profile(val profileId: String) : PlanScope

    /** Одно лекарство: правка расписания, архивация, возврат из архива. */
    data class Medication(val medicationId: String) : PlanScope
}
