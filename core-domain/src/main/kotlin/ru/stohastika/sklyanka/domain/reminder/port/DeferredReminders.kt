package ru.stohastika.sklyanka.domain.reminder.port

import java.time.Instant

/**
 * Отложенное срабатывание: когда напомнить в следующий раз и каким по счёту показом.
 *
 * Хранится и ручное откладывание, и настойчивый повтор — оба суть «отложенное
 * срабатывание» с разным номером показа. Различие — в [attempt] (`0` против `1…`),
 * а не в типе.
 */
data class DeferredReminder(
    val intakeId: String,
    /** Момент следующего показа — точка на абсолютной шкале (UTC). */
    val fireAt: Instant,
    /** Номер показа: 0 — напоминание после ручного откладывания, 1… — настойчивый повтор. */
    val attempt: Int,
)

/**
 * Хранилище отложенных срабатываний (SKL-35, ОВ-75).
 *
 * Порт, а не прямой доступ к DAO: домен объявляет, что ему нужно от хранилища,
 * `core-data` реализует — как у [AlarmRegistry]. Без постоянной записи повтор
 * не переживал бы перезагрузку: восстановление собирало бы окно из приёмов,
 * а `scheduled_at` отложенного приёма уже в прошлом и в окно не попадает.
 *
 * Возврат `Boolean` у [remove] — не удобство: только отметка знает, был ли приём отложен,
 * и по этому ответу решает, снимать ли будильник. Обычный будильник будущего приёма
 * отметка трогать не должна, иначе отмена отметки оставит приём без напоминания.
 */
interface DeferredReminders {

    /** Все записи без фильтра по профилю: пересборка межпрофильная по природе (НАП-12). */
    suspend fun all(): List<DeferredReminder>

    /** Поставить или заменить запись приёма: отложенное срабатывание у него ровно одно. */
    suspend fun put(reminder: DeferredReminder)

    /** @return была ли запись: по ответу отметка понимает, снимать ли отложенный будильник. */
    suspend fun remove(intakeId: String): Boolean
}
