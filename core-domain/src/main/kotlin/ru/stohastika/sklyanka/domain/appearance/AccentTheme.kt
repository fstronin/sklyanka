package ru.stohastika.sklyanka.domain.appearance

/**
 * Акцентная тема «Склянки Про» (§2.5, Р-31).
 *
 * Здесь живёт **выбор**, а не краски: значения цвета темы — свойство интерфейса
 * (`core-ui/.../token/AccentPalette.kt`), и домен о них не знает. Разделение не
 * формальность: правило «после отмены подписки выбранное остаётся, а выбор другой
 * платной темы закрыт» (Р-22, §5.17) — правило продукта, и оно обязано проверяться
 * там, где нет ни Android, ни Compose.
 *
 * [key] — запись в постоянных настройках: короткое латинское слово, не зависящее от
 * языка интерфейса (`ADR-0008`). Имя темы на экране приходит из каталога строк: слово
 * «Олива» переводится, а ключ хранения — нет.
 */
enum class AccentTheme(val key: String) {

    /** «Олива» — базовая тема и значение по умолчанию (Р-20, §2.5). */
    OLIVE("olive"),

    /** «Индиго», глубокий синий (§2.5). */
    INDIGO("indigo"),

    /** «Хвоя», глубокая зелень (§2.5). */
    PINE("pine"),

    /** «Аметист», приглушённый фиолетовый (§2.5). */
    AMETHYST("amethyst"),
    ;

    /**
     * Базовая тема — та, что стоит без доступа и без выбора (Р-20).
     *
     * Доступна в любой подписке и в её отсутствие: метки «Про» у неё нет и быть не может
     * — метка продавала бы бесплатное (Р-71, П-7).
     */
    val isBase: Boolean get() = this == DEFAULT

    companion object {

        /** Базовая тема (Р-20). */
        val DEFAULT: AccentTheme = OLIVE

        /**
         * Тема по записи в постоянных настройках.
         *
         * Незнакомая или испорченная строка читается как базовая «Олива», а не как ошибка:
         * оформление — не данные человека, и запуск из-за него ломаться не должен. Тот же
         * приём, что у палитры профилей: неизвестное значение приходит из более новой
         * сборки (МГ-6).
         */
        fun ofKey(key: String?): AccentTheme = entries.firstOrNull { it.key == key } ?: DEFAULT
    }
}
