package ru.stohastika.sklyanka.domain.transfer

import java.time.LocalDate
import java.time.format.DateTimeFormatter
import java.util.Locale

/**
 * Опознание файла переноса и версия его формата (ПЕР-2, ПЕР-6, ПЕР-7).
 *
 * Версия формата и версия схемы базы — разные независимые числа (МГ-4). Схема Room
 * меняется от задачи к задаче и человеку не видна; формат файла виден и обязан
 * читаться сборкой, которая его не писала.
 *
 * Здесь же заложено то, чего требует ОВ-65: **отличимость будущего изменения формата
 * от битого файла.** Опознаватель и номер версии читаются первыми, до разбора остального
 * файла, и дают три разных исхода вместо одного «файл не подходит»:
 * опознавателя нет или он чужой — файл не наш (ПЕР-28); номер больше [CURRENT_VERSION] —
 * файл из будущего (ПЕР-29); номер меньше — файл старый и читается через миграцию (ПЕР-30).
 * Поэтому смена схемы файла никогда не выглядит как порча файла.
 */
object TransferFormat {

    /** Постоянная строка-опознаватель (ПЕР-6). Без неё файл не считается выгрузкой Склянки. */
    const val MARKER: String = "sklyanka-export"

    /**
     * Версия формата, которую пишет и понимает эта сборка (ПЕР-7).
     *
     * Единица — структура из `docs/v2/10-behavior.md` §2, помеченная там как
     * предложение к согласованию (ОВ-65). Повышается только при несовместимом изменении:
     * добавление необязательного поля версию не двигает, потому что старая сборка
     * такой файл прочитает.
     */
    const val CURRENT_VERSION: Int = 1

    /**
     * Самая старая версия, совместимость с которой поддерживается (ПЕР-30).
     *
     * Совместимость снизу держится для всех выпущенных версий, поэтому нижняя граница
     * совпадает с первой версией и опускается вместе с ней только при удалении
     * выпущенной версии — чего не бывает.
     */
    const val MINIMUM_VERSION: Int = 1

    /** Опознаватель платформы в метаданных выгрузки. */
    const val PLATFORM: String = "android"

    private const val NAME_PREFIX = "sklyanka-"
    private const val NAME_SUFFIX = ".json"

    private val FILE_DATE: DateTimeFormatter = DateTimeFormatter.ISO_LOCAL_DATE.withLocale(Locale.ROOT)

    /**
     * Имя файла выгрузки `sklyanka-ГГГГ-ММ-ДД.json` (ПЕР-2).
     *
     * Дата — локальная дата устройства из инжектируемых часов, а не момент в UTC:
     * человек ищет файл по тому дню, в который он его сохранял.
     */
    fun fileName(date: LocalDate): String = NAME_PREFIX + date.format(FILE_DATE) + NAME_SUFFIX

    /** Имя страховочной копии перед заменой всего (ПЕР-16, ПЕР-36): постоянное, без даты. */
    const val SAFETY_COPY_NAME: String = "sklyanka-before-replace.json"
}
