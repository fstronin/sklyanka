package ru.stohastika.sklyanka.domain.reminder.port

/**
 * Разрешения и настройки, от которых зависит доставка напоминания (НАП-15).
 *
 * Перечисление, а не набор булевых полей: диагностика показывает состояние каждого
 * разрешения **отдельной строкой** (НАП-37), и строка, которую забыли добавить в экран,
 * не должна выглядеть как «всё в порядке».
 */
enum class ReminderPermission {
    /** Показ уведомлений; на Android 13+ запрашивается у человека. */
    NOTIFICATIONS,

    /** Каналы напоминаний: выключен хотя бы один — напоминание не покажется вовсе (SKL-79). */
    NOTIFICATION_CHANNEL,

    /** Точные будильники: `USE_EXACT_ALARM` как основное, `SCHEDULE_EXACT_ALARM` запасное (НАП-16). */
    EXACT_ALARMS,

    /** Полноэкранное уведомление: без него карточка деградирует до heads-up. */
    FULL_SCREEN_INTENT,

    /** Доступ к политике «Не беспокоить»: запрашивается отдельно, не в онбординге (НАП-17). */
    DND_POLICY_ACCESS,

    /** Приёмник загрузки: объявлен в манифесте, отзыву человеком не подлежит (ПЛ-9). */
    BOOT_RECEIVER,

    /** Автозапуск и энергосбережение EMUI: программно не читается (НАП-20, ПЛ-18). */
    AUTOSTART,
}

/**
 * Состояние одного разрешения.
 *
 * [UNKNOWN] — не «ещё не спросили», а «система не даёт ответа»: состояние фирменных
 * ограничений EMUI в публичный API не выставлено, и честная диагностика обязана сказать
 * «проверьте вручную», а не показать зелёную галочку (НАП-20).
 */
enum class PermissionState {
    GRANTED,
    DENIED,
    UNKNOWN,
}

/**
 * Чтение состояния разрешений из системы.
 *
 * Именно из системы и при каждом обращении, а не из сохранённого флага (НФТ-52):
 * сохранённый флаг устаревает ровно в тот момент, когда человек отозвал разрешение,
 * и диагностика начинает врать там, где её и открыли, чтобы узнать правду.
 */
interface PermissionStateReader {

    fun state(permission: ReminderPermission): PermissionState

    /** Все разрешения таблицы НАП-15 — то, что показывает экран диагностики строками. */
    fun all(): Map<ReminderPermission, PermissionState> = ReminderPermission.entries.associateWith(::state)
}
