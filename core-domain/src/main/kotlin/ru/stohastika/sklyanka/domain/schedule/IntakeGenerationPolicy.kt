package ru.stohastika.sklyanka.domain.schedule

/**
 * Настройки генерации приёмов — то, что решает заказчик, а не разработчик.
 *
 * Оба параметра вынесены сюда по одной причине: они относятся к открытым вопросам
 * (`docs/archive/tasks/SKL-06/task.md`, «Открытые вопросы»), и смена решения обязана быть правкой
 * одного значения, а не переписыванием планировщика.
 */
data class IntakeGenerationPolicy(

    /**
     * Глубина окна генерации в сутках, считая текущие (ОВ-8).
     *
     * Рабочее значение — семь суток; обоснование в `task.md`, «Горизонт генерации».
     */
    val windowDepthDays: Int,

    /**
     * Порождать ли приёмы, чьё время уже прошло, **в день начала курса**.
     *
     * Значение по умолчанию — не порождать. Причина не в скорости перехода в MISSED:
     * при границе окна «до конца суток» (ОВ-4) такой приём до полуночи остаётся
     * ожидающимся. Причина в том, что этой дозы не было в природе — человек, заводящий
     * лекарство в 14:30, в 08:00 его не принимал и принять не мог, курса ещё не
     * существовало. Приём, порождённый задним числом, к полуночи станет пропущенным
     * и занизит приверженность за дозу, которая никогда не была назначена.
     *
     * Правило узкое намеренно: в любой другой день прошедшее время — это настоящий приём,
     * который человек мог принять и не отметить либо честно пропустить. Снимать его нельзя,
     * иначе полная перегенерация в середине дня стирала бы сегодняшнюю историю.
     *
     * Границей служит `start_date`, а не момент создания лекарства: момента создания
     * в модели данных нет (`docs/norm/04-behavior.md` §3), и он не нужен — курс,
     * начинающийся сегодня, и есть тот единственный случай, о котором идёт речь.
     */
    val skipPastTimesOnCourseStart: Boolean = true,
) {
    init {
        require(windowDepthDays >= GenerationWindow.MIN_DEPTH_DAYS) {
            "Generation window must cover the 48 hour alarm window: depth=$windowDepthDays"
        }
    }
}
