package ru.stohastika.sklyanka.domain.reminder

/**
 * Механизм постановки будильника приёма (НАП-5, ОВ-110).
 *
 * Значение настройки, код записи журнала и колонка выгрузки — одно и то же: разойдись
 * они, и разметка окна измерения перестала бы отвечать на вопрос, каким механизмом
 * поставлен будильник.
 */
enum class AlarmKind(val code: String) {
    /**
     * Системный будильник: получает исключение из Doze и заморозки, система его
     * не сдвигает, признак виден в статус-баре (НАП-5, ОВ-110).
     */
    ALARM_CLOCK("alarm_clock"),

    /** Тихий точный будильник: контрольное плечо измерения и режим служебных будильников. */
    EXACT_IDLE("exact_idle"),
    ;

    companion object {
        /** Незнакомый код читается как надёжный механизм (МГ-6). */
        fun of(code: String?): AlarmKind = entries.firstOrNull { it.code == code } ?: ALARM_CLOCK
    }
}
