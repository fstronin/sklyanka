package ru.stohastika.sklyanka.domain.reminder

import java.time.Duration

/**
 * Пределы хранения журнала срабатываний (ПМ-30, НФТ-51).
 *
 * Правило ротации — сочетание возраста и объёма: записи старше [maxAge] удаляются,
 * одновременно действует потолок [maxBytes] с вытеснением старейших. Последние
 * [protectedWindow] неприкосновенны: по ним считается сводка «сработало вовремя»
 * и разбираются недавние жалобы, и ротация в это окно не заходит ни при каком
 * объёме.
 *
 * Политика — значение, а не объект с константами: инструментальному тесту нужно
 * вытеснение, укладывающееся в десятки записей, а не в тысячи. Продуктовые числа
 * объявлены здесь один раз и берутся оттуда же выгрузкой журнала.
 */
data class ReminderLogRetention(
    val maxAge: Duration = MAX_AGE,
    val protectedWindow: Duration = PROTECTED_WINDOW,
    val maxBytes: Long = MAX_BYTES,
) {

    companion object {
        /**
         * Сколько журнал хранится: 90 суток.
         *
         * Требование НФТ-51 — «не менее 30 суток»; 90 взяты решением ПМ-30 с запасом:
         * журнал нужен не только недельной диагностике, но и разбору затяжных
         * инцидентов, где проблема всплывает через недели.
         */
        val MAX_AGE: Duration = Duration.ofDays(90)

        /**
         * Неприкосновенное окно: последние 7 суток.
         *
         * Те же 7 суток, что у сводки «вовремя» ([ReminderOnTimeRule.WINDOW]):
         * их совпадение проверяется тестом, чтобы окна не разъехались молча.
         */
        val PROTECTED_WINDOW: Duration = Duration.ofDays(7)

        /** Потолок объёма журнала: 2 МБ (НФТ-51, ПМ-30). */
        const val MAX_BYTES: Long = 2L * 1024 * 1024

        /** Продуктовые пределы — то, что собирает приложение. */
        val DEFAULT: ReminderLogRetention = ReminderLogRetention()
    }
}
