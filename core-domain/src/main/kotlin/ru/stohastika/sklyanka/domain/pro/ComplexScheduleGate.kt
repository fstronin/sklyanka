package ru.stohastika.sklyanka.domain.pro

import ru.stohastika.sklyanka.domain.model.ScheduleRule

/**
 * Граница «Про» на **создание** сложного расписания (ПР-20, ПР-21, Р-17, Р-22, Р-24, Р-28).
 *
 * Правило живёт в домене, а не в ViewModel: его проверяет приёмка без Android
 * (`docs/tasks/SKL-117/TDD.md` §6), и оно же гейт для любой формы, которая однажды
 * появится рядом. Замка здесь нет: закрыто только **завершение создания**, а не выбор
 * вида и не открытие формы — человек имеет право увидеть, что именно покупает (П-7, Р-79).
 *
 * Решение принимается не по новому виду, а по **переходу** (чтение ПР-21, `docs/norm/06-design.md`
 * §5.10): признак «новое сложное расписание» — **сохранённый** вид курса, а не последнее
 * состояние черновика. Иначе один и тот же черновик открывал и закрывал границу в зависимости
 * от порядка нажатий.
 */
object ComplexScheduleGate {

    /**
     * Закрыто ли сохранение: создаётся ли сложное расписание без подписки.
     *
     * @param original вид, с которым курс пришёл в форму; `null` — курс заводят впервые.
     * @param next вид, который получится после сохранения.
     * @param included есть ли доступ «Про» прямо сейчас ([ProStatus.included]).
     * @return `true` — сохранять нельзя, причина называется словами и ведёт в витрину;
     *   `false` — сохранение проходит.
     *
     * Базовое разрешено всегда: ежедневное, «через каждый день» (вырожденный вид),
     * один выбранный день недели и «по потребности» — их `isComplex` ложно (ПР-15, Р-24).
     * Правка уже сложного курса проходит целиком, включая смену одного сложного вида
     * на другой (Р-28): это тот же заведённый и уже оплаченный курс.
     */
    fun isCreationOfComplex(original: ScheduleRule?, next: ScheduleRule, included: Boolean): Boolean =
        // Доступ есть — закрывать нечего; базовое разрешено всегда; сложный курс, уже бывший
        // сложным, — правка заведённого, а не создание нового (Р-28).
        !included && next.isComplex && original?.isComplex != true
}
