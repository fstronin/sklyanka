package ru.stohastika.sklyanka.domain.profile

/**
 * Почему активный профиль сменился.
 *
 * Причина существует ради журнала: «почему я оказался в мамином профиле» — реальный
 * вопрос человека, и ответ на него обязан быть восстановим (`TDD.md §11.1`). Код уходит
 * в журнал служебной строкой, а не текстом для человека: текст живёт в `strings.xml`
 * (НФТ-42).
 */
enum class SwitchReason(val code: String) {

    /** Человек выбрал профиль в списке настроек — единственный осознанный путь (ПРФ-19). */
    USER_SETTINGS("user_settings"),

    /** Открыто напоминание чужого профиля: профиль задаёт приём, а не экран (ПРФ-20). */
    REMINDER_OPENED("reminder_opened"),

    /** Активный профиль скрыли — возврат в профиль владельца (ПРФ-31). */
    PROFILE_HIDDEN("profile_hidden"),

    /** Загружен файл переноса: сохранённый профиль мог исчезнуть (ПЕР-19, вызов — SKL-19). */
    DATA_IMPORTED("data_imported"),

    /**
     * Восстановление инварианта: сохранённое значение указывало в пустоту.
     *
     * Отдельная причина, а не `DATA_IMPORTED`: база могла быть восстановлена и иначе,
     * а человеку и разбору важно именно то, что приложение сменило профиль **само**
     * (ПРФ-31).
     */
    INVARIANT_RESTORED("invariant_restored"),
}
