package ru.stohastika.sklyanka.domain.model

/**
 * Профиль — владелец набора лекарств (docs/norm/04-behavior.md §2).
 *
 * Смешивание профилей запрещено на уровне данных, а не экрана (ПРФ-4): профиль —
 * обязательный параметр любой выборки лекарств, приёмов и истории.
 */
data class Profile(
    val id: String,
    val name: String,
    /** Цвет ARGB из палитры дизайн-системы; база хранит число, палитру знает интерфейс. */
    val color: Int,
    /** Владелец приложения. Такой профиль в базе ровно один (INV-1). */
    val isSelf: Boolean,
    /** Дублировать ли напоминания профиля владельцу. Для самого владельца игнорируется (INV-2). */
    val mirrorReminders: Boolean,
)
