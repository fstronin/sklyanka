package ru.stohastika.sklyanka.domain.pro

/**
 * Кэш состояния подписки на устройстве (`ADR-0015` п. 1–2).
 *
 * Кэшу нужны ровно две вещи: положить ответ магазина и прочитать последний. Срока давности
 * у записи нет намеренно: любой срок — это отключение доступа за то, что человек не выходил
 * в интернет, а отказ доступа из-за неудачной проверки — отказ продукта в его обещании (П-6).
 *
 * Цены в кэш не ложатся: последняя известная цена как текущая не показывается никогда
 * (Р-68 п. 4). Кэшируется только доступ.
 */
interface ProSubscriptionCache {

    /** Последний известный ответ магазина; `null` — подписку ещё ни разу не проверяли. */
    suspend fun read(): ProSubscription?

    /** Записать ответ магазина; недоступность магазина сюда не попадает — она ничего не меняет. */
    suspend fun write(subscription: ProSubscription)
}
