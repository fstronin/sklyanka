package ru.stohastika.sklyanka.domain.reminder

/**
 * Почему окно будильников пересобрано (таблица НАП-11).
 *
 * Причина — не отладочная подробность: по ней в диагностике человек и разработчик отвечают
 * на вопрос «почему напоминание не пришло» (НАП-14, НАП-37). Код уходит в журнал служебной
 * строкой, а не текстом для человека: текст живёт в `strings.xml` (НФТ-42).
 */
enum class RescheduleReason(val code: String) {
    /** Перезагрузка стирает все будильники (ПЛ-9, НФТ-2). */
    BOOT("boot"),

    /** Загрузка до разблокировки: окно восстановлено по снимку (SKL-87). */
    LOCKED_BOOT("locked_boot"),

    /** Разблокировка после перезагрузки: полная пересборка (SKL-87). */
    USER_UNLOCKED("user_unlocked"),

    /** Обновление приложения поверх предыдущей сборки снимает будильники (И-11). */
    PACKAGE_REPLACED("package_replaced"),

    /** Локальное время приёма сдвинулось относительно абсолютного (НФТ-4). */
    TIMEZONE_CHANGED("timezone_changed"),

    /** Ручной или сетевой перевод часов ломает соответствие плана реальному времени. */
    TIME_CHANGED("time_changed"),

    /** Изменились времена приёма, границы курса или доза. */
    SCHEDULE_EDITED("schedule_edited"),

    /** Появилось лекарство — в окне появились новые приёмы. */
    MEDICATION_ADDED("medication_added"),

    /** Архивация: приёмы выбывают из плана немедленно (ПР-11). */
    MEDICATION_ARCHIVED("medication_archived"),

    /** Мягкое удаление: приёмы выбывают из плана, будильники снимаются (ПМ-24, ПР-14). */
    MEDICATION_DELETED("medication_deleted"),

    /** Возврат удаления: приёмы возвращаются в план. */
    MEDICATION_UNDELETED("medication_undeleted"),

    /** Возврат из архива: приёмы возвращаются в план. */
    MEDICATION_UNARCHIVED("medication_unarchived"),

    /** После каждого сработавшего будильника окно сдвигается вперёд (НФТ-7). */
    ALARM_FIRED("alarm_fired"),

    /** Изменился состав профилей или флаг дублирования напоминаний (ПРФ-6, НАП-12). */
    PROFILE_SET_CHANGED("profile_set_changed"),

    /** Якорный будильник — страховка на сутки, в которые не случилось ничего (НАП-8). */
    ANCHOR("anchor"),

    /** «Проверить сейчас» на экране диагностики (НАП-37). */
    MANUAL("manual"),

    /** Загрузка файла переноса данных; вызов добавит SKL-19 (ПЕР-18). */
    DATA_IMPORTED("data_imported"),

    /**
     * Запуск приложения.
     *
     * Причины нет в таблице НАП-11, и заведена она осознанно: на EMUI приложение
     * выгружается, а старт — единственное событие, которое случается наверняка
     * (`SklyankaApp`, SKL-06). Без неё свежая установка не имела бы будильников до
     * первого якоря или перезагрузки.
     */
    APP_START("app_start"),

    /**
     * Человек выдал право на точные будильники (SKL-85, НАП-16, И-20).
     *
     * Приходит системным broadcast'ом на Android 12+: до выдачи системный будильник
     * поставить нельзя, после — план обязан восстановиться без вывода приложения
     * на передний план.
     */
    EXACT_ALARM_GRANTED("exact_alarm_granted"),
}
