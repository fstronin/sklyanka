package ru.stohastika.sklyanka.domain.history

import java.time.LocalDate
import java.time.LocalTime

/**
 * Приверженность за период — всё, что показывает экран истории, одним значением
 * (`docs/tasks/SKL-18/TDD.md §5.1`).
 *
 * Величина производная и нигде не хранится: `docs/spec/02-data-model.md` прямо говорит
 * «приверженность считается из `Intake`». Месячные агрегаты сознательно не заводятся —
 * их пришлось бы инвалидировать при отметке, при правке расписания, при архивации и
 * при загрузке файла переноса, и каждая из этих точек — шанс показать врачу устаревшее
 * число (`TDD.md §4`).
 *
 * Профиль — часть значения, а не контекст вызова: сводка, посчитанная для одного
 * профиля и показанная в другом, — это ложный отчёт врачу (ПР-10).
 */
data class AdherencePeriod(
    val profileId: String,
    val from: LocalDate,
    val to: LocalDate,
    /** Ровно по одному исходу на каждый день периода, от [from] до [to] включительно. */
    val days: List<DayOutcome>,
    val byMedication: List<MedicationAdherence>,
    /** Плитка «дней без пропусков»: дни, в которых принято всё запланированное. */
    val daysWithoutMisses: Int,
    /** Плитка «пропусков за месяц»: и отмеченные человеком, и автоматические (ПР-1). */
    val missesInPeriod: Int,
    /** Плитка «принято вовремя». Не число, а тип: порог не согласован (ОВ-4, [OnTimeShare]). */
    val onTimeShare: OnTimeShare,
    /** Пропуски по времени приёма — опора строки-вывода ([MissedPatternRule]). */
    val missesByTime: Map<LocalTime, Int>,
    /**
     * Времена приёма, встречавшиеся в периоде.
     *
     * Нужны строке-выводу: сравнивать «чаще всего» не с чем, если время приёма в сутках
     * одно (`MissedPatternRule`). Берутся из самих приёмов периода, а не из расписания
     * лекарства: расписание могли изменить после того, как приёмы уже состоялись.
     */
    val scheduledTimes: Set<LocalTime>,
) {

    /**
     * Данных за период нет вовсе: плитки показывают прочерки, календарь пуст, блок
     * «По лекарствам» скрыт, строка-вывод не показывается (`docs/spec/03-screens.md`,
     * состояние «Данных за месяц нет»).
     *
     * Именно «ни одного приёма», а не «ноль принятых»: месяц, в котором всё пропущено,
     * пустым не является и обязан показывать свои числа.
     */
    val isEmpty: Boolean get() = byMedication.isEmpty() && days.none { it.state.hasIntakes }

    companion object {

        /** Период без единого приёма: с ним экран открывается до первого значения потока. */
        fun empty(profileId: String, from: LocalDate, to: LocalDate): AdherencePeriod = AdherencePeriod(
            profileId = profileId,
            from = from,
            to = to,
            days = emptyList(),
            byMedication = emptyList(),
            daysWithoutMisses = 0,
            missesInPeriod = 0,
            onTimeShare = OnTimeShare.Undefined,
            missesByTime = emptyMap(),
            scheduledTimes = emptySet(),
        )
    }
}

/**
 * Исход одного дня календаря.
 *
 * «Сегодня» — не состояние, а признак: сегодняшний день может быть любым, и обводка
 * в макете (`design/screens/History.dc.html`) рисуется поверх исхода, а не вместо него.
 */
data class DayOutcome(val date: LocalDate, val state: DayState, val isToday: Boolean = false)

/**
 * Состояние дня в календаре месяца.
 *
 * Пять состояний назвал `TDD.md §5.1`, шестое — [AHEAD] — добавлено при реализации и
 * объявлено вслух. Без него день, сутки которого ещё не кончились, приходилось бы
 * называть либо пропуском (тогда каждое утро календарь показывает провал, которого нет),
 * либо днём без приёмов (тогда приём, который человеку ещё предстоит, исчезает с глаз).
 * Решение повторяет уже принятое в SKL-10: сегодняшний день в счёт приверженности
 * не идёт (ЭКР-6).
 */
enum class DayState {

    /** Все приёмы дня отмечены принятыми. */
    ALL_TAKEN,

    /** Есть и принятые, и непринятые: определение «частично» (ОВ-12, требует подтверждения). */
    PARTIAL,

    /**
     * Принятых нет, а приёмы были.
     *
     * Пропуск, отмеченный человеком, и пропуск, проставленный приложением по истечении
     * окна, здесь не различаются: для картины врача приём не состоялся в обоих случаях.
     * Различие сохраняется в отчёте ([DoctorReport]): одно говорит о поведении человека,
     * другое может говорить о том, что телефон был выключен.
     */
    MISSED,

    /** Приёмов в этот день не было: расписание его не задело. */
    NO_INTAKES,

    /** День раньше первой записи истории профиля: исхода у него не существует. */
    BEFORE_HISTORY,

    /** Сутки ещё не завершились: приёмы есть, исход им не приписан (ЭКР-6). */
    AHEAD,
    ;

    /** В этот день приёмы были — то есть день участвует в картине месяца. */
    val hasIntakes: Boolean get() = this == ALL_TAKEN || this == PARTIAL || this == MISSED || this == AHEAD

    /** День с завершившимся исходом: только такие дни идут в счёт «дней без пропусков». */
    val isCompleted: Boolean get() = this == ALL_TAKEN || this == PARTIAL || this == MISSED
}

/**
 * Строка блока «По лекарствам»: название, доля принятого и полоса.
 *
 * Архивированный курс — такая же строка, как активный: архив придуман ровно для того,
 * чтобы завершённый курс не исчезал из истории (ПР-11).
 */
data class MedicationAdherence(
    val medicationId: String,
    val name: String,
    val taken: Int,
    val planned: Int,
    val misses: Int,
    val archived: Boolean,
    /** Лекарство с низкой приверженностью выделяется акцентом (`docs/spec/03-screens.md`). */
    val low: Boolean,
    /**
     * В периоде есть отметки, сделанные не владельцем профиля приёма (ПР-12, ПРФ-14).
     *
     * В истории это подпись «отметили вы»: отметку поставил владелец телефона в чужом
     * профиле. В истории своего профиля значение всегда `false` — `actor_profile_id`
     * там не заполняется вовсе (`ActorResolver`), и подписи не бывает по построению,
     * а не потому, что экран её спрятал.
     */
    val markedByOtherProfile: Boolean = false,
) {

    /**
     * Доля принятого от нуля до единицы.
     *
     * Знаменатель нулевым не бывает: строка появляется только у лекарства, у которого
     * в периоде есть приёмы. Защита оставлена, потому что цена ошибки — падение экрана
     * истории на пустом месяце.
     */
    val takenShare: Double get() = if (planned == 0) 0.0 else taken.toDouble() / planned

    /** Округлённый процент для подписи: «29 из 30» — это 97 %, а не 96 %. */
    val takenPercent: Int get() = Math.round(takenShare * PERCENT).toInt()

    private companion object {
        const val PERCENT = 100
    }
}
