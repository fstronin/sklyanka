package ru.stohastika.sklyanka.domain.appearance

import kotlinx.coroutines.flow.Flow

/**
 * Постоянные настройки оформления: выбранная тема и вариант иконки (Р-23, Р-31, §5.17).
 *
 * Оформление — свойство **устройства**, а не данных человека, и живёт в постоянных
 * настройках приложения рядом с активным профилем. В Room оно не едет намеренно: файл
 * переноса не должен нести оформление (ПЕР-37), и запись в базе означала бы, что однажды
 * её положат и в выгрузку.
 *
 * Порт объявлен в домене, а не взят хранилищем напрямую: правило записи живёт здесь
 * ([SetAccentThemeUseCase], [SetIconVariantUseCase]), и оно обязано читаться и писаться
 * одним швом — иначе вторая поверхность, однажды выбравшая тему, заведёт свой путь записи
 * и обойдёт хранилище.
 *
 * Умолчания — базовые: «Олива» (Р-20) и «Ледяная» (Р-56). Поток отдаёт их и тогда, когда
 * записи нет вовсе: «не выбрано» для человека и есть «олива на бумаге», а не пустое
 * значение, которое экран обязан был бы чем-то заполнить.
 */
interface AppearancePreferences {

    /** Выбранная акцентная тема; без записи — базовая «Олива» (Р-20). */
    val accentTheme: Flow<AccentTheme>

    /** Выбранный вариант иконки; без записи — базовая «Ледяная» (Р-56). */
    val iconVariant: Flow<IconVariant>

    suspend fun setAccentTheme(theme: AccentTheme)

    suspend fun setIconVariant(variant: IconVariant)
}
