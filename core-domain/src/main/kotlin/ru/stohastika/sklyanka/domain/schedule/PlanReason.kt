package ru.stohastika.sklyanka.domain.schedule

/**
 * Причина запуска генерации — перечень событий НАП-11 плюс старт приложения.
 *
 * Уходит в журнал служебным кодом: без причины запись «создано 7 приёмов» не отвечает
 * на вопрос «почему они появились именно сейчас» (`TDD.md §9`).
 */
enum class PlanReason(val code: String) {
    APP_START("app_start"),
    BOOT("boot"),
    TIMEZONE_CHANGED("timezone_changed"),
    TIME_CHANGED("time_changed"),
    MEDICATION_SAVED("medication_saved"),
    MEDICATION_ARCHIVED("medication_archived"),

    /**
     * Мягкое удаление лекарства (SKL-99, ПМ-24, ПР-14).
     *
     * Отдельная причина рядом с архивацией: обе уносят курс из плана, но удаление
     * скрывает его везде, и разбор «куда делся приём» упирается именно в различие.
     */
    MEDICATION_DELETED("medication_deleted"),

    /** Возврат удаления в коротком окне отмены: приёмы и будильники возвращаются. */
    MEDICATION_UNDELETED("medication_undeleted"),

    /**
     * Появление лекарства — сохранение новой записи, а не правка существующей.
     *
     * Отдельная причина рядом с MEDICATION_SAVED: для генерации приёмов различие не
     * принципиально, но постановка будильников по НАП-11 различает «добавлено» и
     * «изменено расписание», и нести это различие обязано уже первое звено цепочки.
     */
    MEDICATION_ADDED("medication_added"),

    /**
     * Возврат курса из архива (SKL-11).
     *
     * Отдельная причина рядом с архивацией: обе меняют состав расписания, но разбор
     * вопроса «откуда у архивного курса приёмы» упирается именно в то, различимы ли
     * эти два события в журнале.
     */
    MEDICATION_RESTORED("medication_restored"),
    ANCHOR_ALARM("anchor_alarm"),
    MANUAL_CHECK("manual_check"),

    /**
     * Загрузка файла переноса данных (ПЕР-18, SKL-19).
     *
     * Отдельная причина, а не MANUAL_CHECK: после загрузки состав приёмов меняется целиком,
     * и запись «снято 40 приёмов, создано 52» разбирается только вместе с ответом на вопрос
     * «почему именно сейчас».
     */
    DATA_IMPORTED("data_imported"),
}
