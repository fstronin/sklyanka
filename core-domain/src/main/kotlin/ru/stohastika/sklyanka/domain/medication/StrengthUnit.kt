package ru.stohastika.sklyanka.domain.medication

/**
 * Единица дозировки препарата — закрытый список из шести значений (решение Р-45).
 *
 * Дозировка отвечает на вопрос «сколько действующего вещества в одной единице»: «500 мг»,
 * «50 мкг», «100 МЕ». Приложение её показывает и не использует в расчётах (`CONTEXT.md`),
 * но свободного ввода единицы нет: он давал «мг», «mg» и «мгр» на одну и ту же запись,
 * и сравнение записей при переносе данных ломалось на орфографии.
 *
 * Коды латинские и устойчивы к переводу (НФТ-42); слова единиц живут в ресурсах экранов.
 * Код хранится в `Medication.strengthUnit`, поэтому [ofCode] разбирает его терпимо:
 * незнакомая единица из файла переноса данных — не ошибка, а чужая запись (МГ-6),
 * и показывается она как есть, а не подменяется своей.
 */
enum class StrengthUnit(val code: String) {
    MILLIGRAM("mg"),
    MICROGRAM("mcg"),
    GRAM("g"),
    MILLILITRE("ml"),
    INTERNATIONAL_UNIT("iu"),
    PERCENT("percent"),
    ;

    companion object {
        fun ofCode(code: String): StrengthUnit? = entries.firstOrNull { it.code == code }
    }
}
