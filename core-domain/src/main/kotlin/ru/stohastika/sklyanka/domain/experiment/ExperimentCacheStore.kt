package ru.stohastika.sklyanka.domain.experiment

/**
 * Кэш последнего полученного снимка вариантов (SKL-83, TDD §9).
 *
 * Отдельно от настроек и согласия: снимок не участвует в переносе данных (ПЕР-37)
 * и не сбрасывается заменой содержимого. Значение переживает перезапуск — требование
 * ПМ-20 п. 4; незнакомые значения читаются как «нет варианта» (базовый). Реализация
 * (отдельный DataStore) живёт в `core-data`.
 */
interface ExperimentCacheStore {

    /** Снимок последнего успешного получения; пустая карта — «вариантов нет». */
    suspend fun read(): Map<ExperimentId, VariantKey>

    /** Записать снимок целиком: отсутствующий в ответе эксперимент перестаёт действовать. */
    suspend fun write(variants: Map<ExperimentId, VariantKey>)
}
