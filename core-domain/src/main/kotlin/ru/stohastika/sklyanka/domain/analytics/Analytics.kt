package ru.stohastika.sklyanka.domain.analytics

/**
 * Единственный канал отправки событий (TDD §5.1).
 *
 * Домен и экраны знают только этот порт: адаптер вендора живёт снаружи, в `core-analytics`.
 * `track` синхронный намеренно — вызывающие не ждут сеть, а разрешённость держит адаптер;
 * `applyConsent` пересчитывает её после каждого решения и включает или выключает контур.
 */
interface Analytics {

    /** Отправить событие каталога. До согласия и после выключения вызов ничего не отправляет. */
    fun track(event: AnalyticsEvent)

    /** Применить решение согласия: активировать контур или прекратить отправку. */
    suspend fun applyConsent(consent: AnalyticsConsent)
}
