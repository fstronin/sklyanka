package ru.stohastika.sklyanka.domain.startup

/**
 * Отметки жизни базы и события её пересоздания (МГ-8, Р-87 п. 2).
 *
 * Повреждённый файл базы стирает платформа, и следующее открытие создаёт базу
 * заново — для человека это выглядит как молчаливая потеря всех данных. Отметка
 * «база жила» хранится **вне файла базы** (в постоянных настройках приложения),
 * поэтому она переживает повреждение и позволяет отличить пересоздание после
 * потери от первого запуска чистой установки. Очистка данных приложения стирает
 * отметку вместе с настройками — ложного объяснения на чистой установке нет.
 *
 * Признание пересоздания ([consumeDatabaseRecreated]) — признак из памяти процесса:
 * его ставит колбэк Room `onCreate` при открытии базы, и на один процесс он
 * срабатывает один раз.
 */
interface DatabaseLifeStore {

    /**
     * Снять признак «база пересоздана при этом открытии».
     *
     * Читается ровно один раз на процесс: повторное чтение обязано вернуть `false`,
     * иначе объяснение записалось бы заново при каждом возврате на экран.
     */
    fun consumeDatabaseRecreated(): Boolean

    /** База уже создавалась и приложение с ней работало. */
    suspend fun hadLife(): Boolean

    /** Отметить, что база живёт: ставится после каждого успешного старта. */
    suspend fun markLife()

    /** Момент записанного события сброса; `null` — события не было. */
    suspend fun resetEventAt(): Long?

    /** Записать событие сброса: момент в UTC миллисекундах — идентификатор события. */
    suspend fun recordResetEventAt(epochMillis: Long)

    /** Момент события, которое человек закрыл; `null` — объяснение не закрывали. */
    suspend fun resetEventAcknowledgedAt(): Long?

    /** Закрыть объяснение: событие с этим моментом больше не показывается. */
    suspend fun acknowledgeResetEventAt(epochMillis: Long)
}
