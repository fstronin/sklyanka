package ru.stohastika.sklyanka.domain.transfer

import java.time.Instant
import java.time.LocalDate

/**
 * Границы переноса с внешним миром.
 *
 * Все они объявлены здесь, в домене, и реализованы снаружи (`app`, `core-data`),
 * потому что домен не видит ни Android, ни Room (НФТ-46). Файловая система и системный
 * выбор места — платформенные механизмы ровно того сорта, который правилами проекта
 * обязан прятаться за интерфейсом.
 */

/**
 * Результат разбора файла кодеком.
 *
 * Два исхода, а не исключение: отказ от файла — штатный сценарий продукта с собственным
 * экраном и собственным следом в журнале, а не аварийная ситуация (ПЕР-28, ПЕР-29).
 */
sealed interface TransferDecoded {

    data class Loaded(val snapshot: TransferSnapshot, val notices: List<TransferNotice>) : TransferDecoded

    data class Rejected(val reject: TransferReject) : TransferDecoded
}

/**
 * Чтение и запись файла переноса (`TDD.md §4`).
 *
 * Реализация — `core-data`: версия формата, миграции снизу и терпимость к незнакомым
 * ключам суть свойства формата, а не предметной области.
 */
interface TransferCodec {

    fun encode(snapshot: TransferSnapshot): String

    /** Разбор: опознание, проверка версии, чтение разделов. Ничего не применяет. */
    fun decode(text: String): TransferDecoded
}

/** Куда сохранить файл: непрозрачная ссылка системного выбора места (НФТ-17). */
@JvmInline
value class ExportTarget(val handle: String)

/** Откуда прочитать файл: непрозрачная ссылка системного выбора файла. */
@JvmInline
value class ImportSource(val handle: String)

/** Страховочная копия перед заменой всего (ПЕР-16 п. 3, ПЕР-36). */
data class SafetyCopy(val name: String, val sizeBytes: Long, val createdAt: Instant)

/**
 * Файловые операции переноса.
 *
 * Путь, выбранный человеком в системном диалоге, наружу не возвращается и никуда
 * не записывается: приложение не ведёт учёта того, куда ушёл файл (ПЕР-36, НФТ-19).
 */
interface TransferFiles {

    /** Свободное место, чтобы проверить его **до** начала записи (ПЕР-31, НФТ-11). */
    fun freeSpaceBytes(): Long

    /**
     * Запись содержимого целиком.
     *
     * Наполовину записанный файл не должен выглядеть готовой резервной копией (ПЕР-32),
     * поэтому содержимое собирается полностью до открытия цели, а сорванная запись
     * обязана снять за собой цель — см. [discard].
     */
    suspend fun write(target: ExportTarget, content: String)

    /** Снять недописанную цель: файла с целевым именем в выбранном месте остаться не должно. */
    suspend fun discard(target: ExportTarget)

    suspend fun read(source: ImportSource): String

    /**
     * Страховочная копия во внутреннем хранилище под постоянным именем (ПЕР-36).
     *
     * Постоянное имя — это и есть решение о судьбе копии: она перезаписывается при
     * следующей замене и не копится. Пишется тем же кодеком, что обычная выгрузка:
     * копия, записанная вторым путём, однажды окажется нечитаемой ровно тогда,
     * когда понадобится.
     */
    suspend fun writeSafetyCopy(content: String): SafetyCopy

    /** Имеющаяся страховочная копия, если она есть. Нужна экрану, чтобы сказать, где она лежит. */
    fun safetyCopy(): SafetyCopy?
}

/**
 * Хранилище переноса: чтение всего состояния и исполнение плана одной транзакцией.
 *
 * Отдельно от репозиториев намеренно: репозиторий работает в контексте одного профиля
 * (ПР-10), а перенос — единственная операция продукта, которая обязана видеть всё
 * состояние сразу.
 */
interface TransferStore {

    suspend fun readAll(): DeviceState

    /**
     * Одна транзакция на всю загрузку (ПЕР-27).
     *
     * Исключение внутри означает откат целиком; частично применённая загрузка —
     * недопустимый исход, а не редкий.
     */
    suspend fun apply(plan: TransferPlan): TransferApplied
}

/** Настройки приложения, участвующие в переносе, плюс дата последней выгрузки (ПЕР-4). */
interface TransferSettingsStore {

    suspend fun read(): TransferSettings

    suspend fun write(settings: TransferSettings)

    /** Null означает «выгрузки не было ни разу»: тогда строки о ней на экране нет (критерий 5). */
    suspend fun lastExportDate(): LocalDate?

    suspend fun setLastExportDate(date: LocalDate)

    /**
     * Признак «загрузка началась и не завершилась».
     *
     * Ставится до транзакции и снимается после. Транзакцию откатит хранилище, а сказать
     * человеку, что загрузка не состоялась, после убийства процесса больше нечем (ПЕР-31).
     */
    suspend fun importInProgress(): Boolean

    suspend fun setImportInProgress(value: Boolean)
}

/**
 * Перепланирование напоминаний после загрузки (ПЕР-18, НАП-11).
 *
 * Реализация — `app`, поверх существующего запуска генерации: собственного планирования
 * перенос не делает.
 */
interface TransferReplanner {

    /**
     * @param archivedMedicationIds загруженные **архивированные** курсы.
     *
     * Полный обход планировщика архивированные курсы не посещает (`docs/archive/tasks/SKL-06/TDD.md §7`),
     * а «заменить всё» способно загрузить архивированный курс вместе с его ожидающимися
     * приёмами. Без отдельного обхода по этим записям человек получит напоминания
     * по курсу, который он архивировал (`docs/archive/tasks/SKL-06/TODO.md`, пункт 21).
     */
    suspend fun replanAfterTransfer(archivedMedicationIds: List<String>)
}
