package ru.stohastika.sklyanka.domain.privacy

/**
 * Память о том, что человек видел и принял политику конфиденциальности.
 *
 * Это не согласие на обработку: приложение ничего не собирает и никуда не передаёт
 * (Р-4, Р-86), а магазин требует явно предложить политику при первом запуске (7.5).
 * Поэтому хранится ровно один факт — предложение было и человек нажал «Принимаю».
 *
 * Состояния «показывать снова через N дней» здесь нет намеренно: политика не меняется
 * без новой сборки, а напоминание о прочитанном превратило бы первый запуск в анкету.
 */
interface PrivacyConsentStore {

    /** Принял ли человек политику на первом запуске. */
    suspend fun acknowledged(): Boolean

    /** Записать принятие: диалог первого запуска больше не показывается. */
    suspend fun acknowledge()
}
