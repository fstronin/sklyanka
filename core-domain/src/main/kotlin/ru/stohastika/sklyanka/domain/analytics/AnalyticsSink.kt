package ru.stohastika.sklyanka.domain.analytics

/**
 * Технический канал вендора, за которым стоит SDK (SKL-82).
 *
 * Порт [Analytics] решает, можно ли отправлять; sink только исполняет: активируется,
 * отправляет и выключается. Разделение даёт проверку «до согласия — ноль вызовов SDK»
 * на JVM с подменой sink — и в доменных тестах, и в сценарной приёмке.
 *
 * Реализация (Huawei Analytics Kit) живёт в `core-analytics`; здесь — только контракт,
 * чтобы правило гейта оставалось доменным и проверяемым без Android.
 */
interface AnalyticsSink {

    /** Активировать SDK. Вызывается только после согласия и никогда в debug. */
    suspend fun activate()

    /** Прекратить отправку. Выключение в настройках действует немедленно (ПМ-18). */
    suspend fun deactivate()

    /** Передать событие каталога. До активации сюда не попадает ни одного вызова. */
    fun send(event: AnalyticsEvent)
}
