package ru.stohastika.sklyanka.domain.model

/**
 * Форма выпуска лекарства (docs/norm/04-behavior.md §5).
 *
 * Значение хранится строкой — именем константы, а не порядковым номером:
 * номер ломается при вставке нового значения в середину списка и нечитаем
 * в файле переноса данных (МГ-6).
 */
enum class MedicationForm {
    TABLET,
    CAPSULE,
    SPRAY,
    SYRUP,
    DROPS,
    INJECTION,
    ;

    /**
     * Вид таблетки применим только к форме «Таблетка» (ПР-9, ИНВ-16, ОВ-88).
     *
     * У капсулы вида нет: её силуэт задан самой формой, подходящих вариантов среди пяти
     * не существует («круглой капсулы» не бывает).
     */
    val allowsShape: Boolean get() = this == TABLET
}
