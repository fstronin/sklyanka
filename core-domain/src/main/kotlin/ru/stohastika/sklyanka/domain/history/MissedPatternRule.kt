package ru.stohastika.sklyanka.domain.history

import java.time.LocalTime

/**
 * Строка-вывод: время приёма, на которое приходится наибольшая доля пропусков
 * (`TDD.md §5.4`).
 *
 * Это единственное место в продукте, где приложение обобщает за человека, и в текстовой
 * спецификации оно не описано вовсе — требование выведено из макета
 * (`docs/spec/03-screens.md`: «Строка вывода о самом пропускаемом приёме в текстовой
 * спеке не описана»).
 *
 * Отсюда два ограничения, которые являются частью дизайна, а не редактуры:
 *
 * 1. **Формулировка описательная.** Правило возвращает время, а текст берётся из шаблона
 *    в ресурсах: приложение не медицинское изделие (`CLAUDE.md`) и рекомендаций не даёт.
 *    Свободной генерации текста нет вовсе.
 * 2. **Лидер обязан быть явным.** Ложный вывод хуже отсутствующего, поэтому лидера мало
 *    просто «больше остальных»: он обязан собрать заметную долю пропусков, пропусков
 *    должно быть достаточно, чтобы говорить о закономерности, и сравнивать должно быть
 *    с чем.
 */
class MissedPatternRule(
    /**
     * Доля пропусков, начиная с которой время считается лидером.
     *
     * Строго больше половины: при равном распределении между двумя временами (6 и 6)
     * лидера нет, и это прямое требование сценария приёмки. 0,6 оставляет запас —
     * «7 против 5» закономерностью ещё не является. Значение требует подтверждения
     * заказчика (открытый вопрос 7 в `task.md`).
     */
    private val dominantShare: Double = DOMINANT_SHARE,
    /**
     * Меньше этого числа пропусков за период — вывода нет.
     *
     * Один пропуск за месяц даёт долю 100 % и «лидера» на шуме. Порог отвечает на
     * вопрос «есть ли вообще о чём говорить», и он отдельный от доли намеренно.
     */
    private val minimumMisses: Int = MINIMUM_MISSES,
) {

    /**
     * @param missesByTime пропуски периода, сгруппированные по времени приёма
     * @param scheduledTimes времена, которые в периоде вообще встречались
     * @return время самого пропускаемого приёма или `null`, если явного лидера нет
     */
    fun dominantMissedTime(missesByTime: Map<LocalTime, Int>, scheduledTimes: Set<LocalTime>): LocalTime? {
        val total = missesByTime.values.sum()
        val leader = missesByTime.maxByOrNull { it.value }
        val worthTelling =
            // Сравнивать не с чем: у лекарства одно время приёма в сутки, и «чаще всего
            // пропускается приём в 08:00» сообщает только то, что других приёмов нет.
            scheduledTimes.size >= MINIMUM_TIMES &&
                total >= minimumMisses &&
                // Два времени с одинаковым числом пропусков лидера не образуют, каким бы
                // большим это число ни было: «поровну» — отсутствие закономерности.
                leader != null &&
                missesByTime.count { it.value == leader.value } == 1
        return leader?.key?.takeIf { worthTelling && leader.value.toDouble() / total >= dominantShare }
    }

    /** Тот же вывод по готовой сводке периода: экрану считать нечего заново. */
    fun dominantMissedTime(period: AdherencePeriod): LocalTime? =
        dominantMissedTime(period.missesByTime, period.scheduledTimes)

    private companion object {
        const val DOMINANT_SHARE = 0.6
        const val MINIMUM_MISSES = 4
        const val MINIMUM_TIMES = 2
    }
}
