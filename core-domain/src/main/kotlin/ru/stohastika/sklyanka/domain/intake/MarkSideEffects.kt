package ru.stohastika.sklyanka.domain.intake

/**
 * Что приложение делает вслед за состоявшейся отметкой приёма.
 *
 * Заведено задачей SKL-13: отметка обязана снять полноэкранное напоминание и отозвать
 * парную карточку на часах (НАП-30, ЧАС-16). Место для этого одно — [MarkIntakeUseCase],
 * единственная точка отметки: отметку делают экран «Сегодня», карточка напоминания
 * и колбэк часов, и «закрывать уведомление» в каждом из трёх мест означало бы, что
 * четвёртое место об этом забудет.
 *
 * Значение по умолчанию — [None]: жизненный цикл приёма (SKL-07) не обязан знать
 * о существовании напоминаний, и его тесты собирают сценарий без подсистемы доставки.
 */
fun interface MarkSideEffects {

    /**
     * Приём больше не ожидается: он отмечен человеком, часами или замещающей отметкой.
     *
     * Вызывается **после** записи, вне транзакции: снятие уведомления не имеет права
     * откатить отметку (НФТ-10).
     */
    suspend fun onIntakeMarked(intakeId: String)

    companion object {
        val None: MarkSideEffects = MarkSideEffects { }
    }
}
