package ru.stohastika.sklyanka.domain.onboarding

import ru.stohastika.sklyanka.domain.reminder.ReminderWarning
import java.time.Instant

/**
 * Состояние одного шага цепочки.
 *
 * Иерархия намеренно несимметрична: разрешение Android и настройки EMUI — сущности разной
 * природы, и сведение их к одному типу «выдано / не выдано» породило бы ложно-зелёный
 * вендорский шаг (НАП-20, ПЛ-18, `TDD.md §5.2`). Ложно-зелёный шаг лишает человека
 * единственного шанса заметить проблему до того, как он пропустит приём, поэтому
 * невозможность такого состояния держится типом, а не дисциплиной вызова.
 */
sealed interface StepState {

    /**
     * Шаг пройден.
     *
     * У разрешения Android это «система ответила «выдано»»; у вендорской настройки —
     * «человек подтвердил, что настроил». Слова разные намеренно: приложение не проверяло
     * настройку EMUI и утверждать, что она настроена, не может (НАП-20).
     */
    val isResolved: Boolean
}

/**
 * Состояние разрешения Android: прочитано у системы при каждом показе (НФТ-52).
 *
 * Ровно два варианта, и это проверяется тестом: третий вариант здесь означал бы, что
 * приложение чего-то о разрешении не знает, — а о разрешении Android оно знает всё.
 */
sealed interface PermissionGrant : StepState {

    /**
     * Разрешение выдано; [readAt] — момент чтения.
     *
     * Момент хранится, а не выбрасывается, потому что «выдано» — это утверждение о прошлом
     * длиной в один показ экрана: разрешение отзывают в системных настройках, и диагностике
     * нужно видеть, насколько свежие данные на экране (`TDD.md §10`).
     */
    data class Granted(val readAt: Instant) : PermissionGrant {
        override val isResolved: Boolean get() = true
    }

    /**
     * Разрешение не выдано.
     *
     * [canAsk] — может ли приложение запросить его само, не отправляя человека в системные
     * настройки. Это свойство платформы, а не счётчик отказов: `POST_NOTIFICATIONS`
     * запрашивается диалогом только с Android 13 (ПЛ-13), а право на точные будильники
     * не запрашивается диалогом никогда — его выдают на экране особого доступа (ПЛ-14).
     * Подпись кнопки от этого не зависит: она задана макетом.
     */
    data class Denied(val canAsk: Boolean) : PermissionGrant {
        override val isResolved: Boolean get() = false
    }
}

/** Состояние отдельной настройки внутри шага «Уведомления», которую система читает булево. */
enum class PermissionGate {
    GRANTED,
    DENIED,
}

/**
 * Состояние шага «Уведомления»: три проверяемых состояния одной карточкой (ОВ-107).
 *
 * До этой задачи полноэкранное право и канал не читались на экране настройки, и причина
 * «карточка приёма не появится на заблокированном экране» не называлась нигде, кроме
 * диагностики. [issue] возвращает тип из `domain.reminder` — так слова на карточке, баннере
 * «Сегодня» и в диагностике берутся из одного перечисления и разойтись не могут.
 */
data class NotificationAccessState(
    val permission: PermissionGrant,
    val channel: PermissionGate,
    val fullScreenIntent: PermissionGate,
) : StepState {

    override val isResolved: Boolean
        get() = permission is PermissionGrant.Granted &&
            channel == PermissionGate.GRANTED &&
            fullScreenIntent == PermissionGate.GRANTED

    /**
     * Старшая проблема карточки — словами того же перечисления, что баннер и диагностика.
     *
     * Порядок тот же, что у баннера (ОВ-107): разрешение → канал → полноэкранные;
     * при невыданном разрешении канал не называется — он внутри разрешения.
     */
    val issue: ReminderWarning?
        get() = when {
            permission !is PermissionGrant.Granted -> ReminderWarning.NOTIFICATIONS_OFF
            channel == PermissionGate.DENIED -> ReminderWarning.NOTIFICATION_CHANNEL_OFF
            fullScreenIntent == PermissionGate.DENIED -> ReminderWarning.FULL_SCREEN_INTENT_OFF
            else -> null
        }
}

/**
 * Состояние вендорской настройки — запуск приложений, энергосбережение, закрепление в недавних.
 *
 * **Варианта «выдано» у этого типа нет и появиться не может** (НАП-20, ПЛ-18): состояние
 * фирменных ограничений не выставлено в публичный API, и ни один расчёт не вправе прийти
 * к выводу, что настройка точно настроена. Единственное, что может измениться, —
 * [confirmedByUser]: человек сам сказал, что прошёл по пути, названному инструкцией.
 *
 * [hints] — косвенные признаки. Они существуют, чтобы показать человеку то, что известно,
 * и подписаны на экране как косвенные. Подменять факт настройки они не имеют права:
 * снятая оптимизация батареи — другая настройка, а не ручной запуск приложений на EMUI,
 * HyperOS или One UI.
 */
data class ManualStepState(val confirmedByUser: Boolean, val hints: Set<ManualStepHint> = emptySet()) : StepState {

    /** Пройденным шаг делает подтверждение человека — и только оно (критерий приёмки 4). */
    override val isResolved: Boolean get() = confirmedByUser

    /**
     * Проверено ли состояние системой. Всегда нет — это и есть НАП-20.
     *
     * Свойство существует, чтобы утверждение было записано в коде, а не только в комментарии:
     * вендорскому шагу неоткуда стать зелёным самому.
     */
    val verifiedBySystem: Boolean get() = false
}

/**
 * Косвенный признак снятой оптимизации батареи (НАП-20).
 *
 * Единственный признак относится к шагу «Энергосбережение»: его предмет — оптимизация
 * батареи Android, а не ручной запуск приложений вендора. Перечисление, а не булево поле:
 * признак, который забыли показать, не должен выглядеть как «признаков нет».
 */
enum class ManualStepHint {
    /**
     * Приложение исключено из оптимизации батареи (`isIgnoringBatteryOptimizations`).
     *
     * Косвенный признак: это стандартная настройка Android, а список ручного управления
     * запуском EMUI — фирменная, и одна не следует из другой.
     */
    BATTERY_OPTIMIZATION_IGNORED,
}
