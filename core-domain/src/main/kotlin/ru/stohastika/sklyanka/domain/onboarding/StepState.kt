package ru.stohastika.sklyanka.domain.onboarding

import java.time.Instant

/**
 * Состояние одного шага цепочки.
 *
 * Иерархия намеренно несимметрична: разрешение Android и автозапуск EMUI — сущности разной
 * природы, и сведение их к одному типу «выдано / не выдано» породило бы ложно-зелёный третий
 * шаг (НАП-20, ПЛ-18, `TDD.md §5.1`). Ложно-зелёный шаг лишает человека единственного шанса
 * заметить проблему до того, как он пропустит приём, поэтому невозможность такого состояния
 * держится типом, а не дисциплиной вызова.
 */
sealed interface StepState {

    /**
     * Шаг пройден.
     *
     * У разрешения Android это «система ответила «выдано»»; у автозапуска — «человек
     * подтвердил, что настроил». Слова разные намеренно: приложение не проверяло автозапуск
     * и утверждать, что он настроен, не может (НАП-20).
     */
    val isResolved: Boolean
}

/**
 * Состояние разрешения Android: прочитано у системы при каждом показе (НФТ-52).
 *
 * Ровно два варианта, и это проверяется тестом: третий вариант здесь означал бы, что
 * приложение чего-то о разрешении не знает, — а о разрешении Android оно знает всё.
 */
sealed interface PermissionGrant : StepState {

    /**
     * Разрешение выдано; [readAt] — момент чтения.
     *
     * Момент хранится, а не выбрасывается, потому что «выдано» — это утверждение о прошлом
     * длиной в один показ экрана: разрешение отзывают в системных настройках, и диагностике
     * нужно видеть, насколько свежие данные на экране (`TDD.md §10`).
     */
    data class Granted(val readAt: Instant) : PermissionGrant {
        override val isResolved: Boolean get() = true
    }

    /**
     * Разрешение не выдано.
     *
     * [canAsk] — может ли приложение запросить его само, не отправляя человека в системные
     * настройки. Это свойство платформы, а не счётчик отказов: `POST_NOTIFICATIONS`
     * запрашивается диалогом только с Android 13 (ПЛ-13), а право на точные будильники
     * не запрашивается диалогом никогда — его выдают на экране особого доступа (ПЛ-14).
     * Подпись кнопки от этого не зависит: она задана макетом.
     */
    data class Denied(val canAsk: Boolean) : PermissionGrant {
        override val isResolved: Boolean get() = false
    }
}

/**
 * Состояние автозапуска и ограничений энергосбережения EMUI.
 *
 * **Варианта «выдано» у этого типа нет и появиться не может** (НАП-20, ПЛ-18): состояние
 * фирменных ограничений не выставлено в публичный API, и ни один расчёт не вправе прийти
 * к выводу, что автозапуск точно настроен. Единственное, что может измениться, —
 * [confirmedByUser]: человек сам сказал, что прошёл по пути «Настройки → Батарея →
 * Запуск приложений → Склянка → вручную».
 *
 * [hints] — косвенные признаки. Они существуют, чтобы показать человеку то, что известно,
 * и подписаны на экране как косвенные. Подменять факт настройки они не имеют права:
 * снятая оптимизация батареи — другая настройка, а дошедшее пробное напоминание говорит
 * о прошлом срабатывании, а не о состоянии устройства.
 */
data class AutostartState(val confirmedByUser: Boolean, val hints: Set<AutostartHint> = emptySet()) : StepState {

    /** Пройденным шаг делает подтверждение человека — и только оно (критерий приёмки 7). */
    override val isResolved: Boolean get() = confirmedByUser

    /**
     * Проверено ли состояние системой. Всегда нет — это и есть НАП-20.
     *
     * Свойство существует, чтобы утверждение было записано в коде, а не только в комментарии:
     * экран показывает по нему строку «проверить это может только пробное напоминание»,
     * и строка не исчезнет от того, что признаков стало больше.
     */
    val verifiedBySystem: Boolean get() = false
}

/**
 * Косвенный признак настроенного автозапуска (НАП-20).
 *
 * Перечисление, а не булевы поля: признак, который забыли показать, не должен выглядеть
 * как «признаков нет», и каждый признак подписывается на экране своими словами.
 */
enum class AutostartHint {
    /**
     * Приложение исключено из оптимизации батареи (`isIgnoringBatteryOptimizations`).
     *
     * Косвенный признак: это стандартная настройка Android, а список ручного управления
     * запуском EMUI — фирменная, и одна не следует из другой.
     */
    BATTERY_OPTIMIZATION_IGNORED,

    /**
     * Пробное напоминание дошло — и дошло недавно (`TDD.md §10`).
     *
     * Самый сильный из косвенных признаков и всё равно косвенный: он говорит, что цепочка
     * работала в тот момент, а не что она настроена сегодня. Поэтому у него есть срок
     * давности — [ReadPermissionChecklistUseCase.TEST_REMINDER_HINT_MAX_AGE].
     */
    TEST_REMINDER_DELIVERED,
}
