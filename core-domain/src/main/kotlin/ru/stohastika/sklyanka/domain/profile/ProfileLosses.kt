package ru.stohastika.sklyanka.domain.profile

import kotlinx.coroutines.flow.Flow

/**
 * Числа потерь профиля: что экран подтверждения обещает стереть (SKL-36).
 *
 * [medications] — все лекарства профиля, активные и архивные; [archived] — из них
 * архивные; [intakes] — все записи приёмов профиля. Отдельного учёта приложение
 * не ведёт: это те же множества, что показывает список лекарств и история.
 */
data class ProfileLosses(val medications: Int, val archived: Int, val intakes: Int)

/**
 * Поток чисел потерь — теми же запросами, что список лекарств и историю профиля.
 *
 * Лекарства считает выборка списка (активные и архивные), записи истории — соединение
 * приёмов с лекарствами профиля; второй семантики «сколько их» не заводится.
 *
 * Поток, а не разовое чтение: экран подтверждения остаётся открытым и во время
 * системного выбора места выгрузки, и число обязано не разойтись с тем, что
 * действительно будет стёрто.
 */
fun interface ProfileLossesSource {

    fun observe(profileId: String): Flow<ProfileLosses>
}
