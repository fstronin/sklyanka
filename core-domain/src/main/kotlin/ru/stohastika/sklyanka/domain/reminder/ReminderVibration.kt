package ru.stohastika.sklyanka.domain.reminder

/**
 * Замороженные осциллограммы вибрации каналов напоминаний (НАП-24, ПМ-11).
 *
 * Формат — как у Android `NotificationChannel.vibrationPattern`: чередование
 * длительностей «пауза, удар, пауза, удар, …» в миллисекундах, первое значение — 0.
 *
 * Паттерны — часть совместимости, как идентификаторы каналов (ADR-0004): после публикации
 * приложения сменить их у пользователей нельзя, потому что параметры канала неизменяемы
 * после создания (ПЛ-10). Менять значения — только осознанным решением об изменении канала,
 * а не «заодно»; тест на неизменность обязан упасть.
 */
object ReminderVibration {

    /** Обычный канал: два удара по 350 мс с паузой 250 мс, около 0,95 с. */
    val REGULAR: LongArray = longArrayOf(0, 350, 250, 350)

    /** Настойчивый: тот же ритм — пауза 250 мс, — но удары по 700 мс и третий повтор, около 2,6 с. */
    val PERSISTENT: LongArray = longArrayOf(0, 700, 250, 700, 250, 700)

    /**
     * Паттерн канала.
     *
     * Возвращается копия: вызывающий не должен суметь изменить замороженное значение.
     */
    fun of(channel: ReminderChannel): LongArray = when (channel) {
        ReminderChannel.REGULAR -> REGULAR.copyOf()
        ReminderChannel.PERSISTENT -> PERSISTENT.copyOf()
    }
}
