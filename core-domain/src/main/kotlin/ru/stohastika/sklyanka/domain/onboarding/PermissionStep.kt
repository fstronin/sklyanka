package ru.stohastika.sklyanka.domain.onboarding

/**
 * Три шага онбординга разрешений в фиксированном порядке (НАП-19, ПЛ-18).
 *
 * Перечисление, а не список в состоянии экрана: порядок задан требованием, а не вёрсткой
 * (`design/screens/Onboarding.dc.html`), и экран, собравший шаги в другом порядке, нарушил бы
 * НАП-19 молча. Порядок объявления и есть порядок показа.
 */
enum class PermissionStep {
    /** Уведомления: без них напоминание планируется, срабатывает и не показывается (ПЛ-13). */
    NOTIFICATIONS,

    /** Точные будильники: без них Android сдвигает срабатывание (ПЛ-14, ПЛ-15, НАП-16). */
    EXACT_ALARMS,

    /**
     * Автозапуск и снятие ограничений энергосбережения EMUI.
     *
     * Не разрешение Android вовсе: нигде не объявляется, из кода не запрашивается
     * и программно не читается (НАП-20, ПЛ-18). Поэтому его состояние выражается
     * отдельным типом — [AutostartState], у которого нет варианта «выдано».
     */
    AUTOSTART,
}

/**
 * Откуда человек пришёл на экран разрешений.
 *
 * Нужно журналу (`TDD.md §11.1`): жалоба «приложение каждый раз просит разрешения»
 * разбирается по источнику, а не по факту показа. Заодно источник решает, показывать ли
 * индикатор шагов: при входе из настроек его нет (критерий приёмки 15).
 */
enum class OnboardingSource {
    /** Первый запуск: цепочка идёт как часть онбординга. */
    FIRST_LAUNCH,

    /** Пункт «Разрешения и автозапуск» из настроек (НАП-21). */
    SETTINGS,

    /** Предупреждение на экране «Сегодня» (НАП-21). */
    TODAY_WARNING,
    ;

    /** Индикатор шагов принадлежит онбордингу, а не экрану (критерий приёмки 15). */
    val showsStepIndicator: Boolean get() = this == FIRST_LAUNCH
}
