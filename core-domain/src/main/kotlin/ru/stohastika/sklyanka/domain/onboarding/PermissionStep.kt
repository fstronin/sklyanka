package ru.stohastika.sklyanka.domain.onboarding

/**
 * Шаги цепочки надёжности в фиксированном порядке (НАП-19, ПЛ-18, ОВ-106).
 *
 * Перечисление, а не список в состоянии экрана: порядок задан требованием, а не вёрсткой,
 * и экран, собравший шаги в другом порядке, нарушил бы НАП-19 молча. Порядок объявления
 * и есть порядок показа.
 *
 * Состав зависит от прошивки: [APP_STARTUP], [BATTERY_SAVING] и [RECENTS_PIN] — вендорские
 * настройки, и у каждого профиля свой их набор ([VendorSteps.of], [PermissionChecklist.steps]);
 * на незнакомой прошивке они не показываются вовсе.
 */
enum class PermissionStep {
    /** Уведомления: без них напоминание планируется, срабатывает и не показывается (ПЛ-13). */
    NOTIFICATIONS,

    /** Точные будильники: без них Android сдвигает срабатывание (ПЛ-14, ПЛ-15, НАП-16). */
    EXACT_ALARMS,

    /**
     * Запуск приложений: автозапуск, косвенный запуск и работа в фоне (ПЛ-18, НАП-20).
     *
     * На EMUI шаг зовётся «Запуск приложений», на HyperOS/MIUI — «Автозапуск»: слова даёт
     * профиль, предмет один. Не разрешение Android вовсе: нигде не объявляется, из кода
     * не запрашивается и программно не читается. Поэтому его состояние выражается отдельным
     * типом — [ManualStepState], у которого нет варианта «выдано».
     */
    APP_STARTUP,

    /** Энергосбережение: снятие ограничений фоновой работы («Не ограничивать») — условие доставки (ПЛ-6). */
    BATTERY_SAVING,

    /** Закрепление в недавних: удерживает карточку приложения от выгрузки (ПЛ-6). */
    RECENTS_PIN,
    ;

    /**
     * Читает ли состояние шага система.
     *
     * У общих разрешений Android состояние читается и называется словами; у вендорских
     * настроек — нет, и подтверждать их может только человек (НАП-20). Свойство живёт
     * на шаге, чтобы экран не перечислял вендорские шаги поименно.
     */
    val verifiedBySystem: Boolean
        get() = this == NOTIFICATIONS || this == EXACT_ALARMS
}

/**
 * Откуда человек пришёл на экран «Настроить надёжность».
 *
 * Нужно журналу (`TDD.md §11`): жалоба «приложение каждый раз просит разрешения»
 * разбирается по источнику, а не по факту показа. Заодно источник решает, показывать ли
 * индикатор шагов и куда прокрутить список: при входе из настроек индикатора нет
 * (критерий приёмки 13), а баннеры ведут к первому незакрытому шагу (ОВ-107).
 */
enum class OnboardingSource {
    /** Первый запуск: цепочка идёт как часть онбординга. */
    FIRST_LAUNCH,

    /** Пункт «Разрешения и автозапуск» из настроек (НАП-21). */
    SETTINGS,

    /** Предупреждение на экране «Сегодня» (НАП-21). */
    TODAY_WARNING,

    /** Сообщение о перерыве при входе (НАП-38, ОВ-107). */
    OUTAGE_BANNER,
    ;

    /** Индикатор шагов принадлежит онбордингу, а не экрану (критерий приёмки 13). */
    val showsStepIndicator: Boolean get() = this == FIRST_LAUNCH

    /** Входы, где экран прокручивается к первому незакрытому шагу (ОВ-107). */
    val focusesFirstUnresolved: Boolean get() = this == TODAY_WARNING || this == OUTAGE_BANNER
}
