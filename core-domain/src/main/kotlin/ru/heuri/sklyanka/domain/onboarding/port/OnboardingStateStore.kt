package ru.heuri.sklyanka.domain.onboarding.port

import ru.heuri.sklyanka.domain.onboarding.PermissionStep

/**
 * Единственное, что об онбординге сохраняется (НФТ-52, `TDD.md §4`).
 *
 * Состояния разрешений здесь нет и быть не может: сохранённый флаг «разрешение выдано»
 * описывает прошлое и устаревает ровно в тот момент, когда человек отозвал разрешение
 * в системных настройках, — то есть именно тогда, когда правда нужна. Состояние разрешений
 * читается из системы при каждом показе экрана.
 *
 * Сохраняются два факта, которых в системе нет вовсе:
 * - человек уже видел экран разрешений (прошёл или пропустил) — НАП-21;
 * - человек подтвердил, что настроил автозапуск EMUI — НАП-20. Это исключение не из правила
 *   «читать, а не помнить», а из невозможности чтения: состояние автозапуска не выставлено
 *   в публичный API, и подтверждение человека — единственное, что об этом шаге вообще есть.
 */
interface OnboardingStateStore {

    /** Видел ли человек экран разрешений. Разницы «прошёл» и «пропустил» здесь нет намеренно. */
    suspend fun seen(): Boolean

    /** Отметить, что экран показан: со следующего запуска онбординг сам не открывается. */
    suspend fun markSeen()

    /** Подтвердил ли человек, что настроил автозапуск (НАП-20). */
    suspend fun autostartConfirmed(): Boolean

    /** Записать подтверждение человека — или снять его, если он передумал. */
    suspend fun setAutostartConfirmed(confirmed: Boolean)
}

/**
 * Косвенные признаки настроенного автозапуска (НАП-20).
 *
 * Отдельный порт, а не поле [ru.heuri.sklyanka.domain.reminder.port.PermissionStateReader]:
 * «оптимизация батареи снята» — не разрешение и в таблицу НАП-15 не входит. Смешав их,
 * диагностика получила бы строку «Оптимизация батареи: выдано», то есть ровно то
 * ложно-зелёное утверждение, которого задача не допускает.
 */
interface AutostartHintReader {

    /**
     * Исключено ли приложение из оптимизации батареи Android.
     *
     * Косвенный признак и не более: список ручного управления запуском EMUI — фирменная
     * настройка, и из снятой оптимизации батареи она не следует.
     */
    fun batteryOptimizationIgnored(): Boolean
}

/**
 * Что из цепочки приложение вправе запросить системным диалогом (ПЛ-13, ПЛ-14).
 *
 * Свойство платформы, а не счётчик отказов: `POST_NOTIFICATIONS` запрашивается диалогом
 * только с Android 13, а право на точные будильники не запрашивается диалогом никогда —
 * его выдают на экране особого доступа. Читается снаружи домена, потому что ответ зависит
 * от версии системы, а домен версий системы не знает (НФТ-46).
 */
interface PermissionRequestSupport {

    /** Можно ли получить разрешение шага системным диалогом, не уводя человека в настройки. */
    fun canRequestFromCode(step: PermissionStep): Boolean
}
