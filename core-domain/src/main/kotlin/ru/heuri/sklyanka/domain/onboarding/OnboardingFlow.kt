package ru.heuri.sklyanka.domain.onboarding

/**
 * Место экрана разрешений в онбординге — то, что показывает индикатор шагов.
 *
 * Числа взяты из макета и только из него (`design/screens/Onboarding.dc.html`): три полоски,
 * две залиты акцентом, то есть экран разрешений — **второй из трёх**. Третий шаг известен —
 * это подключение часов (`design/screens/WatchSetup.dc.html`, SKL-17). Первый в макетах
 * не нарисован и в спецификации не назван (ОВ-51).
 *
 * Индикатор рисуется ровно таким, каким он в макете, и приложение не придумывает первый шаг,
 * чтобы индикатор «сошёлся»: придуманный экран приветствия был бы решением за дизайн, а
 * подделанный индикатор (две полоски вместо трёх) — правкой макета. Пока ответа нет, человек
 * на первом запуске видит второй шаг из трёх — и это честное отражение состояния постановки.
 */
object OnboardingFlow {

    /** Всего шагов в онбординге по макету. */
    const val TOTAL_STEPS: Int = 3

    /** Номер шага «Разрешения»: второй из трёх, две полоски из трёх залиты. */
    const val PERMISSIONS_STEP: Int = 2
}
