package ru.heuri.sklyanka.domain.profile

/**
 * Перепланирование, вызванное изменением **состава** профилей (ПРФ-6, ПРФ-30, НАП-12).
 *
 * Порт, а не прямая зависимость на пересборку окна будильников: домен профилей не обязан
 * знать ни о будильниках, ни о том, что перед ними идёт генерация приёмов — этот порядок
 * держит `app`.
 *
 * Поводов ровно три: профиль заведён, профиль скрыт, переключено дублирование напоминаний.
 * **Смена активного профиля в этот список не входит** и никогда не войдёт: состав
 * будильников определяется свойствами профилей, а не тем, какой экран открыт (НАП-12).
 * Путаница здесь стоит дорого в обе стороны — лишнее перепланирование при каждом
 * переключении шумит в журнале, а забытое при смене флага оставляет человека без
 * напоминаний до следующего якорного будильника.
 *
 * Значение по умолчанию — [None]: правила профилей проверяются на JVM без подсистемы
 * доставки.
 */
fun interface ProfileSetReplanner {

    suspend fun onProfileSetChanged()

    companion object {
        val None: ProfileSetReplanner = ProfileSetReplanner { }
    }
}
