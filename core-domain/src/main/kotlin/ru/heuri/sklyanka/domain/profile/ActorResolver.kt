package ru.heuri.sklyanka.domain.profile

import ru.heuri.sklyanka.domain.model.IntakeSource

/**
 * Кто поставил отметку, если это был не владелец профиля лекарства (ПР-12, ПРФ-14).
 *
 * Три `null` из четырёх ветвей содержательны, а не означают «нечего записать»:
 * подпись «отметили вы» появляется ровно тогда, когда владелец телефона своей рукой
 * отметил чужой приём.
 *
 * Отдельный объект, а не приватный метод сценария отметки: правило одно и то же для
 * обычной отметки, отметки по потребности и отметки, пришедшей с часов, а три копии
 * одного правила расходятся на первой же правке — и расходятся молча, потому что
 * подпись в истории никто не сверяет с источником отметки.
 */
object ActorResolver {

    /**
     * @param intakeProfileId профиль приёма — он же профиль его лекарства (ПР-10)
     * @param source чем поставлена отметка
     * @param selfProfileId профиль владельца телефона; `null` до первого запуска
     * @return профиль исполнителя либо `null`, если подпись не нужна
     */
    fun actorFor(intakeProfileId: String, source: IntakeSource, selfProfileId: String?): String? = when {
        // До создания профиля владельца отмечать некому: подписывать нечем.
        selfProfileId == null -> null

        // На часах экрана профиля нет, и нажавший мог быть самим подопечным (ПРФ-22).
        // Выдать такую отметку за отметку владельца — это ровно та ложь в истории,
        // от которой защищает вся задача.
        source == IntakeSource.WATCH -> null

        // Автоперевод в «пропущено» никем не поставлен (ПР-1): исполнителя у него нет.
        source == IntakeSource.AUTO -> null

        // Своё — без подписи: в истории своего профиля она бессмысленна (ПРФ-14).
        intakeProfileId == selfProfileId -> null

        else -> selfProfileId
    }
}
