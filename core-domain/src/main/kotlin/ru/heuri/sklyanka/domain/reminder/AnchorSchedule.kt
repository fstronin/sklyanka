package ru.heuri.sklyanka.domain.reminder

import java.time.Instant
import java.time.LocalTime
import java.time.ZoneId

/**
 * Якорный будильник перепланирования (НАП-8).
 *
 * Последняя линия обороны: если за сутки не сработало ни одного напоминания, приложение
 * не открывали, расписание не правили и устройство не перезагружали, окно пересобирать
 * некому. Якорь пересобирает его сам.
 *
 * Час выбран ночной и не круглый: в 03:17 система не разбирает очередь будильников всех
 * приложений, поставленных «на три ночи». Время локальное, поэтому при смене пояса якорь
 * пересчитывается вместе с окном (`TDD.md §10`).
 */
object AnchorSchedule {

    /** Ночной час малой нагрузки в локальном времени. */
    val AT: LocalTime = LocalTime.of(3, 17)

    /**
     * Ближайший якорь строго после [now].
     *
     * Строго: якорь, поставленный на момент «сейчас», сработал бы немедленно и пересобрал
     * бы окно второй раз подряд, ничего не изменив.
     */
    fun next(now: Instant, zone: ZoneId): Instant {
        val local = now.atZone(zone)
        val today = local.toLocalDate().atTime(AT).atZone(zone)
        val anchor = if (today.toInstant().isAfter(now)) today else today.plusDays(1)
        return anchor.toInstant()
    }
}

/**
 * Будильник границы суток (НАП-34, ПР-1).
 *
 * Проход по просроченным приёмам выполняется не только при открытии приложения и при
 * пересборке окна: пока телефон включён и приложение не открывают, неотмеченный приём
 * обязан стать пропущенным ровно в полночь, а его карточка — исчезнуть из шторки.
 * Иначе человек утром видит уведомление о вчерашнем приёме и отмечает его задним числом.
 *
 * Полночь берётся календарём профиля, а не вычитанием суток из момента: в сутках
 * с переводом времени их 23 или 25 (НФТ-37).
 */
object DayBoundarySchedule {

    fun next(now: Instant, zone: ZoneId): Instant =
        now.atZone(zone).toLocalDate().plusDays(1).atStartOfDay(zone).toInstant()
}
