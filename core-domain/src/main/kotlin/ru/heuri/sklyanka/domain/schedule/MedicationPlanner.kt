package ru.heuri.sklyanka.domain.schedule

/**
 * Перепланирование приёмов одного лекарства — порт наружу.
 *
 * Зачем порт, если [PlanIntakesUseCase] лежит в том же модуле. Точка запуска генерации
 * собрана в `app` (`IntakePlanningTrigger`): она держит обязательный порядок «сначала
 * перевод просроченных приёмов, потом генерация окна» (НАП-34) и добавляет постановку
 * будильников, когда та появится (SKL-13). Домен не имеет права видеть `app`, поэтому
 * архивация и возврат из архива зовут не сам use-case генерации, а этот порт: подстановка
 * делается в графе, а на JVM подставляется запись вызовов.
 */
fun interface MedicationPlanner {

    /** @return итог генерации по этому лекарству: сколько приёмов создано и сколько снято. */
    suspend fun plan(medicationId: String, reason: PlanReason): PlanResult
}
