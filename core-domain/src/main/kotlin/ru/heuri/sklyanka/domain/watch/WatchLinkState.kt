package ru.heuri.sklyanka.domain.watch

/**
 * Состояние связи с часами, каким его показывает строка настроек (ЧАС-18).
 *
 * Тип перечисляет состояния, а не хранит «подключено да/нет»: «часы не настроены» и «часы
 * настроены, но сейчас недоступны» — разные утверждения, и человеку, у которого карточка
 * не дошла до часов, важно ровно это различие. Ни одно состояние не является ошибкой
 * и ни одно не блокирует приложение: приём отмечается на телефоне (ЧАС-19).
 *
 * Название модели — строка, пришедшая от системы часов, а не текст интерфейса: подставить
 * её в подпись обязан экран, и формат подписи живёт в `strings.xml` (НФТ-42).
 */
sealed interface WatchLinkState {

    /** Часы на связи. [model] — то, как их называет сама система («GT 6 Pro»). */
    data class Connected(val model: String) : WatchLinkState

    /** Часы подключены к телефону ранее, сейчас недоступны: выключены, вне связи, Bluetooth снят. */
    data object NotConnected : WatchLinkState

    /** Связка не настроена вовсе — штатное состояние, а не отказ (ЧАС-14). */
    data object NotConfigured : WatchLinkState
}

/**
 * Чтение состояния связи с часами.
 *
 * Читается из системы при каждом показе экрана, а не запоминается флагом: часы выключают
 * и снимают Bluetooth мимо приложения, и сохранённая подпись «подключены» — ложь ровно
 * в том месте, ради которого строка существует (НФТ-52).
 *
 * Цепочка проверок Wear Engine — SKL-17; порт заведён здесь, потому что подпись строки
 * настроек нужна раньше, чем интеграция.
 */
interface WatchLinkStateReader {

    suspend fun read(): WatchLinkState
}
