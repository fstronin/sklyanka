package ru.heuri.sklyanka.domain

/**
 * Транзакционная точка входа хранилища.
 *
 * Нужна двум сценариям, которые нельзя выполнить наполовину: отметка приёма со списанием
 * остатка (НФТ-11) и замена всех данных при переносе (ПЕР-27). Отказ на любом шаге
 * оставляет исходное состояние, а не половину загруженного.
 */
interface Transactor {
    suspend fun <T> inTransaction(block: suspend () -> T): T
}
