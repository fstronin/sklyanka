package ru.heuri.sklyanka.domain.schedule

/**
 * Настройки генерации приёмов — то, что решает заказчик, а не разработчик.
 *
 * Оба параметра вынесены сюда по одной причине: они относятся к открытым вопросам
 * (`docs/tasks/SKL-06/task.md`, «Открытые вопросы»), и смена решения обязана быть правкой
 * одного значения, а не переписыванием планировщика.
 */
data class IntakeGenerationPolicy(

    /**
     * Глубина окна генерации в сутках, считая текущие (ОВ-8).
     *
     * Рабочее значение — семь суток; обоснование в `task.md`, «Горизонт генерации».
     */
    val windowDepthDays: Int,

    /**
     * Порождать ли приёмы, чьё время сегодня уже прошло.
     *
     * Значение по умолчанию — не порождать: запись, созданная задним числом, занижает
     * приверженность за приём, о котором человека никто не предупреждал (`task.md`,
     * «День начала курса»; `TDD.md §5.3`). Противоположное решение защитимо и вынесено
     * заказчику, поэтому оно параметр, а не `if` внутри разворачивания.
     *
     * Отличить «лекарство только что завели» от «курс начался сегодня» домен не может:
     * момента создания у лекарства в модели данных нет (`docs/spec/02-data-model.md` §3),
     * поэтому правило сформулировано в терминах суток, а не события.
     */
    val skipPastTimesToday: Boolean = true,
) {
    init {
        require(windowDepthDays >= GenerationWindow.MIN_DEPTH_DAYS) {
            "Generation window must cover the 48 hour alarm window: depth=$windowDepthDays"
        }
    }
}
