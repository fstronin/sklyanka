package ru.heuri.sklyanka.domain.time

import java.time.Instant
import java.time.ZoneId

/**
 * Единственный разрешённый источник текущего времени и часового пояса.
 *
 * Прямые обращения к системным часам запрещены правилом DirectSystemClockAccess (НФТ-48).
 * Причина не в чистоте: окно приёма, переход pending → missed, полуночная граница,
 * конец курса и смена часового пояса иначе непроверяемы, а ошибка в них стоит
 * пропущенного приёма.
 *
 * Реализация поверх системных часов живёт вне домена и подставляется через Hilt;
 * в тестах подставляется управляемая реализация [FixedTimeSource].
 */
interface TimeSource {
    /** Текущий момент в UTC. Моменты времени (acted_at, журнал) хранятся в UTC. */
    fun now(): Instant

    /**
     * Часовой пояс профиля.
     *
     * Расписание приёмов — локальное время человека: приём «в 08:00» остаётся
     * в 08:00 после перелёта, поэтому пояс нужен отдельно от момента.
     */
    fun zone(): ZoneId
}
