package ru.heuri.sklyanka.domain.repository

import kotlinx.coroutines.flow.Flow
import ru.heuri.sklyanka.domain.history.HistorySlice
import ru.heuri.sklyanka.domain.history.HistoryWindow

/**
 * Данные истории приёмов за период.
 *
 * Отдельный порт рядом с [IntakeRepository] и [MedicationRepository], а не новые методы
 * у них: история — **единственное** место приложения, где выборка лекарств идёт без
 * фильтра архива (ПР-11). Метод, у которого это написано в названии и в документации,
 * не «починят для единообразия» с экранами «Сегодня» и «Лекарства», где фильтр
 * обязателен.
 *
 * Профиль остаётся обязательным параметром (ПР-10): запроса, возвращающего историю
 * нескольких профилей сразу, в приложении не существует — не «не используется»,
 * а отсутствует в интерфейсе.
 */
interface HistoryRepository {

    /**
     * Приёмы периода вместе с лекарствами профиля и датой первой записи истории.
     *
     * Одним потоком, а не тремя: сводка, посчитанная из данных, приехавших вразнобой,
     * показала бы приёмы одного месяца рядом с лекарствами другого профиля.
     */
    fun observe(profileId: String, window: HistoryWindow): Flow<HistorySlice>
}
