package ru.heuri.sklyanka.domain.history

import java.time.LocalDateTime

/**
 * Доля приёмов, отмеченных в своё окно, — плитка «принято вовремя».
 *
 * Тип, а не число, потому что числа может не быть: порог «вовремя» нигде не задан и
 * смыкается с границей окна перехода «ожидается → пропущено» (ПР-1, ОВ-4). Плитка,
 * показывающая выдуманное число, — это число, которое человек покажет врачу.
 */
sealed interface OnTimeShare {

    /** Доля от нуля до единицы, посчитанная по согласованному правилу. */
    data class Value(val share: Double) : OnTimeShare {

        val percent: Int get() = Math.round(share * PERCENT).toInt()

        private companion object {
            const val PERCENT = 100
        }
    }

    /**
     * Доля не определена — плитка показывает прочерк.
     *
     * Это проектное решение, а не заглушка (`TDD.md §5.2`). Причина конкретна:
     * по ОВ-4 выбрана граница окна «до конца суток» ([ru.heuri.sklyanka.domain.intake]
     * `EndOfDayIntakeWindow`), и при ней «вовремя» совпадает с «принято» — приём,
     * отмеченный в 23:50 вместо 08:00, попадает в своё окно. Метрика вырождается в долю
     * отмеченных, то есть перестаёт отличаться от приверженности и сообщает врачу не то,
     * что обещает подписью. Пока порог не согласован отдельно от окна, доли нет.
     */
    data object Undefined : OnTimeShare
}

/**
 * Порог «вовремя» — параметр предметной области, а не константа в коде.
 *
 * Требование `docs/spec/02-data-model.md` §7 к окну приёма действует и здесь: «окно
 * должно быть параметром домена, а не константой в коде, чтобы решение можно было
 * заменить без переделки». Расчёт приверженности спрашивает правило и не знает,
 * чему равна граница.
 *
 * **НАП-2 здесь неприменим.** Он определяет «вовремя» для срабатывания напоминания
 * (отклонение от 0 до +120 секунд) — там опаздывает приложение, здесь человек. Совпадение
 * слова в двух смыслах — ловушка, поэтому у этих понятий и имена разные: `ReminderDelay`
 * живёт в подсистеме напоминаний, а порог отметки — здесь.
 */
sealed interface OnTimeRule {

    /**
     * Порог не согласован (ОВ-4): доля «принято вовремя» не считается вовсе.
     *
     * Значение, зарегистрированное в графе приложения. Когда заказчик ответит,
     * меняется одна строка сборки — расчёт не переделывается.
     */
    data object NotAgreed : OnTimeRule

    /**
     * Согласованный порог: приём «вовремя», если отмечен не позже границы своего окна.
     *
     * Оба момента — местные: назначенное время хранится локальным (НФТ-34), а момент
     * отметки переводится в местное время ровно здесь и больше нигде.
     */
    fun interface Agreed : OnTimeRule {
        fun isOnTime(scheduledAt: LocalDateTime, actedAt: LocalDateTime): Boolean
    }
}
