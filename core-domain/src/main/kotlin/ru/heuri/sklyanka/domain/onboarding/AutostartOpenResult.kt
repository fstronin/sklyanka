package ru.heuri.sklyanka.domain.onboarding

/**
 * Чем закончилась попытка открыть экран автозапуска производителя (ПЛ-18).
 *
 * Интент этого экрана нестандартен и различается между прошивками
 * (`docs/spec/01-platform.md` §6), поэтому «открылось» — не единственный исход и не
 * исключительная ситуация. Запасной путь обязателен: именно он отрабатывает на всех
 * неэталонных прошивках, то есть у большинства людей.
 */
enum class AutostartOpenResult {
    /** Системный раздел управления запуском приложений открылся. */
    OPENED,

    /**
     * Ни один известный интент не разрешился — показывается текстовая инструкция.
     *
     * Инструкция не «сообщение об ошибке», а рабочий путь: названия пунктов меню человек
     * найдёт в системных настройках сам (критерий приёмки 6).
     */
    FALLBACK_TO_INSTRUCTIONS,
}

/** Как человек ушёл с экрана разрешений (НАП-21, `TDD.md §9.3`). */
enum class OnboardingOutcome {
    /** «Дальше»: цепочка пройдена, следующий шаг онбординга — подключение часов (SKL-17). */
    NEXT,

    /** «Пропустить, настрою позже»: легальный путь, а не ошибка. */
    SKIPPED,
}
